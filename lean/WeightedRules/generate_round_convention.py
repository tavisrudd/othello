"""Render the Lean/Rust round-convention checks from the producer's fixture family.

Input: the fixture files under ``fixtures/round-convention/`` written by the
producer's ``lean_boundary_fixtures`` generator. Output: one Lean module per
domain size under ``RoundConvention/``. Every table in the fixtures is read by
the Lean elaborator itself through ``nat_table_from_json``; this script only
writes the declarations and the decidable statements around those reads, and
copies no numbers except the round counts that the statements name.

Run from the Lean package root:

    python3 WeightedRules/generate_round_convention.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
FIXTURES = ROOT / "fixtures" / "round-convention"
OUTPUT = ROOT / "RoundConvention"
NUMBER_WORDS = {3: "Three", 4: "Four", 5: "Five", 6: "Six"}

HEADER = """import WeightedRules.TableProgram
import WeightedRules.IncrementalReflection
import WeightedRules.OutputConvergence

/-!
# Round conventions on domain {domain}: producer against synchronous iterate

Generated by `generate_round_convention.py` from `{fixture}`, itself written by
the producer's `lean_boundary_fixtures` generator. Every source has domain
{domain}, one binary input relation `edge`, one unary derived relation `dist`
with the rule `dist(y) :- dist(x), edge(x, y)`, and the fact `dist(0) = 0`; the
grounding has {scalars} scalar coordinates. All tables are read from the fixture
file by the elaborator; nothing numeric is transcribed here except the round
counts named in the statements.

For each case, kernel reduction establishes three facts about the producer's
numbers. First, the round count returned with the from-zero certificate is the
least index at which the synchronous iterate from the zero valuation equals
the certified values: the certificate is accepted at that count and rejected at
the preceding one. Second, the sweep count returned by the producer's
incremental update from the held solution is the least replay count at which
the warm iterate from the old values equals the new values, and it lies within
the rule-output bound. Third, three single mutations of each certificate, a
unit perturbation of one finite coordinate, a swap of two distinct values and
a dropped entry, are rejected by the same checker.
-/

namespace WeightedRules.RoundConvention

set_option maxRecDepth 32768
set_option maxHeartbeats 4000000

"""

TABLE = 'nat_table_from_json "../fixtures/round-convention/{file}" at [{keys}]'


def table(file, *keys):
    return TABLE.format(file=file, keys=", ".join(f'"{k}"' for k in keys))


def render_case(word, n, file, name, case):
    rounds = case["certificate"]["rounds"]
    sweeps = case["improvement"]["sweeps"]
    p = f"program{word}{name[4:]}"
    q = f"improved{word}{name[4:]}"
    v = f"values{word}{name[4:]}"
    w = f"improvedValues{word}{name[4:]}"
    lines = [
        f"/-- Case `{name}`: the producer's grounding of the base source. -/",
        f"def {p} : Program Cost {n} := programOfTables {n}",
        f"  ({table(file, 'cases', name, 'grounding', 'inputs')})",
        f"  ({table(file, 'cases', name, 'grounding', 'products')})",
        "",
        f"/-- Case `{name}`: the certified from-zero values. -/",
        f"def {v} : List Cost := costList",
        f"  ({table(file, 'cases', name, 'certificate', 'values')})",
        "",
        f"example : checkCertificate {p} {rounds} {v} = true := by decide +kernel",
    ]
    if rounds > 0:
        lines.append(
            f"example : checkCertificate {p} {rounds - 1} {v} = false := by decide +kernel")
    lines += [
        "",
        f"/-- Case `{name}`: the producer's grounding of the improved source. -/",
        f"def {q} : Program Cost {n} := programOfTables {n}",
        f"  ({table(file, 'cases', name, 'improvement', 'grounding', 'inputs')})",
        f"  ({table(file, 'cases', name, 'improvement', 'grounding', 'products')})",
        "",
        f"/-- Case `{name}`: the values after the incremental update. -/",
        f"def {w} : List Cost := costList",
        f"  ({table(file, 'cases', name, 'improvement', 'values')})",
        "",
        f"example : checkImprovementCertificate {p} {q} {v} {sweeps} {w} = true := by",
        "  decide +kernel",
    ]
    if sweeps > 0:
        lines += [
            f"example : checkImprovementCertificate {p} {q} {v} {sweeps - 1} {w} = false := by",
            "  decide +kernel",
        ]
    lines.append(f"example : {sweeps} ≤ ruleOutputBound {q} := by decide +kernel")
    for kind in sorted(case["rejected"]):
        lines += [
            "",
            f"example : checkCertificate {p} {rounds}",
            f"    (costList ({table(file, 'cases', name, 'rejected', kind)})) = false := by",
            "  decide +kernel",
        ]
    lines.append("")
    return "\n".join(lines)


def main():
    OUTPUT.mkdir(exist_ok=True)
    for path in sorted(FIXTURES.glob("domain-*.json")):
        document = json.loads(path.read_text())
        domain = document["domain"]
        word = NUMBER_WORDS[domain]
        cases = document["cases"]
        scalars = {c["grounding"]["scalar_count"] for c in cases.values()}
        assert len(scalars) == 1, "one coordinate count per domain"
        n = scalars.pop()
        body = HEADER.format(domain=domain, fixture=path.name, scalars=n)
        body += "\n".join(render_case(word, n, path.name, name, case)
                          for name, case in cases.items())
        body += "\nend WeightedRules.RoundConvention\n"
        target = OUTPUT / f"Domain{word}.lean"
        target.write_text(body)
        print(target.relative_to(ROOT))


if __name__ == "__main__":
    main()
