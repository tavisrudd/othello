#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Generate one-group Q11 A5 point-action certificate leaves."""

from __future__ import annotations
import argparse
import re
from pathlib import Path

Q, POINT_COUNT, GROUP_COUNT, BLOCK = 11, 133, 60, 5
LEAN_ROOT = Path(__file__).resolve().parents[1]
RCA = LEAN_ROOT / "RelativeConicArcs"
DATA = RCA / "Q11A5PointOrbitsData.lean"


def matrices() -> list[list[int]]:
    text = DATA.read_text()
    text = text[text.index("def matrixCode"):text.index("def supportPerm")]
    rows = [[int(x) for x in re.findall(r"\d+", row)]
            for row in re.findall(r"!\[([0-9,\s]+)\]", text)]
    assert len(rows) == 60 and all(len(row) == 9 for row in rows)
    return rows


def points() -> list[tuple[int, int, int]]:
    return ([(1, i // Q, i % Q) for i in range(Q * Q)]
            + [(0, 1, z) for z in range(Q)] + [(0, 0, 1)])


def normalize(v: tuple[int, int, int]) -> tuple[int, int, int]:
    for x in v:
        if x:
            inverse = pow(x, -1, Q)
            return tuple(y * inverse % Q for y in v)
    raise AssertionError("matrix sent a projective point to zero")


def point_index(v: tuple[int, int, int]) -> int:
    if v[0]:
        return v[1] * Q + v[2]
    if v[1]:
        return Q * Q + v[2]
    return POINT_COUNT - 1


def action_table(matrix: list[int]) -> list[int]:
    result = []
    for point in points():
        image = tuple(sum(matrix[3*r+c] * point[c] for c in range(3)) % Q
                      for r in range(3))
        result.append(point_index(normalize(image)))
    assert sorted(result) == list(range(POINT_COUNT))
    return result


def landed_table(group: int) -> list[int]:
    path = RCA / f"Q11A5PointOrbitsRowsG{group:02d}.lean"
    text = path.read_text()
    match = re.search(
        rf"def pointActionCode_{group} .*? :=\s*!\[(.*?)\]\s*p",
        text, re.DOTALL)
    assert match is not None
    values = [int(x) for x in re.findall(r"\d+", match.group(1))]
    assert len(values) == POINT_COUNT
    expected_payload = "\n" + table_text(values) + "\n  "
    assert match.group(1) == expected_payload, f"noncanonical table bytes in group {group}"
    return values


def table_text(values: list[int]) -> str:
    return ",\n".join(
        "    " + ", ".join(map(str, values[start:start+12]))
        for start in range(0, len(values), 12))


def leaf(group: int, values: list[int]) -> str:
    return f"""import RelativeConicArcs.Q11A5PointOrbitsArithmetic

/-!
# Generated arithmetic row {group} for the Q11 A5 point action

Generated by lean/scripts/generate-q11-a5-point-action.py; do not edit by hand.
-/

namespace RelativeConicArcs.Examples.Q11A5PointOrbits

set_option maxHeartbeats 100000000
set_option maxRecDepth 100000

private instance : Fact (Nat.Prime 11) := ⟨by decide⟩

theorem action_on_witness_row_{group} :
    ∀ i : Fin 6, pointAction {group} (witnessIndex i) = witnessIndex (supportPerm {group} i) := by
  intro i
  rw [pointAction_eq_fast]
  revert i
  decide

def pointActionCode_{group} (p : PointIndex) : PointIndex :=
  ![
{table_text(values)}
  ] p

theorem pointAction_eq_code_{group} :
    ∀ p : PointIndex, pointAction {group} p = pointActionCode_{group} p := by
  intro p
  rw [pointAction_eq_fast]
  revert p
  decide

theorem orbitIndex_code_{group} :
    ∀ p : PointIndex, orbitIndex (pointActionCode_{group} p) = orbitIndex p := by
  decide

theorem orbitIndex_pointAction_row_{group} :
    ∀ p : PointIndex, orbitIndex (pointAction {group} p) = orbitIndex p := by
  intro p
  rw [pointAction_eq_code_{group} p]
  exact orbitIndex_code_{group} p

end RelativeConicArcs.Examples.Q11A5PointOrbits
"""


def aggregator(block: int) -> str:
    first = block * BLOCK
    imports = "\n".join(
        f"import RelativeConicArcs.Q11A5PointOrbitsRowsG{g:02d}"
        for g in range(first, first + BLOCK))
    return f"""{imports}

/-!
# Arithmetic rows {first}--{first + BLOCK - 1} for the Q11 A5 point action

Generated by lean/scripts/generate-q11-a5-point-action.py.  This compatibility
module is intentionally proof-free; every group row is compiled in its own leaf.
-/
"""


def put(path: Path, content: str, check: bool) -> None:
    if check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"generated file is stale: {path}")
    else:
        path.write_text(content)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    tables = [action_table(matrix) for matrix in matrices()]

    for group in range(5):
        old = landed_table(group)
        assert tables[group] == old, f"landed table mismatch in group {group}"

    for group in range(5, GROUP_COUNT):
        put(RCA / f"Q11A5PointOrbitsRowsG{group:02d}.lean",
            leaf(group, tables[group]), args.check)
    for block in range(1, GROUP_COUNT // BLOCK):
        put(RCA / f"Q11A5PointOrbitsRows{block:02d}.lean",
            aggregator(block), args.check)

    mode = "verified" if args.check else "generated"
    print(f"{mode} groups 5--59 after exact groups 0--4 cross-check")


if __name__ == "__main__":
    main()
