#!/usr/bin/env python3
"""Locate every generated Lean certificate family across all working roots.

The boundary checker guards one repository.  A certificate family can also
survive as a stale copy in a paper mirror, a dependency checkout, a backup
working tree, or a build directory, where nothing checks it and nothing rebuilds
it.  This audit sweeps the roots as a whole and reports where generated families
live, so that each one can be classified as official payload, declared pending
work, or a shadow to remove.

It reads file contents only.  It runs no Lean, takes no lock, and writes nothing.
"""

from __future__ import annotations

import argparse
import collections
import re
import subprocess
from pathlib import Path


# Kept identical to the boundary checker's rule: a do-not-edit marker, or
# "generated by" followed by something that looks like a script name in
# backticks.  The path-or-extension requirement is what separates a real banner
# from prose about a subgroup generated by `g`.
BANNER = r"DO NOT EDIT|automatically generated|generated by[ \t]+`[^`]*[./][^`]*`"
# Build outputs and version-control internals are not sources; a certificate
# family hiding in one is reported by path, not by walking the whole tree.
SKIP = {".git", ".lake", "build", ".cache", "node_modules"}


def generated_files(root: Path) -> list[Path]:
    result = subprocess.run(
        ["rg", "-l", "-i", "--no-messages", BANNER, "-g", "*.lean", str(root)],
        capture_output=True,
        text=True,
    )
    files = []
    for line in result.stdout.splitlines():
        path = Path(line)
        if not any(part in SKIP for part in path.parts):
            files.append(path)
    return files


def family_of(root: Path, path: Path) -> str:
    """A family is the directory holding the generated leaves."""
    relative = path.relative_to(root)
    return str(relative.parent)


def generator_references(root: Path) -> collections.Counter[str]:
    """Count the generators that this root's generated sources name.

    Generated Lean leaves are half of a family.  The other half — the generator, the
    replay program, the data the replay reads — is not Lean, carries no banner of its
    own, and is found only through the banner that names it.
    """
    result = subprocess.run(
        [
            "rg", "-o", "-i", "--no-messages", "-r", "$1",
            r"generated by[ \t]+`([^`]*[./][^`]*?)`",
            "-g", "*.lean", str(root),
        ],
        capture_output=True,
        text=True,
    )
    references: collections.Counter[str] = collections.Counter()
    for line in result.stdout.splitlines():
        _, _, reference = line.partition(".lean:")
        if reference and not any(part in SKIP for part in Path(line).parts):
            references[reference] += 1
    return references


def resolution(root: Path, reference: str) -> str:
    """Say whether the named generator is actually here, and where.

    A banner names its generator the way its author ran it: repository-relative,
    package-relative, or as a bare basename meaning "beside the family".  Reporting
    an unresolved reference as absent would call every bare basename a missing
    generator, so the basename is searched for as well.
    """
    if (root / reference).is_file():
        return f"resident: {reference}"
    matches = [
        path
        for path in root.rglob(Path(reference).name)
        if path.is_file()
        and not any(part in SKIP for part in path.parts)
        # A reference carrying a directory means that directory: matching its
        # basename anywhere would resolve `verification/.../generate.py` to any
        # `generate.py` in the tree, a vendored dependency included.
        and str(path).endswith(reference)
    ]
    if matches:
        return f"resident: {min(matches).relative_to(root)}"
    return "not in this root"


def stale_build_artifacts(root: Path) -> dict[str, tuple[int, int]]:
    """Build outputs whose Lean source no longer exists in this root.

    Deleting an extracted family's sources does not delete what building them left
    behind.  The residue is invisible to every source-level rule, it is the largest
    thing on disk that no longer belongs to anything, and until a build window can
    remove it the sweep must at least name it.  A root may hold the build directly or
    one level down, as this repository does with `lean/`, so both are swept.
    """
    stale: dict[str, tuple[int, int]] = {}
    for build in sorted(root.glob("*/.lake/build")) + sorted(root.glob(".lake/build")):
        collect_stale_artifacts(build, stale)
    return stale


def collect_stale_artifacts(build: Path, stale: dict[str, tuple[int, int]]) -> None:
    package_root = build.parent.parent
    # A package may keep its modules at the package root or under a source directory
    # the lakefile names, so the source is recognized by the path it ends with rather
    # than by one assumed prefix.  Getting this wrong reports every module in a
    # correctly built package as stale.
    sources: set[str] = set()
    for path in package_root.rglob("*.lean"):
        if any(part in SKIP for part in path.parts):
            continue
        relative = path.relative_to(package_root)
        sources.add(relative.as_posix())
        if len(relative.parts) > 1:
            sources.add(Path(*relative.parts[1:]).as_posix())
    # Lake puts a module's outputs at a path that mirrors its source path, under
    # `lib/lean/` for compiled artifacts and `ir/` for generated C.  Stripping that
    # prefix recovers the source the artifact came from, which is what makes the
    # match exact rather than a name coincidence.
    for area, strip in (("lib/lean", 2), ("ir", 1)):
        for path in (build / area).rglob("*"):
            if not path.is_file():
                continue
            relative = path.relative_to(build).parts[strip:]
            if not relative:
                continue
            module = Path(*relative)
            stem = module.name.split(".")[0]
            wanted = (module.parent / f"{stem}.lean").as_posix()
            if wanted in sources:
                continue
            name = str(Path(package_root.name) / module.parent / stem)
            count, size = stale.get(name, (0, 0))
            # Blocks, not apparent size: the question a sweep of build residue has to
            # answer is what removing it would free.
            stale[name] = (count + 1, size + path.stat().st_blocks * 512)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "roots", type=Path, nargs="+", help="working roots to sweep"
    )
    parser.add_argument(
        "--min-family",
        type=int,
        default=1,
        help="only report families holding at least this many generated files",
    )
    parser.add_argument(
        "--payload",
        action="store_true",
        help="also report the non-Lean payload each root's banners name",
    )
    parser.add_argument(
        "--build-artifacts",
        action="store_true",
        help="also report build outputs whose Lean source no longer exists",
    )
    args = parser.parse_args()

    total = 0
    for root in args.roots:
        root = root.resolve()
        if not root.is_dir():
            print(f"{root}: absent")
            continue
        if args.payload:
            references = generator_references(root)
            if references:
                print(f"{root.name}: generators named by its generated sources")
                for reference, uses in references.most_common():
                    print(f"    {uses:6d}  {reference}  [{resolution(root, reference)}]")
            else:
                print(f"{root.name}: no generator named by any generated source")
        if args.build_artifacts:
            stale = stale_build_artifacts(root)
            if stale:
                files = sum(count for count, _ in stale.values())
                size = sum(size for _, size in stale.values())
                print(
                    f"{root.name}: {len(stale)} built modules with no source"
                    f" — {files} files, {size / 1e6:.1f} MB"
                )
                for module, (count, module_size) in sorted(
                    stale.items(), key=lambda item: -item[1][1]
                )[:5]:
                    print(f"    {module_size / 1e6:8.1f} MB  {count:4d}  {module}")
            else:
                print(f"{root.name}: no built module without a source")
        families: collections.Counter[str] = collections.Counter()
        for path in generated_files(root):
            families[family_of(root, path)] += 1
        count = sum(families.values())
        total += count
        if not count:
            print(f"{root.name}: no generated Lean source")
            continue
        print(f"{root.name}: {count} generated Lean files in {len(families)} families")
        for family, size in families.most_common():
            if size >= args.min_family:
                print(f"    {size:6d}  {family}")
    print(f"total generated Lean files across all roots: {total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
