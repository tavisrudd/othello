#!/usr/bin/env python3
"""Independent replay of the C1028 chain-ring instrument test.

Deliberately independent of the Rust driver in two ways:

  * lines of ``PHG(2,R)`` are built as spans of pairs of non-neighbouring
    points (free rank-two submodules by generation), not as kernels of
    unimodular linear forms;
  * the arc search and the code enumeration are written from scratch here.

Checks, all against the published ground truth in
Honold-Kiermaier-Landjev, arXiv:2409.02099v1, Table 3, and the classical
octacode / Nordstrom-Robinson landmarks:

  * plane parameters: 28 points, 28 lines, 6 points per line, 7 neighbour
    classes of size 4, and lines-as-spans equal lines-as-kernels;
  * ``m_2(Z4) = 7`` and ``m_2(S2) = 6``, with the count of maximum arcs;
  * ``m_3(Z4) = m_3(S2) = 10``;
  * the Gray image of the code of a maximal 2-arc in ``PHG(2,Z4)`` is a
    ``(14, 2^6, 6)`` non-linear binary code;
  * the extended cyclic length-eight ``Z4`` code generated by the Hensel lift
    ``x^3 + 2x^2 + x + 3`` of ``x^3 + x + 1`` is the octacode, with Gray image
    the ``(16, 256, 6)`` Nordstrom-Robinson code.

Replay:  python3 ergodis-private/python/check_c1028_chain_ring.py
"""

from __future__ import annotations

import itertools
import json
import sys
from typing import Callable

# --- chain-ring arithmetic, encoded as a + 2b -------------------------------


def z4_add(x: int, y: int) -> int:
    return (x + y) & 3


def z4_mul(x: int, y: int) -> int:
    return (x * y) & 3


def s2_add(x: int, y: int) -> int:
    return x ^ y


def s2_mul(x: int, y: int) -> int:
    a0, a1 = x & 1, x >> 1
    b0, b1 = y & 1, y >> 1
    return (a0 & b0) | ((((a0 & b1) ^ (a1 & b0)) & 1) << 1)


RINGS = {"Z4": (z4_add, z4_mul), "S2": (s2_add, s2_mul)}
HOM_WEIGHT = (0, 1, 2, 1)
GRAY = (0b00, 0b01, 0b11, 0b10)


def is_unit(x: int) -> bool:
    return x & 1 == 1


class Plane:
    """PHG(2,R) with lines built by generation, not by duality."""

    def __init__(self, add: Callable[[int, int], int], mul: Callable[[int, int], int]):
        self.add, self.mul = add, mul
        vectors = [(a, b, c) for a in range(4) for b in range(4) for c in range(4)]
        self.points: list[tuple[int, int, int]] = []
        self.index: dict[tuple[int, int, int], int] = {}
        for v in vectors:
            if not any(is_unit(e) for e in v):
                continue
            pivot = next(i for i in range(3) if is_unit(v[i]))
            scale = v[pivot]  # both units are self-inverse in both rings
            rep = tuple(mul(e, scale) for e in v)
            if rep not in self.index:
                self.index[rep] = len(self.points)
                self.points.append(rep)
            self.index[v] = self.index[rep]

        # Lines by generation: the span of two non-neighbouring points.
        spans: set[frozenset[int]] = set()
        for i, j in itertools.combinations(range(len(self.points)), 2):
            u, w = self.points[i], self.points[j]
            if all((u[k] & 1) == (w[k] & 1) for k in range(3)):
                continue  # neighbours: they do not span a free rank-two module
            members = set()
            for s in range(4):
                for t in range(4):
                    vec = tuple(add(mul(s, u[k]), mul(t, w[k])) for k in range(3))
                    if any(is_unit(e) for e in vec):
                        members.add(self.index[vec])
            spans.add(frozenset(members))
        self.lines = sorted(sorted(s) for s in spans)

        # Lines by duality, for the cross-check.
        dual = set()
        for lam in self.points:
            members = frozenset(
                p
                for p, v in enumerate(self.points)
                if self._dot(lam, v) == 0
            )
            dual.add(members)
        self.dual_lines = sorted(sorted(s) for s in dual)

        self.point_lines = [0] * len(self.points)
        self.line_masks = []
        for li, line in enumerate(self.lines):
            mask = 0
            for p in line:
                mask |= 1 << p
                self.point_lines[p] |= 1 << li
            self.line_masks.append(mask)

    def _dot(self, a, b) -> int:
        total = 0
        for k in range(3):
            total = self.add(total, self.mul(a[k], b[k]))
        return total


def max_arc(plane: Plane, bound: int) -> tuple[int, int]:
    """Largest (k, bound)-arc and the number of maximum arcs."""
    n = len(plane.points)
    nlines = len(plane.lines)
    best = 0
    counts = [0] * nlines

    def search(start: int, size: int) -> None:
        nonlocal best
        if size > best:
            best = size
        if size + (n - start) <= best:
            return
        for p in range(start, n):
            if size + (n - p) <= best:
                return
            lines = plane.point_lines[p]
            touched = []
            ok = True
            m = lines
            while m:
                low = m & -m
                li = low.bit_length() - 1
                m ^= low
                if counts[li] == bound:
                    ok = False
                    break
                touched.append(li)
            if not ok:
                continue
            for li in touched:
                counts[li] += 1
            search(p + 1, size + 1)
            for li in touched:
                counts[li] -= 1

    search(0, 0)

    found = 0
    target = best

    def collect(start: int, size: int) -> None:
        nonlocal found
        if size == target:
            found += 1
            return
        if size + (n - start) < target:
            return
        for p in range(start, n):
            if size + (n - p) < target:
                return
            lines = plane.point_lines[p]
            touched = []
            ok = True
            m = lines
            while m:
                low = m & -m
                li = low.bit_length() - 1
                m ^= low
                if counts[li] == bound:
                    ok = False
                    break
                touched.append(li)
            if not ok:
                continue
            for li in touched:
                counts[li] += 1
            collect(p + 1, size + 1)
            for li in touched:
                counts[li] -= 1

    collect(0, 0)
    return best, found


def first_max_arc(plane: Plane, bound: int, size: int) -> list[int]:
    n = len(plane.points)
    counts = [0] * len(plane.lines)
    chosen: list[int] = []

    def search(start: int) -> bool:
        if len(chosen) == size:
            return True
        if len(chosen) + (n - start) < size:
            return False
        for p in range(start, n):
            lines = plane.point_lines[p]
            touched = []
            ok = True
            m = lines
            while m:
                low = m & -m
                li = low.bit_length() - 1
                m ^= low
                if counts[li] == bound:
                    ok = False
                    break
                touched.append(li)
            if not ok:
                continue
            for li in touched:
                counts[li] += 1
            chosen.append(p)
            if search(p + 1):
                return True
            chosen.pop()
            for li in touched:
                counts[li] -= 1
        return False

    search(0)
    return chosen


def gray_parameters(add, mul, words: list[tuple[int, ...]]) -> tuple[int, int, int, bool]:
    images = sorted({
        sum(GRAY[e] << (2 * i) for i, e in enumerate(w)) for w in words
    })
    length = 2 * len(words[0])
    distance = min(
        bin(a ^ b).count("1") for a, b in itertools.combinations(images, 2)
    )
    image_set = set(images)
    linear = all((a ^ b) in image_set for a in images for b in images)
    return length, len(images), distance, linear


def arc_code(plane: Plane, arc: list[int]) -> list[tuple[int, ...]]:
    columns = [plane.points[p] for p in arc]
    words = []
    for a in itertools.product(range(4), repeat=3):
        word = []
        for col in columns:
            total = 0
            for j in range(3):
                total = plane.add(total, plane.mul(a[j], col[j]))
            word.append(total)
        words.append(tuple(word))
    return words


def octacode(add, mul, g: tuple[int, int, int, int]) -> list[tuple[int, ...]]:
    words = []
    for a in itertools.product(range(4), repeat=4):
        c = [0] * 8
        for i, ai in enumerate(a):
            for j, gj in enumerate(g):
                c[i + j] = add(c[i + j], mul(ai, gj))
        total = 0
        for e in c[:7]:
            total = add(total, e)
        # additive inverse of the running sum
        c[7] = next(x for x in range(4) if add(total, x) == 0)
        words.append(tuple(c))
    return words


def divides_x7_minus_1(add, mul, g: tuple[int, int, int, int]) -> bool:
    rem = [0] * 8
    rem[0] = next(x for x in range(4) if add(1, x) == 0)
    rem[7] = 1
    for power in range(7, 2, -1):
        lead = rem[power]
        if lead == 0:
            continue
        shift = power - 3
        for i in range(4):
            product = mul(lead, g[i])
            negated = next(x for x in range(4) if add(product, x) == 0)
            rem[shift + i] = add(rem[shift + i], negated)
    return all(c == 0 for c in rem[:3])


PUBLISHED = {
    "m_2": {"Z4": 7, "S2": 6},
    "m_3": {"Z4": 10, "S2": 10},
    "hyperoval_gray": (14, 64, 6, False),
    "octacode_gray": (16, 256, 6, False),
}


def main() -> int:
    results: dict[str, object] = {}
    failures: list[str] = []
    for name, (add, mul) in RINGS.items():
        plane = Plane(add, mul)
        entry: dict[str, object] = {
            "points": len(plane.points),
            "lines": len(plane.lines),
            "line_sizes": sorted({len(l) for l in plane.lines}),
            "spans_equal_kernels": plane.lines == plane.dual_lines,
        }
        classes = {}
        for p in plane.points:
            classes.setdefault(tuple(e & 1 for e in p), []).append(p)
        entry["neighbour_classes"] = len(classes)
        entry["neighbour_class_sizes"] = sorted({len(v) for v in classes.values()})

        if len(plane.points) != 28 or len(plane.lines) != 28:
            failures.append(f"{name}: plane has {len(plane.points)} points, {len(plane.lines)} lines")
        if not entry["spans_equal_kernels"]:
            failures.append(f"{name}: lines-as-spans differ from lines-as-kernels")

        for bound in (2, 3):
            best, count = max_arc(plane, bound)
            entry[f"m_{bound}"] = best
            entry[f"maximum_{bound}_arcs"] = count
            if best != PUBLISHED[f"m_{bound}"][name]:
                failures.append(
                    f"{name}: m_{bound} = {best}, published {PUBLISHED[f'm_{bound}'][name]}"
                )

        arc = first_max_arc(plane, 2, entry["m_2"])
        params = gray_parameters(add, mul, arc_code(plane, arc))
        entry["hyperoval_gray_image"] = params
        if name == "Z4" and params != PUBLISHED["hyperoval_gray"]:
            failures.append(f"Z4 hyperoval Gray image {params}, published (14, 64, 6, non-linear)")

        lifts = [
            g + (1,)
            for g in itertools.product(range(4), repeat=3)
            if divides_x7_minus_1(add, mul, g + (1,))
        ]
        entry["monic_cubic_divisors_of_x7_minus_1"] = lifts
        entry["extended_cyclic_gray_images"] = [
            gray_parameters(add, mul, octacode(add, mul, g)) for g in lifts
        ]
        if name == "Z4":
            hensel = (3, 1, 2, 1)  # 3 + x + 2x^2 + x^3
            if hensel not in lifts:
                failures.append("Z4: x^3 + 2x^2 + x + 3 does not divide x^7 - 1")
            else:
                params = gray_parameters(add, mul, octacode(add, mul, hensel))
                entry["octacode_gray_image"] = params
                if params != PUBLISHED["octacode_gray"]:
                    failures.append(f"Z4 octacode Gray image {params}, published (16, 256, 6, non-linear)")
        results[name] = entry

    print(json.dumps(results, indent=1, default=list))
    if failures:
        print("MISMATCHES:", file=sys.stderr)
        for line in failures:
            print("  " + line, file=sys.stderr)
        return 1
    print("all published cells reproduced")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
