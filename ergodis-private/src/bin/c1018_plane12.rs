//! C1018 (gem-mining): proof-carrying elimination of restricted cases for a
//! hypothetical projective plane of order 12.
//!
//! Subcommands
//!   multiplier  numerical-multiplier orbit certificate for a planar (v,k,1)
//!               difference set (the point-regular / Singer case)
//!   sidon       exhaustive backtracking search for planar difference sets in
//!               Z_v, independent of the multiplier theorem
//!   orbit13     exhaustive search of the orbit matrices of a collineation of
//!               order 13 (= n+1) of a plane of order n = 12
//!   starter     exhaustive enumeration of Z_m starters, i.e. of the
//!               cyclic one-factorizations of K_{m+1} forced on an external
//!               line of a hyperoval invariant under the order-13 collineation
//!
//! Every subcommand writes a JSON certificate; the Hall tests use the exact
//! bipartite matcher `ergodis_private::hall_core`, whose deficient-set output is
//! the elimination witness.

use std::fs::{self, File};
use std::io::BufWriter;
use std::path::PathBuf;

use anyhow::Result;
use clap::{Parser, Subcommand};
use ergodis_private::hall_core::{HallOutcome, HallWorkspace};
use serde::Serialize;

#[derive(Parser)]
#[command(about = "restricted order-12 projective-plane eliminations")]
struct Arguments {
    #[arg(long)]
    out: PathBuf,
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Multiplier-orbit certificate for a planar (v, k, 1) difference set.
    Multiplier {
        #[arg(long, default_value_t = 157)]
        v: u64,
        #[arg(long, default_value_t = 13)]
        k: u64,
    },
    /// Exhaustive planar-difference-set search in Z_v (translation-normalized).
    Sidon {
        #[arg(long, default_value_t = 157)]
        v: usize,
        #[arg(long, default_value_t = 13)]
        k: usize,
    },
    /// Orbit matrices of an order-(n+1) collineation of a plane of order n.
    Orbit13 {
        #[arg(long, default_value_t = 12)]
        n: usize,
        /// Stop after this many solutions (0 = exhaustive).
        #[arg(long, default_value_t = 0)]
        cap: usize,
    },
    /// Exhaustive enumeration of starters in Z_m.
    Starter {
        #[arg(long, default_value_t = 13)]
        m: usize,
    },
}

fn main() -> Result<()> {
    let args = Arguments::parse();
    if let Some(parent) = args.out.parent() {
        fs::create_dir_all(parent)?;
    }
    let value = match args.command {
        Command::Multiplier { v, k } => serde_json::to_value(multiplier_certificate(v, k))?,
        Command::Sidon { v, k } => serde_json::to_value(sidon_search(v, k))?,
        Command::Orbit13 { n, cap } => serde_json::to_value(orbit_matrix_search(n, cap))?,
        Command::Starter { m } => serde_json::to_value(starter_search(m))?,
    };
    let writer = BufWriter::new(File::create(&args.out)?);
    serde_json::to_writer_pretty(writer, &value)?;
    println!("{}", serde_json::to_string(&value)?);
    Ok(())
}

// ---------------------------------------------------------------- multiplier

#[derive(Serialize)]
struct MultiplierCertificate {
    schema: &'static str,
    v: u64,
    k: u64,
    n: u64,
    multiplier_primes: Vec<u64>,
    multiplier_orders: Vec<u64>,
    group_order: usize,
    orbit_sizes: Vec<usize>,
    representable: bool,
    verdict: &'static str,
}

fn mul_order(a: u64, v: u64) -> u64 {
    let mut x = a % v;
    let mut order = 1u64;
    while x != 1 {
        x = (x * (a % v)) % v;
        order += 1;
    }
    order
}

fn prime_divisors(mut n: u64) -> Vec<u64> {
    let mut out = Vec::new();
    let mut p = 2;
    while p * p <= n {
        if n % p == 0 {
            out.push(p);
            while n % p == 0 {
                n /= p;
            }
        }
        p += 1;
    }
    if n > 1 {
        out.push(n);
    }
    out
}

fn gcd(a: u64, b: u64) -> u64 {
    if b == 0 {
        a
    } else {
        gcd(b, a % b)
    }
}

fn multiplier_certificate(v: u64, k: u64) -> MultiplierCertificate {
    let n = k - 1;
    let primes: Vec<u64> = prime_divisors(n)
        .into_iter()
        .filter(|p| gcd(*p, v) == 1)
        .collect();
    let orders: Vec<u64> = primes.iter().map(|p| mul_order(*p, v)).collect();

    // Subgroup of (Z/v)^* generated by the numerical multipliers.
    let mut group = vec![1u64];
    let mut changed = true;
    while changed {
        changed = false;
        let snapshot = group.clone();
        for g in &snapshot {
            for p in &primes {
                let x = (g * p) % v;
                if !group.contains(&x) {
                    group.push(x);
                    changed = true;
                }
            }
        }
    }

    // Orbits of the multiplier group acting on Z_v by multiplication.
    let mut seen = vec![false; v as usize];
    let mut orbit_sizes = Vec::new();
    for x in 0..v {
        if seen[x as usize] {
            continue;
        }
        let mut size = 0usize;
        for g in &group {
            let y = ((g % v) * (x % v)) % v;
            if !seen[y as usize] {
                seen[y as usize] = true;
                size += 1;
            }
        }
        orbit_sizes.push(size);
    }

    // A multiplier-fixed difference set is a union of orbits, so k must be a
    // subset sum of the orbit sizes.
    let target = k as usize;
    let mut reach = vec![false; target + 1];
    reach[0] = true;
    for size in &orbit_sizes {
        for t in (*size..=target).rev() {
            if reach[t - size] {
                reach[t] = true;
            }
        }
    }
    let representable = reach[target];

    MultiplierCertificate {
        schema: "c1018.plane12.multiplier.v1",
        v,
        k,
        n,
        multiplier_primes: primes,
        multiplier_orders: orders,
        group_order: group.len(),
        orbit_sizes,
        representable,
        verdict: if representable {
            "multiplier test inconclusive"
        } else {
            "eliminated: k is not a sum of multiplier-orbit sizes"
        },
    }
}

// --------------------------------------------------------------------- sidon

#[derive(Serialize)]
struct SidonCertificate {
    schema: &'static str,
    v: usize,
    k: usize,
    normalization: &'static str,
    nodes: u64,
    solutions: usize,
    examples: Vec<Vec<usize>>,
    hall_verified: usize,
    hall_failures: usize,
    verdict: String,
}

/// Independent Hall check that `set` is a planar difference set in Z_v:
/// left = unordered pairs of `set`, right = difference classes {d, v-d}.
/// A saturating matching exists exactly when every class is hit once.
fn hall_difference_check(set: &[usize], v: usize, ws: &mut HallWorkspace) -> HallOutcome {
    let k = set.len();
    let left = k * (k - 1) / 2;
    let right = (v - 1) / 2;
    let mut offsets = Vec::with_capacity(left + 1);
    let mut neighbors = Vec::with_capacity(left);
    offsets.push(0u32);
    for i in 0..k {
        for j in (i + 1)..k {
            let d = (set[j] + v - set[i]) % v;
            let class = std::cmp::min(d, v - d) - 1;
            neighbors.push(class as u32);
            offsets.push(neighbors.len() as u32);
        }
    }
    ws.solve(left, right, &offsets, &neighbors)
        .expect("well-formed CSR")
}

fn sidon_search(v: usize, k: usize) -> SidonCertificate {
    assert_eq!(k * (k - 1), v - 1, "not a planar parameter set");

    // Canonical form: 0 in D (translation), and the cyclic gap ending at 0 is a
    // maximum gap, so every element is at most v - (largest internal gap).
    fn recurse(
        depth: usize,
        v: usize,
        k: usize,
        max_gap: usize,
        chosen: &mut Vec<usize>,
        used: &mut Vec<bool>,
        nodes: &mut u64,
        solutions: &mut Vec<Vec<usize>>,
        ws: &mut HallWorkspace,
        hall_verified: &mut usize,
        hall_failures: &mut usize,
    ) {
        if depth == k {
            match hall_difference_check(&chosen[..k], v, ws) {
                HallOutcome::Saturated => {
                    *hall_verified += 1;
                    solutions.push(chosen[..k].to_vec());
                }
                HallOutcome::Deficient { .. } => *hall_failures += 1,
            }
            return;
        }
        let last = chosen[depth - 1];
        let limit = (v - max_gap).min(v - 1);
        for x in (last + 1)..=limit {
            *nodes += 1;
            let mut ok = true;
            let mut marked = 0usize;
            for i in 0..depth {
                let d = x - chosen[i];
                let e = v - d;
                if used[d] || used[e] {
                    ok = false;
                    break;
                }
                used[d] = true;
                used[e] = true;
                marked += 1;
            }
            if ok {
                chosen[depth] = x;
                let gap = x - last;
                recurse(
                    depth + 1,
                    v,
                    k,
                    max_gap.max(gap),
                    chosen,
                    used,
                    nodes,
                    solutions,
                    ws,
                    hall_verified,
                    hall_failures,
                );
            }
            for i in 0..marked {
                let d = x - chosen[i];
                used[d] = false;
                used[v - d] = false;
            }
        }
    }

    // The first branch (choice of the second element) is split over threads;
    // each worker owns its own difference bitmap, Hall workspace and counters.
    let threads = std::thread::available_parallelism()
        .map(|p| p.get().min(12))
        .unwrap_or(4);
    let next = std::sync::atomic::AtomicUsize::new(1);
    let mut nodes = 0u64;
    let mut hall_verified = 0usize;
    let mut hall_failures = 0usize;
    let mut solutions: Vec<Vec<usize>> = Vec::new();

    let partials: Vec<(u64, usize, usize, Vec<Vec<usize>>)> = std::thread::scope(|scope| {
        let handles: Vec<_> = (0..threads)
            .map(|_| {
                let next = &next;
                scope.spawn(move || {
                    let mut used = vec![false; v];
                    let mut chosen = vec![0usize; k];
                    let mut ws = HallWorkspace::new(k * (k - 1) / 2, v);
                    let mut nodes = 0u64;
                    let mut verified = 0usize;
                    let mut failures = 0usize;
                    let mut sols: Vec<Vec<usize>> = Vec::new();
                    loop {
                        let d2 = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                        if d2 > v - 1 {
                            break;
                        }
                        nodes += 1;
                        chosen[0] = 0;
                        chosen[1] = d2;
                        used[d2] = true;
                        used[v - d2] = true;
                        recurse(
                            2,
                            v,
                            k,
                            d2,
                            &mut chosen,
                            &mut used,
                            &mut nodes,
                            &mut sols,
                            &mut ws,
                            &mut verified,
                            &mut failures,
                        );
                        used[d2] = false;
                        used[v - d2] = false;
                    }
                    (nodes, verified, failures, sols)
                })
            })
            .collect();
        handles.into_iter().map(|h| h.join().unwrap()).collect()
    });
    for (n, ver, fail, sols) in partials {
        nodes += n;
        hall_verified += ver;
        hall_failures += fail;
        solutions.extend(sols);
    }

    let count = solutions.len();
    let examples: Vec<Vec<usize>> = solutions.into_iter().take(4096).collect();
    SidonCertificate {
        schema: "c1018.plane12.sidon.v1",
        v,
        k,
        normalization: "0 in D; the cyclic gap ending at 0 is a maximum gap",
        nodes,
        solutions: count,
        examples,
        hall_verified,
        hall_failures,
        verdict: if count == 0 {
            format!("eliminated: no planar ({v},{k},1) difference set exists")
        } else {
            format!("{count} canonical planar difference sets found")
        },
    }
}

// ------------------------------------------------------------------ orbit13

#[derive(Serialize)]
struct OrbitCertificate {
    schema: &'static str,
    n: usize,
    p: usize,
    dimension: usize,
    row_sum: usize,
    row_square_sum: usize,
    pairwise_dot: usize,
    column_sum: usize,
    row_types: Vec<Vec<usize>>,
    candidate_rows: usize,
    nodes: u64,
    solutions: usize,
    cap: usize,
    exhaustive: bool,
    type_profiles: Vec<Vec<usize>>,
    examples: Vec<Vec<Vec<usize>>>,
    verdict: String,
}

/// Multisets of nonnegative integers with `dim` slots, sum `s`, square sum `q`.
fn row_multisets(dim: usize, s: usize, q: usize) -> Vec<Vec<usize>> {
    let mut out = Vec::new();
    let mut current: Vec<usize> = Vec::new();
    fn go(
        dim: usize,
        s: usize,
        q: usize,
        max_part: usize,
        current: &mut Vec<usize>,
        out: &mut Vec<Vec<usize>>,
    ) {
        if s == 0 {
            if q == 0 {
                out.push(current.clone());
            }
            return;
        }
        if current.len() == dim {
            return;
        }
        let top = max_part.min(s);
        for part in (1..=top).rev() {
            if part * part > q {
                continue;
            }
            current.push(part);
            go(dim, s - part, q - part * part, part, current, out);
            current.pop();
        }
    }
    go(dim, s, q, s, &mut current, &mut out);
    out
}

fn expand_rows(multiset: &[usize], dim: usize) -> Vec<Vec<usize>> {
    let mut padded = multiset.to_vec();
    padded.resize(dim, 0);
    padded.sort_unstable();
    let mut out = Vec::new();
    loop {
        out.push(padded.clone());
        // next lexicographic permutation
        let mut i = dim - 1;
        while i > 0 && padded[i - 1] >= padded[i] {
            i -= 1;
        }
        if i == 0 {
            break;
        }
        let mut j = dim - 1;
        while padded[j] <= padded[i - 1] {
            j -= 1;
        }
        padded.swap(i - 1, j);
        padded[i..].reverse();
    }
    out
}

fn dot(a: &[usize], b: &[usize]) -> usize {
    a.iter().zip(b.iter()).map(|(x, y)| x * y).sum()
}

#[allow(clippy::too_many_arguments)]
fn orbit_matrix_search(n: usize, cap: usize) -> OrbitCertificate {
    let dim = n - 1;
    let row_sum = n;
    let row_sq = 2 * n;
    let pair_dot = n;
    let col_sum = n;

    let types = row_multisets(dim, row_sum, row_sq);
    let mut rows: Vec<Vec<usize>> = Vec::new();
    let mut row_type: Vec<usize> = Vec::new();
    for (t, ms) in types.iter().enumerate() {
        for r in expand_rows(ms, dim) {
            rows.push(r);
            row_type.push(t);
        }
    }

    let max_entry = rows
        .iter()
        .flat_map(|r| r.iter().copied())
        .max()
        .unwrap_or(1);

    let mut nodes = 0u64;
    let mut found = 0u64;
    let mut solutions: Vec<Vec<Vec<usize>>> = Vec::new();
    let mut profiles: Vec<Vec<usize>> = Vec::new();

    // Column symmetry is used once: the distinguished first row is put in
    // sorted-descending form, one representative per row multiset.  The
    // remaining rows are enumerated in strictly increasing lexicographic order,
    // which quotients the residual row symmetry.
    for ms in &types {
        let mut first = ms.clone();
        first.resize(dim, 0);
        first.sort_unstable_by(|a, b| b.cmp(a));

        let compatible: Vec<usize> = (0..rows.len())
            .filter(|i| dot(&rows[*i], &first) == pair_dot)
            .collect();

        let mut colsum = first.clone();
        let mut picked: Vec<usize> = Vec::new();
        search(
            dim,
            col_sum,
            pair_dot,
            &rows,
            &compatible,
            &mut colsum,
            &mut picked,
            &first,
            &mut nodes,
            &mut found,
            &mut solutions,
            &mut profiles,
            &row_type,
            types.len(),
            cap,
            max_entry,
        );
    }

    profiles.sort_unstable();
    profiles.dedup();
    let count = found as usize;
    let examples: Vec<Vec<Vec<usize>>> = solutions;
    let type_list: Vec<Vec<usize>> = types.clone();

    OrbitCertificate {
        schema: "c1018.plane12.orbit.v2",
        n,
        p: n + 1,
        dimension: dim,
        row_sum,
        row_square_sum: row_sq,
        pairwise_dot: pair_dot,
        column_sum: col_sum,
        row_types: type_list,
        candidate_rows: rows.len(),
        nodes,
        solutions: count,
        cap,
        exhaustive: cap == 0 || count < cap,
        type_profiles: profiles,
        examples,
        verdict: if count == 0 {
            format!(
                "eliminated: no orbit matrix for an order-{} collineation",
                n + 1
            )
        } else if cap > 0 && count >= cap {
            format!("at least {count} normalized orbit matrices survive (cap reached)")
        } else {
            format!("{count} normalized orbit matrices survive")
        },
    }
}

#[allow(clippy::too_many_arguments)]
fn search(
    dim: usize,
    col_sum: usize,
    pair_dot: usize,
    rows: &[Vec<usize>],
    candidates: &[usize],
    colsum: &mut Vec<usize>,
    picked: &mut Vec<usize>,
    first: &[usize],
    nodes: &mut u64,
    found: &mut u64,
    solutions: &mut Vec<Vec<Vec<usize>>>,
    profiles: &mut Vec<Vec<usize>>,
    row_type: &[usize],
    type_count: usize,
    cap: usize,
    max_entry: usize,
) {
    if picked.len() + 1 == dim {
        if colsum.iter().all(|c| *c == col_sum) {
            let mut profile = vec![0usize; type_count];
            profile[row_type_of(first, rows, row_type)] += 1;
            for i in picked.iter() {
                profile[row_type[*i]] += 1;
            }
            if !profiles.contains(&profile) {
                profiles.push(profile);
            }
            if solutions.len() < 2 {
                let mut matrix = vec![first.to_vec()];
                for i in picked.iter() {
                    matrix.push(rows[*i].clone());
                }
                solutions.push(matrix);
            }
            *found += 1;
        }
        return;
    }
    // capacity prune: each further row contributes at most max_entry per column
    let remaining = dim - picked.len() - 1;
    for (pos, idx) in candidates.iter().enumerate() {
        if cap > 0 && *found >= cap as u64 {
            return;
        }
        *nodes += 1;
        let row = &rows[*idx];
        let mut ok = true;
        for j in 0..dim {
            if colsum[j] + row[j] > col_sum {
                ok = false;
                break;
            }
        }
        if ok {
            for j in 0..dim {
                let deficit = col_sum - colsum[j] - row[j];
                if deficit > (remaining - 1).max(0) * max_entry {
                    ok = false;
                    break;
                }
            }
        }
        if !ok {
            continue;
        }
        for j in 0..dim {
            colsum[j] += row[j];
        }
        let next: Vec<usize> = candidates[pos + 1..]
            .iter()
            .copied()
            .filter(|c| dot(&rows[*c], row) == pair_dot)
            .collect();
        picked.push(*idx);
        search(
            dim, col_sum, pair_dot, rows, &next, colsum, picked, first, nodes, found, solutions,
            profiles, row_type, type_count, cap, max_entry,
        );
        picked.pop();
        for j in 0..dim {
            colsum[j] -= row[j];
        }
    }
}

fn row_type_of(first: &[usize], rows: &[Vec<usize>], row_type: &[usize]) -> usize {
    for (i, r) in rows.iter().enumerate() {
        if r == first {
            return row_type[i];
        }
    }
    0
}

// ------------------------------------------------------------------- starter

#[derive(Serialize)]
struct StarterCertificate {
    schema: &'static str,
    m: usize,
    partitions_examined: u64,
    starters: usize,
    hall_saturated: usize,
    hall_deficient: usize,
    example: Vec<[usize; 2]>,
    verdict: String,
}

fn starter_search(m: usize) -> StarterCertificate {
    assert!(m % 2 == 1 && m >= 3);
    let half = (m - 1) / 2;
    let mut ws = HallWorkspace::new(half, half);
    let elements: Vec<usize> = (1..m).collect();
    let mut used = vec![false; m];
    let mut pairs: Vec<[usize; 2]> = Vec::new();
    let mut examined = 0u64;
    let mut starters = 0usize;
    let mut saturated = 0usize;
    let mut deficient = 0usize;
    let mut example: Vec<[usize; 2]> = Vec::new();

    #[allow(clippy::too_many_arguments)]
    fn go(
        m: usize,
        half: usize,
        elements: &[usize],
        used: &mut Vec<bool>,
        pairs: &mut Vec<[usize; 2]>,
        examined: &mut u64,
        starters: &mut usize,
        saturated: &mut usize,
        deficient: &mut usize,
        example: &mut Vec<[usize; 2]>,
        ws: &mut HallWorkspace,
    ) {
        if pairs.len() == half {
            *examined += 1;
            // Hall test: pairs must be matched bijectively to difference classes.
            let mut offsets = vec![0u32];
            let mut neighbors = Vec::new();
            for p in pairs.iter() {
                let d = (p[1] + m - p[0]) % m;
                let class = std::cmp::min(d, m - d) - 1;
                neighbors.push(class as u32);
                offsets.push(neighbors.len() as u32);
            }
            match ws.solve(half, half, &offsets, &neighbors) {
                Ok(HallOutcome::Saturated) => {
                    *saturated += 1;
                    *starters += 1;
                    if example.is_empty() {
                        *example = pairs.clone();
                    }
                }
                Ok(HallOutcome::Deficient { .. }) => *deficient += 1,
                Err(_) => unreachable!("well-formed CSR"),
            }
            return;
        }
        let a = *elements.iter().find(|e| !used[**e]).expect("free element");
        used[a] = true;
        for &b in elements.iter() {
            if used[b] {
                continue;
            }
            used[b] = true;
            pairs.push([a, b]);
            go(
                m, half, elements, used, pairs, examined, starters, saturated, deficient, example,
                ws,
            );
            pairs.pop();
            used[b] = false;
        }
        used[a] = false;
    }

    go(
        m,
        half,
        &elements,
        &mut used,
        &mut pairs,
        &mut examined,
        &mut starters,
        &mut saturated,
        &mut deficient,
        &mut example,
        &mut ws,
    );

    StarterCertificate {
        schema: "c1018.plane12.starter.v1",
        m,
        partitions_examined: examined,
        starters,
        hall_saturated: saturated,
        hall_deficient: deficient,
        example,
        verdict: if starters == 0 {
            format!("eliminated: no starter in Z_{m}")
        } else {
            format!("{starters} starters in Z_{m}")
        },
    }
}
