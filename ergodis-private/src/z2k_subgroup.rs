//! Bounded, allocation-free subgroup membership over `Z / 2^k`.
//!
//! The kernel applies invertible row and column operations to a small generator
//! matrix.  Choosing a nonzero entry of minimum 2-adic valuation makes every
//! remaining entry divisible by the pivot, so ordinary elimination produces a
//! Smith-style diagonal with entries in `{1, 2, 4, ...}`.  The transformed
//! target is in the generated subgroup exactly when each pivot divides its
//! coordinate and every unpivoted coordinate is zero.

use thiserror::Error;

pub const MAX_GENERATORS: usize = 64;

#[derive(Clone, Copy, Debug, Error, PartialEq, Eq)]
pub enum Z2kSubgroupError {
    #[error("the exponent must lie in 1..=15")]
    InvalidExponent,
    #[error("too many subgroup generators")]
    TooManyGenerators,
    #[error("a generator or target coordinate is not reduced modulo 2^k")]
    CoordinateOutOfRange,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Z2kMembership {
    pub contains: bool,
    pub pivot_count: u8,
    pub pivot_valuations: [u8; 8],
    pub transformed_target: [u16; 8],
    /// Invertible row operation matrix `U`; the reported target is `U target`.
    pub row_transform: [[u16; 8]; 8],
}

impl Z2kMembership {
    /// Canonical residue in the cokernel coordinates selected by the reduction.
    /// Two targets have the same residue exactly when their difference lies in
    /// the generated subgroup, provided they were reduced with the same basis.
    pub fn quotient_residue(&self) -> [u16; 8] {
        let mut residue = self.transformed_target;
        for (row, value) in residue
            .iter_mut()
            .enumerate()
            .take(usize::from(self.pivot_count))
        {
            *value &= (1_u16 << self.pivot_valuations[row]) - 1;
        }
        residue
    }
}

fn subtract_multiple(left: u16, multiple: u16, right: u16, modulus: u32) -> u16 {
    ((u32::from(left) + modulus - (u32::from(multiple) * u32::from(right)) % modulus) % modulus)
        as u16
}

fn odd_inverse(value: u16, modulus: u16) -> u16 {
    let mut candidate = 1_u16;
    while (u32::from(value) * u32::from(candidate)) % u32::from(modulus) != 1 {
        candidate += 2;
    }
    candidate
}

/// Decide membership in the subgroup generated by at most 64 eight-coordinate
/// vectors.  The entire reduction uses fixed stack storage and no recursion.
pub fn subgroup_membership_z2k(
    generators: &[[u16; 8]],
    target: [u16; 8],
    exponent: u8,
) -> Result<Z2kMembership, Z2kSubgroupError> {
    if !(1..=15).contains(&exponent) {
        return Err(Z2kSubgroupError::InvalidExponent);
    }
    if generators.len() > MAX_GENERATORS {
        return Err(Z2kSubgroupError::TooManyGenerators);
    }
    let modulus_u16 = 1_u16 << exponent;
    let modulus = u32::from(modulus_u16);
    if target.iter().any(|&value| value >= modulus_u16)
        || generators
            .iter()
            .any(|generator| generator.iter().any(|&value| value >= modulus_u16))
    {
        return Err(Z2kSubgroupError::CoordinateOutOfRange);
    }

    let mut matrix = [[0_u16; MAX_GENERATORS]; 8];
    for (column, generator) in generators.iter().enumerate() {
        for row in 0..8 {
            matrix[row][column] = generator[row];
        }
    }
    let mut transformed_target = target;
    let mut row_transform = [[0_u16; 8]; 8];
    for (row, transform_row) in row_transform.iter_mut().enumerate() {
        transform_row[row] = 1;
    }
    let mut pivot_valuations = [exponent; 8];
    let mut pivot = 0_usize;
    while pivot < 8 && pivot < generators.len() {
        let mut chosen = None;
        let mut chosen_valuation = exponent;
        for row in pivot..8 {
            for column in pivot..generators.len() {
                let value = matrix[row][column];
                if value != 0 {
                    let valuation = value.trailing_zeros() as u8;
                    if chosen.is_none() || valuation < chosen_valuation {
                        chosen = Some((row, column));
                        chosen_valuation = valuation;
                    }
                }
            }
        }
        let Some((chosen_row, chosen_column)) = chosen else {
            break;
        };
        matrix.swap(pivot, chosen_row);
        transformed_target.swap(pivot, chosen_row);
        row_transform.swap(pivot, chosen_row);
        for row in 0..8 {
            matrix[row].swap(pivot, chosen_column);
        }

        let divisor = 1_u16 << chosen_valuation;
        let odd_part = matrix[pivot][pivot] / divisor;
        let inverse = odd_inverse(odd_part, modulus_u16);
        for column in pivot..generators.len() {
            matrix[pivot][column] =
                ((u32::from(matrix[pivot][column]) * u32::from(inverse)) % modulus) as u16;
        }
        transformed_target[pivot] =
            ((u32::from(transformed_target[pivot]) * u32::from(inverse)) % modulus) as u16;
        for coordinate in 0..8 {
            row_transform[pivot][coordinate] = ((u32::from(row_transform[pivot][coordinate])
                * u32::from(inverse))
                % modulus) as u16;
        }
        debug_assert_eq!(matrix[pivot][pivot], divisor);

        for row in 0..8 {
            if row == pivot {
                continue;
            }
            let quotient = matrix[row][pivot] / divisor;
            for column in pivot..generators.len() {
                matrix[row][column] = subtract_multiple(
                    matrix[row][column],
                    quotient,
                    matrix[pivot][column],
                    modulus,
                );
            }
            transformed_target[row] = subtract_multiple(
                transformed_target[row],
                quotient,
                transformed_target[pivot],
                modulus,
            );
            for coordinate in 0..8 {
                row_transform[row][coordinate] = subtract_multiple(
                    row_transform[row][coordinate],
                    quotient,
                    row_transform[pivot][coordinate],
                    modulus,
                );
            }
        }
        for column in 0..generators.len() {
            if column == pivot {
                continue;
            }
            let quotient = matrix[pivot][column] / divisor;
            for row in pivot..8 {
                matrix[row][column] =
                    subtract_multiple(matrix[row][column], quotient, matrix[row][pivot], modulus);
            }
        }
        pivot_valuations[pivot] = chosen_valuation;
        pivot += 1;
    }

    let mut contains = true;
    for row in 0..pivot {
        contains &= transformed_target[row] & ((1_u16 << pivot_valuations[row]) - 1) == 0;
    }
    contains &= transformed_target[pivot..].iter().all(|&value| value == 0);
    Ok(Z2kMembership {
        contains,
        pivot_count: pivot as u8,
        pivot_valuations,
        transformed_target,
        row_transform,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::allocation_test::tracked_allocations;

    fn brute(generators: &[[u16; 8]], target: [u16; 8], modulus: u16) -> bool {
        let mut coefficients = [0_u16; 4];
        loop {
            let mut value = [0_u16; 8];
            for (column, generator) in generators.iter().enumerate() {
                for row in 0..8 {
                    value[row] = ((u32::from(value[row])
                        + u32::from(coefficients[column]) * u32::from(generator[row]))
                        % u32::from(modulus)) as u16;
                }
            }
            if value == target {
                return true;
            }
            let mut column = 0;
            while column < generators.len() {
                coefficients[column] += 1;
                if coefficients[column] != modulus {
                    break;
                }
                coefficients[column] = 0;
                column += 1;
            }
            if column == generators.len() {
                return false;
            }
        }
    }

    #[test]
    fn exhaustive_small_systems_match_brute_force() {
        for encoded in 0_u16..256 {
            let generators = [
                [encoded & 3, (encoded >> 2) & 3, 0, 0, 0, 0, 0, 0],
                [(encoded >> 4) & 3, (encoded >> 6) & 3, 0, 0, 0, 0, 0, 0],
            ];
            for target in 0_u16..16 {
                let target = [target & 3, (target >> 2) & 3, 0, 0, 0, 0, 0, 0];
                assert_eq!(
                    subgroup_membership_z2k(&generators, target, 2)
                        .unwrap()
                        .contains,
                    brute(&generators, target, 4)
                );
            }
        }
    }

    #[test]
    fn kernel_allocates_nothing() {
        let generators = [[1, 2, 4, 8, 3, 6, 12, 0]; 32];
        let (_, allocations) = tracked_allocations(|| {
            for target in 0_u16..256 {
                std::hint::black_box(
                    subgroup_membership_z2k(&generators, [target & 15, 0, 0, 0, 0, 0, 0, 0], 4)
                        .unwrap(),
                );
            }
        });
        assert_eq!(allocations, 0);
    }

    #[test]
    fn reported_row_transform_reproduces_target_and_residue() {
        let generators = [
            [1, 2, 4, 8, 3, 6, 12, 0],
            [2, 1, 5, 9, 7, 4, 8, 2],
            [0, 4, 2, 6, 10, 12, 14, 8],
        ];
        for seed in 0_u16..256 {
            let target = std::array::from_fn(|coordinate| {
                (seed.wrapping_mul(2 * coordinate as u16 + 1) + coordinate as u16) & 15
            });
            let reduced = subgroup_membership_z2k(&generators, target, 4).unwrap();
            let replayed = std::array::from_fn(|row| {
                reduced.row_transform[row]
                    .iter()
                    .zip(target)
                    .fold(0_u16, |sum, (&coefficient, value)| {
                        (sum + coefficient * value) & 15
                    })
            });
            assert_eq!(replayed, reduced.transformed_target);
            assert_eq!(reduced.quotient_residue() == [0; 8], reduced.contains);
        }
    }
}
