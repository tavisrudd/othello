"""C497 — double-coset stratum-constancy pre-diagnostic on the frozen q17 census.

Question (transfer note 2026-07-22-c434-c80-cross-lane-transfers.md, Transfer 3;
sharpened by C495 ej2): stratify the frozen q17 three-intruder census by the
double-coset label of the (prior-triple stabilizer, reply) pair and test whether
`Y_NK0`-membership is stratum-constant.

Per the queued task, this is the CHEAP PRE-DIAGNOSTIC that runs FIRST: does the
double-coset partition even refine `Y_NK0`-membership? If not, the stratification is
non-constant immediately and the full P/N sweep is skipped.

Run independently, NOT as a transport of C434's q=11 fibre identity (C495 falsified
that identification: the q=11 packet symmetry is `C5`, the double-coset label is
additive/incidence data orthogonal to the multiplicative `Legendre(u)` value sort).

Method (C434-style, group-structure-independent): the intruder centres are off-conic
grid cells; each induces a conic involution in `G = PGL_2(q)` acting on the q+1 conic
parameters.  The prior triple's stabiliser `K = Stab_G({sigma_1,sigma_2,sigma_3})`;
the double-coset label of the (K, reply) pair is exactly the `G`-orbit of the marked
configuration `({sigma_1,sigma_2,sigma_3}, sigma_reply)` under simultaneous
conjugation.  Two `Y_0` objects share a double-coset label iff an explicit
`g in PGL_2(q)` conjugates one marked configuration to the other.

`Y_0` / `Y_NK0` are reproduced verbatim from the committed C80 census
(rust/scripts/c80_response_fibre_census.py): a `Y_0` object is a legal off-conic
reply, primitive relative to the opponent move, with no conic fixed point for any of
the four intruder triple products; it is a `Y_NK0` member iff its grandchild has an
empty conic, is graph-exact, and has conflict-graph Grundy value zero.  `Y_NK0`
membership here is computed WITHOUT the full game recursion (empty conic + graph-exact
+ zone Grundy zero), which the census proves equivalent to the P-value on that domain.
"""

