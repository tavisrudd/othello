def load_module(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_pgl(game, inf) -> tuple[list[tuple[int, ...]], dict]:
    """PGL_2(q) on the q+1 conic parameters, generated by standard Mobius maps."""
    params = game.params
    idx = {p: i for i, p in enumerate(params)}
    n = len(params)
    q = game.q

    def mobius(a: int, b: int, c: int, d: int) -> tuple[int, ...]:
        out = [0] * n
        for i, t in enumerate(params):
            if t is inf:
                num, den = a, c
            else:
                num, den = (a * t + b) % q, (c * t + d) % q
            out[i] = idx[inf] if den % q == 0 else idx[(num * pow(den, q - 2, q)) % q]
        return tuple(out)

    gens = [mobius(1, 1, 0, 1), mobius(3, 0, 0, 1), mobius(0, (-1) % q, 1, 0)]
    ident = tuple(range(n))
    group = {ident}
    frontier = deque([ident])
    while frontier:
        x = frontier.popleft()
        for gen in gens:
            y = tuple(gen[x[i]] for i in range(n))
            if y not in group:
                group.add(y)
                frontier.append(y)
    ordered = sorted(group)
    inverses = {}
    for g in ordered:
        inv = [0] * n
        for i in range(n):
            inv[g[i]] = i
        inverses[g] = tuple(inv)
    return ordered, inverses


def enumerate_y0(game, geometry, census, lines, states, inf) -> list[tuple]:
    """Reproduce the census inner loop; record every Y_0 object with its nk_zero flag.

    Returns (sorted three intruder cells, reply cell, nk_zero) tuples.
    """
    q = game.q
    objects = []
    three_intruder_transitions = 0
    for mask, _row in states:
        for move in geometry.bits(game.legal_mask(mask) & ~game.conic_mask):
            child = mask | (1 << move)
            old = geometry.intruders(game, child)
            if len(old) != 3:
                continue
            three_intruder_transitions += 1
            cells = tuple(geometry.cell(game, p) for p in old)
            if census.fixed_count(q, census.discriminant(q, *cells)):
                continue
            for reply in geometry.bits(game.legal_mask(child) & ~game.conic_mask):
                if geometry.prod_order(game, move, reply) not in (q - 1, q + 1):
                    continue
                quad = tuple(geometry.cell(game, p) for p in (*old, reply))
                if any(
                    census.fixed_count(q, census.discriminant(q, *(quad[i] for i in tri)))
                    for tri in combinations(range(4), 3)
                ):
                    continue
                grand = child | (1 << reply)
                grand_live = len(geometry.live_conic(game, grand))
                features = game.state_features(grand, geometry.intruders(game, grand))
                nk_exact = census.node_kayles_exact(game, lines, grand)
                nk_zero = nk_exact and grand_live == 0 and features["zone_grundy"] == 0
                objects.append((tuple(sorted(old)), reply, nk_zero))
    return objects, three_intruder_transitions


def run() -> dict:
    census = load_module(CENSUS, "c497_census")
    geometry = load_module(GEOMETRY, "c497_geometry")
    c31 = geometry.load_c31_module()
    c20 = c31.load_c20_module()
    inf = c20.INF
    game = c20.PrimeGridGame(Q)
    lines = census.projective_lines(game)
    states, _ = c31.load_p_reply_states(ROWS, Q)

    group, inverses = build_pgl(game, inf)
    params = game.params
    idx = {p: i for i, p in enumerate(params)}
    n = len(params)

    invcache: dict[int, tuple[int, ...]] = {}

    def involution(cell: int) -> tuple[int, ...]:
        cached = invcache.get(cell)
        if cached is None:
            sp = game.sigma_perm(cell)
            cached = tuple(idx[sp[params[i]]] for i in range(n))
            invcache[cell] = cached
        return cached

    def fixed(iv: tuple[int, ...]) -> int:
        return sum(1 for i in range(n) if iv[i] == i)

    def product_order(a: tuple[int, ...], b: tuple[int, ...]) -> int:
        comp = tuple(a[b[i]] for i in range(n))
        seen = [False] * n
        order = 1
        for s in range(n):
            if seen[s]:
                continue
            t, length = s, 0
            while not seen[t]:
                seen[t] = True
                t = comp[t]
                length += 1
            order = order * length // gcd(order, length)
        return order

    def conjugate(g: tuple[int, ...], gi: tuple[int, ...], iv: tuple[int, ...]) -> tuple[int, ...]:
        return tuple(g[iv[gi[i]]] for i in range(n))

    def min_conjugator(three_a, reply_a, three_b, reply_b):
        """Least g (in sorted PGL) conjugating configuration A onto B, or None."""
        a_unmarked = [involution(c) for c in three_a]
        a_mark = involution(reply_a)
        b_unmarked = {involution(c) for c in three_b}
        b_mark = involution(reply_b)
        for g in group:
            gi = inverses[g]
            if conjugate(g, gi, a_mark) != b_mark:
                continue
            if {conjugate(g, gi, x) for x in a_unmarked} == b_unmarked:
                return g
        return None

    objects, three_intruder_transitions = enumerate_y0(
        game, geometry, census, lines, states, inf
    )
    y0_members = len(objects)
    ynk0_members = sum(1 for _, _, nk in objects if nk)

    # --- double-coset (G-invariant) partition of the Y_0 objects ---
    def label(three, reply):
        ivs = [involution(c) for c in three]
        iz = involution(reply)
        return (
            tuple(sorted(fixed(v) for v in ivs)),
            fixed(iz),
            tuple(sorted(product_order(ivs[i], ivs[j]) for i, j in combinations(range(3), 2))),
            tuple(sorted(product_order(v, iz) for v in ivs)),
        )

    buckets = defaultdict(list)
    for three, reply, nk in objects:
        buckets[label(three, reply)].append((three, reply, nk))

    mixed = sorted(k for k, v in buckets.items() if len({x[2] for x in v}) > 1)
    objects_in_mixed = sum(len(buckets[k]) for k in mixed)

    # --- verify true-orbit splits: an explicit g conjugating a Y_NK0 object onto a
    #     non-Y_NK0 object inside the same double-coset stratum ---
    verified_split_buckets = 0
    witness = None
    for k in mixed:
        members = sorted(buckets[k])
        yes = [m for m in members if m[2]]
        no = [m for m in members if not m[2]]
        found = None
        for a in yes:
            for b in no:
                g = min_conjugator(a[0], a[1], b[0], b[1])
                if g is not None:
                    found = (a, b, g)
                    break
            if found:
                break
        if found:
            verified_split_buckets += 1
            if witness is None:
                witness = (k, found)

    assert three_intruder_transitions == 59153
    assert y0_members == 17954
    assert ynk0_members == 3048
    assert witness is not None, "expected a verified double-coset split"

    (wkey, (wyes, wno, wg)) = witness
    gi = inverses[wg]
    # hard self-check of the witness
    a_unmarked = [involution(c) for c in wyes[0]]
    assert {conjugate(wg, gi, x) for x in a_unmarked} == {involution(c) for c in wno[0]}
    assert conjugate(wg, gi, involution(wyes[1])) == involution(wno[1])
    assert wyes[2] is True and wno[2] is False

    frozen = json.loads(FROZEN_CENSUS.read_text())
    field17 = next(f for f in frozen["fields"] if f["q"] == Q)
    assert field17["three_intruder_transitions"] == three_intruder_transitions
    assert field17["packet_members"] == y0_members
    assert field17["node_kayles_zero_members"] == ynk0_members

    def cells(triple):
        return [list(geometry.cell(game, c)) for c in triple]

    return {
        "claim_scope": (
            "Pre-diagnostic C497: whether the (prior-triple stabilizer, reply) "
            "double-coset partition refines Y_NK0-membership on the frozen q=17 "
            "three-intruder census. Independent stratification test, not a transport "
            "of C434's q=11 fibre identity (C495 FALSIFIER NO)."
        ),
        "double_coset_label": (
            "G = PGL_2(q) acting on the q+1 conic parameters; each off-conic intruder "
            "centre induces a conic involution. The double-coset label of a (prior "
            "triple, reply) pair is the G-orbit of the marked configuration "
            "({sigma_1,sigma_2,sigma_3}, sigma_reply) under simultaneous conjugation; "
            "sameness is witnessed by an explicit conjugating g in G."
        ),
        "q": Q,
        "group_order": len(group),
        "three_intruder_transitions": three_intruder_transitions,
        "y0_members": y0_members,
        "ynk0_members": ynk0_members,
        "double_coset_buckets": len(buckets),
        "mixed_ynk0_buckets": len(mixed),
        "y0_objects_in_mixed_buckets": objects_in_mixed,
        "verified_true_orbit_split_buckets": verified_split_buckets,
        "refines_ynk0_membership": False,
        "verdict": (
            "NON-CONSTANT: the double-coset partition does not refine "
            "Y_NK0-membership. Y_NK0 and non-Y_NK0 objects share a double-coset label "
            "(explicit PGL_2(17) conjugator), so stratum-constancy fails and the full "
            "P/N sweep is skipped. The double-coset label (additive/incidence sort) is "
            "orthogonal to Y_NK0-membership (value sort), confirming C495 ej2 at q=17. "
            "Stratification is refuted as the bulk-descent mechanism."
        ),
        "canonical_witness": {
            "label_fixed_points_triple": list(wkey[0]),
            "label_reply_fixed_points": wkey[1],
            "label_triple_product_orders": list(wkey[2]),
            "label_reply_product_orders": list(wkey[3]),
            "ynk0_object": {
                "intruder_cells": list(wyes[0]),
                "intruder_coords": cells(wyes[0]),
                "reply_cell": wyes[1],
                "reply_coords": list(geometry.cell(game, wyes[1])),
                "in_ynk0": True,
            },
            "non_ynk0_object": {
                "intruder_cells": list(wno[0]),
                "intruder_coords": cells(wno[0]),
                "reply_cell": wno[1],
                "reply_coords": list(geometry.cell(game, wno[1])),
                "in_ynk0": False,
            },
            "conjugator_param_permutation": list(wg),
        },
        "inputs": {
            path.name: {"sha256": sha256(path), "bytes": path.stat().st_size}
            for path in (CENSUS, GEOMETRY, FROZEN_CENSUS, ROWS)
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUT)
    args = parser.parse_args()

    payload = run()
    rendered = json.dumps(payload, indent=2, sort_keys=True) + "\n"
    if args.check:
        assert args.output.read_text() == rendered
        print("C497 double-coset stratum-constancy: PASS (partition does NOT refine Y_NK0)")
    else:
        args.output.write_text(rendered)
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
