#!/usr/bin/env python3
"""C80 — does the C496 quadratic character generalize to the escape family?

C496 found the frozen q=11 seed's depth-1 value factors through chi(u), the Legendre
character of a bespoke frame-edge quotient.  The recursion-stability probe showed that
object is depth-0 and its conic scaffold (5-arc -> conic -> edge) exists only at the
size-4 escape layer.  So the ONLY place a chi value-law could recur is ACROSS the escape
family (recursion in q, not depth).  This probe tests exactly that on the canonical
data: each on-conic S4ARENA bucket is a PGL-canonical size-4 residual position t4 (four
conic parameters; the burned directions inf,0 are the marked opening pair) with an EXACT
game value P/N.

Question: is the P/N label a fixed quadratic character of a canonical invariant of the
6-arc {inf, 0} u t4, uniformly over q in {11,13,17,19}?

The relevant symmetry is Stab({inf,0}) in PGL_2(q) (generated by z->az and z->1/z), under
which the well-defined chi invariants of t4 are:
  * the square-class multiset {chi(t_i)} up to a global flip  ->  k = #squares, folded to
    min(k, 4-k)   (z->(nonsquare)*z flips all four);
  * chi(prod_i t_i), chi(prod_{i<j}(t_i - t_j)) (the t4 discriminant), and the mixed
    products chi(prod t_i * prod(t_i - t_j)).
We also test the full-arc discriminant square class over all 6 points (with inf handled
by dropping its factors), the natural fully-PGL-covariant candidate and C520's tt#1 object.

Decisive: a character that perfectly separates P from N buckets uniformly => a static
value-law at the escape layer (a major step toward (ON) and C520).  No separator =>
C496's chi is bespoke to its edge and does not govern the escape family.

Run from /home/tavis/src/othello:
    python3 rust/scripts/c496_escape_family_character_probe.py [--write|--check]
"""

from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
QS = [11, 13, 17, 19]
BUCKET_FILE = "notes/data/c68b-onconic-buckets-q{q}.txt"
OUT = ROOT / "notes/2026-07-23-c496-escape-family-character-probe.json"
REP_RE = re.compile(r"rep=\[([0-9, ]+)\]\s+status=\S+\s+value=([PN])")


def leg(x, q):
    x %= q
    if x == 0:
        return 0
    return 1 if pow(x, (q - 1) // 2, q) == 1 else -1


def load_buckets(q):
    text = (ROOT / BUCKET_FILE.format(q=q)).read_text()
    out = []
    for m in REP_RE.finditer(text):
        t4 = tuple(int(v) for v in m.group(1).split(","))
        assert len(t4) == 4 and all(1 <= t < q for t in t4), (q, t4)
        out.append((t4, m.group(2)))
    assert out, q
    return out


def invariants(t4, q):
    """Stab({inf,0})-invariant quadratic-character features of the 4 params t4."""
    sq = [leg(t, q) for t in t4]
    k = sum(1 for s in sq if s == 1)  # squares rel to 0
    prod = 1
    for t in t4:
        prod = prod * t % q
    disc = 1  # t4 Vandermonde prod_{i<j}(t_i - t_j)
    for i, j in combinations(range(4), 2):
        disc = disc * (t4[i] - t4[j]) % q
    # 6-arc discriminant over finite points {0} u t4 (inf factors dropped):
    #   prod over pairs among [0, t1..t4]; adds factor prod_i (t_i - 0) = prod t_i.
    disc6 = disc * prod % q
    # full-PGL cross-ratio characters (C520 discriminant object): the 3 essential
    # cross-ratios from the 3 pairings of the 4 params; chi-multiset is PGL-invariant.
    a, b, c, d = t4
    lam = []
    for (w, x, y, z) in ((a, b, c, d), (a, c, b, d), (a, d, b, c)):
        num = (w - y) * (x - z) % q
        den = (w - z) * (x - y) % q
        lam.append(leg(num * pow(den, q - 2, q) % q, q) if den else 0)
    cr_multiset = tuple(sorted(lam))
    return {
        # discrete square-class pattern, folded by the global-flip symmetry
        "k_squares_folded": min(k, 4 - k),
        "chi_prod_params": leg(prod, q),
        "chi_disc4": leg(disc, q),
        "chi_disc6_finite": leg(disc6, q),
        "chi_prod_times_disc4": leg(prod * disc % q, q),
        "cr_chi_multiset": cr_multiset,
    }


FEATURES = (
    "k_squares_folded", "chi_prod_params", "chi_disc4",
    "chi_disc6_finite", "chi_prod_times_disc4", "cr_chi_multiset",
)


def contingency(rows, key):
    """map feature-value -> Counter(P/N).  A feature genuinely separates only when the
    row set has BOTH labels AND every feature-class is label-pure (single-class row sets
    are vacuous: any feature 'separates' them)."""
    table = defaultdict(Counter)
    labels = set()
    for feat, val in rows:
        table[feat[key]][val] += 1
        labels.add(val)
    pure = len(labels) >= 2 and all(len(c) == 1 for c in table.values())
    return pure, {str(k): dict(v) for k, v in sorted(table.items(), key=lambda kv: str(kv[0]))}


def main():
    per_q = {}
    pooled_rows = []
    for q in QS:
        buckets = load_buckets(q)
        rows = [(invariants(t4, q), val) for t4, val in buckets]
        pooled_rows.extend(rows)
        labels = Counter(v for _f, v in rows)
        feats = {}
        for key in FEATURES:
            pure, tab = contingency(rows, key)
            feats[key] = {"separates": pure, "table": tab}
        per_q[str(q)] = {"buckets": len(rows), "labels": dict(labels), "features": feats}

    # pooled (uniform across q) separation
    pooled = {}
    for key in FEATURES:
        pure, tab = contingency(pooled_rows, key)
        pooled[key] = {"separates": pure, "table": tab}

    any_uniform = [k for k, v in pooled.items() if v["separates"]]
    any_perq = {
        q: [k for k, v in d["features"].items() if v["separates"]]
        for q, d in per_q.items()
    }

    cert = {
        "schema": "c496-escape-family-character-probe-v1",
        "qs": QS,
        "per_q": per_q,
        "pooled": pooled,
        "uniform_separators": any_uniform,
        "per_q_separators": any_perq,
        "verdict": (
            "CHARACTER_LAW_UNIFORM" if any_uniform else
            ("CHARACTER_LAW_PER_Q_ONLY" if any(any_perq.values()) else
             "NO_CHARACTER_LAW")
        ),
    }

    # ---- readable summary ----
    print("=== escape-family quadratic-character value-law probe ===")
    for q in QS:
        d = per_q[str(q)]
        print(f"\nq={q}: {d['buckets']} on-conic buckets, labels={d['labels']}")
        for key, fd in d["features"].items():
            mark = "SEPARATES" if fd["separates"] else "mixed"
            print(f"  {key:22s} {mark:10s} {fd['table']}")
    print("\n=== pooled across q (uniform law?) ===")
    for key, fd in pooled.items():
        mark = "SEPARATES" if fd["separates"] else "mixed"
        print(f"  {key:22s} {mark:10s} {fd['table']}")
    print(f"\nuniform separators: {any_uniform or 'NONE'}")
    print(f"per-q separators:   {any_perq}")
    print(f"\nVERDICT: {cert['verdict']}")
    return cert


def canonical_bytes(data):
    return (json.dumps(data, indent=2, sort_keys=True) + "\n").encode()


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = main()
    payload = canonical_bytes(result)
    if args.write:
        OUT.write_bytes(payload)
        print(f"\nwrote {OUT.relative_to(ROOT)}")
    elif args.check:
        assert OUT.read_bytes() == payload, "C496 escape-family character certificate drift"
        print("\nC496 escape-family character check: PASS")
