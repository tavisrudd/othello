//! Multi-ProbCut forward pruning for the `strong++` engine.
//!
//! ProbCut (Buro) skips a deep search when a cheap shallow search proves the
//! value lies far outside the `(alpha, beta)` window. The deep value relates to
//! the shallow one by a calibrated linear model `v_deep ≈ a·v_shallow + b` with
//! residual std `σ`; we cut when a shallow null-window search clears the window
//! by `MPC_T·σ`. "Multi" = the check is applied at several depths, each with its
//! own shallow probe depth (`MPC_PAIRS`).
//!
//! Unlike everything else in this crate this is **not value-preserving**: it is
//! forward pruning, so a fixed-depth `strong++` value can differ from `strong+`.
//! The payoff is depth-per-time -- at equal wall-clock `strong++` searches
//! deeper. The exact endgame solve is untouched (`solve` never calls `pvs`).
//!
//! All values are side-to-move (negamax) units -- colour-swap invariant, so one
//! table serves both sides. Coefficients are per `(depth-pair, disc-count)`; `σ`
//! grows sharply toward the endgame, so MPC self-disables where shallow searches
//! mispredict. Regenerate the table with `cargo run --release --example
//! calibrate_mpc` (it is calibrated for the `strong+` horizon eval that
//! `strong++` uses, so the probe leaf values match the search).

