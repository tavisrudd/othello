/// MPC is attempted only at depths `>=` this. Every shallow probe depth in
/// `MPC_PAIRS` is strictly below it, so a probe is pure PVS -- MPC never nests,
/// and the runtime probe matches the (MPC-off) calibration exactly.
pub const MPC_MIN_DEPTH: i32 = 5;
/// Cut threshold in σ units: larger = safer (fewer, more-confident cuts). 1.5 is
/// Buro's classic operating point (~93% one-sided confidence under the model).
pub const MPC_T: f32 = 1.5;
/// Eval-magnitude ceiling. A bound past this can't be reached by a shallow
/// search, so the corresponding test is skipped -- which also disables MPC at the
/// full root window (`±1e9`), confining it to the narrow scout windows it helps.
pub const MPC_LIMIT: i32 = 4000;

/// A computed ProbCut probe: the shallow depth to search, and the null-window
/// bounds whose proof triggers a fail-high (`>= hi`) or fail-low (`<= lo`) cut.
pub struct Probe {
    pub shallow: i32,
    pub hi: Option<i32>,
    pub lo: Option<i32>,
}

/// Pair index for a deep `depth`: pairs cover deep depths 5.. contiguously, and
/// anything deeper than the deepest calibrated pair reuses it.
#[inline]
fn pair_index(depth: i32) -> usize {
    ((depth - MPC_MIN_DEPTH) as usize).min(MPC_PAIRS.len() - 1)
}

/// Compute the ProbCut probe for `(depth, discs)` at window `(alpha, beta)`, or
/// `None` if MPC does not apply (shallow eval only; `plus` guards that the table
/// matches the running eval). Side-to-move units throughout.
#[inline]
pub fn probe(plus: bool, depth: i32, discs: u32, alpha: i32, beta: i32) -> Option<Probe> {
    if !plus || depth < MPC_MIN_DEPTH {
        return None; // MPC is calibrated for the plus eval only
    }
    let pi = pair_index(depth);
    let (_, shallow) = MPC_PAIRS[pi];
    let (a, b, sigma) = MPC_COEFF[pi][(discs as usize).min(63)];
    let margin = MPC_T * sigma;

    // Fail-high: cut if a·v_s + b - margin >= beta  <=>  v_s >= (beta-b+margin)/a.
    let hi = if (-MPC_LIMIT..MPC_LIMIT).contains(&beta) {
        let bound = ((beta as f32 - b + margin) / a).ceil() as i32;
        ((-MPC_LIMIT..MPC_LIMIT).contains(&bound)).then_some(bound)
    } else {
        None
    };
    // Fail-low: cut if a·v_s + b + margin <= alpha  <=>  v_s <= (alpha-b-margin)/a.
    let lo = if (-MPC_LIMIT..MPC_LIMIT).contains(&alpha) {
        let bound = ((alpha as f32 - b - margin) / a).floor() as i32;
        ((-MPC_LIMIT..MPC_LIMIT).contains(&bound)).then_some(bound)
    } else {
        None
    };

    if hi.is_none() && lo.is_none() {
        return None;
    }
    Some(Probe { shallow, hi, lo })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pairs_are_contiguous_from_min_depth() {
        // pair_index relies on deep depths being MPC_MIN_DEPTH, +1, +2, ...
        for (i, &(deep, shallow)) in MPC_PAIRS.iter().enumerate() {
            assert_eq!(deep, MPC_MIN_DEPTH + i as i32);
            assert!(shallow < MPC_MIN_DEPTH, "probe must not re-trigger MPC");
            assert!(shallow >= 1);
        }
    }

    #[test]
    fn no_probe_at_full_window_or_with_base_eval() {
        // Root full window: nothing reachable -> no probe.
        assert!(probe(true, 8, 20, -1_000_000_000, 1_000_000_000).is_none());
        // Base eval: uncalibrated -> never.
        assert!(probe(false, 8, 20, -10, 10).is_none());
        // Below MPC_MIN_DEPTH -> never.
        assert!(probe(true, 4, 20, -10, 10).is_none());
    }

    #[test]
    fn scout_window_yields_a_bound() {
        // A tight midgame scout window should produce at least one finite bound.
        let p = probe(true, 8, 30, 9, 10).expect("scout probe");
        assert_eq!(p.shallow, 4);
        assert!(p.hi.is_some() || p.lo.is_some());
        if let Some(hi) = p.hi {
            assert!(hi > 10, "fail-high bound sits above beta by the margin");
        }
        if let Some(lo) = p.lo {
            assert!(lo < 9, "fail-low bound sits below alpha by the margin");
        }
    }
}
