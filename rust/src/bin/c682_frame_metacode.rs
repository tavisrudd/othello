//! Exhaustive three-word weight enumerator for the C682 Paper-IV frame code.
//!
//! The canonical octahedral--toric certificate supplies the cubic transition
//! matrix C.  This tool constructs
//!
//!     H = [ I  C ]
//!         [ C' I ]
//!
//! over F_2, derives a basis of ker(H), and enumerates its codewords in Gray
//! order as three u64 words.  A bounded from-scratch evaluator independently
//! checks the optimized kernel before a full 2^37 run.

use clap::Parser;
use rayon::prelude::*;
use serde::Deserialize;
use serde_json::json;
use std::error::Error;
use std::fs;
use std::path::PathBuf;
use std::time::Instant;

const FRAME: usize = 91;
const LENGTH: usize = 2 * FRAME;
const WORDS: usize = 3;

#[derive(Parser, Debug)]
struct Args {
    /// Canonical Paper-IV orbit-correspondence JSON certificate.
    #[arg(long)]
    input: Option<PathBuf>,

    /// Enumerate the subcode generated by the first B basis vectors.
    #[arg(long, default_value_t = 37)]
    bits: usize,

    /// Number of low basis bits swept in each Gray-code block.
    #[arg(long, default_value_t = 20)]
    low_bits: usize,

    /// Independently check the first B basis vectors before the main run.
    #[arg(long, default_value_t = 18)]
    self_check_bits: usize,

    /// Disable the bounded independent self-check.
    #[arg(long)]
    no_self_check: bool,

    /// Override the Rayon worker count.
    #[arg(long)]
    threads: Option<usize>,

    /// Write the result as canonical pretty JSON.
    #[arg(long)]
    output: Option<PathBuf>,

    /// Compare the canonical result with an existing JSON certificate.
    #[arg(long)]
    check: Option<PathBuf>,
}

#[derive(Deserialize)]
struct Certificate {
    schema: String,
    correspondence: Correspondence,
}

#[derive(Deserialize)]
struct Correspondence {
    left_neighbor_indices: Vec<[usize; 3]>,
    paired_coordinate_column_words_le: Vec<[String; 3]>,
}

#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
struct Word3([u64; WORDS]);

impl Word3 {
    #[inline]
    fn set(&mut self, bit: usize) {
        self.0[bit >> 6] |= 1u64 << (bit & 63);
    }

    #[inline]
    fn get(self, bit: usize) -> bool {
        self.0[bit >> 6] >> (bit & 63) & 1 != 0
    }

    #[inline]
    fn xor_assign(&mut self, rhs: Self) {
        self.0[0] ^= rhs.0[0];
        self.0[1] ^= rhs.0[1];
        self.0[2] ^= rhs.0[2];
    }

    #[inline]
    fn weight(self) -> usize {
        (self.0[0].count_ones() + self.0[1].count_ones() + self.0[2].count_ones()) as usize
    }

    #[inline]
    fn dot(self, rhs: Self) -> bool {
        ((self.0[0] & rhs.0[0]).count_ones()
            + (self.0[1] & rhs.0[1]).count_ones()
            + (self.0[2] & rhs.0[2]).count_ones())
            & 1
            != 0
    }
}

fn build_metacheck(left_neighbors: &[[usize; 3]]) -> Vec<Word3> {
    assert_eq!(left_neighbors.len(), FRAME);
    let mut rows = vec![Word3::default(); LENGTH];
    let mut right_degree = [0usize; FRAME];
    for (i, neighbors) in left_neighbors.iter().enumerate() {
        rows[i].set(i);
        for &j in neighbors {
            assert!(j < FRAME);
            rows[i].set(FRAME + j);
            rows[FRAME + j].set(i);
            right_degree[j] += 1;
        }
    }
    for j in 0..FRAME {
        rows[FRAME + j].set(FRAME + j);
    }
    assert!(right_degree.iter().all(|&degree| degree == 3));
    assert!(rows.iter().all(|row| row.weight() == 4));
    rows
}

fn kernel_basis(mut rows: Vec<Word3>) -> (usize, Vec<Word3>) {
    let mut pivots = Vec::new();
    let mut rank = 0usize;
    for column in 0..LENGTH {
        let Some(pivot) = (rank..rows.len()).find(|&row| rows[row].get(column)) else {
            continue;
        };
        rows.swap(rank, pivot);
        let pivot_row = rows[rank];
        for (row_index, row) in rows.iter_mut().enumerate() {
            if row_index != rank && row.get(column) {
                row.xor_assign(pivot_row);
            }
        }
        pivots.push((rank, column));
        rank += 1;
    }

    let mut is_pivot = [false; LENGTH];
    for &(_, column) in &pivots {
        is_pivot[column] = true;
    }
    let mut basis = Vec::new();
    for free in (0..LENGTH).filter(|&column| !is_pivot[column]) {
        let mut vector = Word3::default();
        vector.set(free);
        for &(row, pivot) in &pivots {
            if rows[row].get(free) {
                vector.set(pivot);
            }
        }
        basis.push(vector);
    }
    (rank, basis)
}

#[derive(Clone)]
struct Stats {
    counts: [u64; LENGTH + 1],
    minimum_nonzero_weight: usize,
    minimum_coefficient: u64,
    minimum_word: Word3,
    words_at_or_below_coordinate_weight: Vec<(Word3, u64)>,
}

impl Stats {
    fn new() -> Self {
        Self {
            counts: [0; LENGTH + 1],
            minimum_nonzero_weight: usize::MAX,
            minimum_coefficient: u64::MAX,
            minimum_word: Word3::default(),
            words_at_or_below_coordinate_weight: Vec::new(),
        }
    }

    #[inline]
    fn record(&mut self, word: Word3, coefficient: u64) {
        let weight = word.weight();
        self.counts[weight] += 1;
        if coefficient != 0
            && (weight < self.minimum_nonzero_weight
                || (weight == self.minimum_nonzero_weight
                    && coefficient < self.minimum_coefficient))
        {
            self.minimum_nonzero_weight = weight;
            self.minimum_coefficient = coefficient;
            self.minimum_word = word;
        }
        if coefficient != 0 && weight <= 28 {
            self.words_at_or_below_coordinate_weight
                .push((word, coefficient));
        }
    }

    fn merge(mut self, other: Self) -> Self {
        for weight in 0..=LENGTH {
            self.counts[weight] += other.counts[weight];
        }
        if other.minimum_nonzero_weight < self.minimum_nonzero_weight
            || (other.minimum_nonzero_weight == self.minimum_nonzero_weight
                && other.minimum_coefficient < self.minimum_coefficient)
        {
            self.minimum_nonzero_weight = other.minimum_nonzero_weight;
            self.minimum_coefficient = other.minimum_coefficient;
            self.minimum_word = other.minimum_word;
        }
        self.words_at_or_below_coordinate_weight
            .extend(other.words_at_or_below_coordinate_weight);
        self
    }
}

fn parse_word3(words: &[String; 3]) -> Result<Word3, Box<dyn Error>> {
    let mut answer = Word3::default();
    for (index, word) in words.iter().enumerate() {
        answer.0[index] = u64::from_str_radix(word.strip_prefix("0x").unwrap_or(word), 16)?;
    }
    Ok(answer)
}

fn word_from_coefficient(basis: &[Word3], coefficient: u64) -> Word3 {
    let mut word = Word3::default();
    let mut bits = coefficient;
    while bits != 0 {
        let bit = bits.trailing_zeros() as usize;
        word.xor_assign(basis[bit]);
        bits &= bits - 1;
    }
    word
}

fn enumerate_reference(basis: &[Word3], bits: usize) -> Stats {
    let mut stats = Stats::new();
    for coefficient in 0..(1u64 << bits) {
        stats.record(word_from_coefficient(basis, coefficient), coefficient);
    }
    stats
}

fn enumerate_gray(basis: &[Word3], bits: usize, low_bits: usize) -> Stats {
    let low_bits = low_bits.min(bits);
    let high_bits = bits - low_bits;
    let low_count = 1u64 << low_bits;
    let high_count = 1u64 << high_bits;

    (0..high_count)
        .into_par_iter()
        .fold(Stats::new, |mut stats, high_coefficient| {
            let base = word_from_coefficient(&basis[low_bits..bits], high_coefficient);
            let mut word = base;
            let mut low_coefficient = 0u64;
            for index in 0..low_count {
                let coefficient = (high_coefficient << low_bits) | low_coefficient;
                stats.record(word, coefficient);
                if index + 1 != low_count {
                    let flip = (index + 1).trailing_zeros() as usize;
                    word.xor_assign(basis[flip]);
                    low_coefficient ^= 1u64 << flip;
                }
            }
            stats
        })
        .reduce(Stats::new, Stats::merge)
}

fn main() -> Result<(), Box<dyn Error>> {
    let args = Args::parse();
    let input = args.input.unwrap_or_else(|| {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../notes/2026-08-04-c682-paper-iv-orbit-correspondence.json")
    });
    let certificate: Certificate = serde_json::from_str(&fs::read_to_string(&input)?)?;
    let rows = build_metacheck(&certificate.correspondence.left_neighbor_indices);
    let mut coordinate_columns: Vec<Word3> = certificate
        .correspondence
        .paired_coordinate_column_words_le
        .iter()
        .map(parse_word3)
        .collect::<Result<_, _>>()?;
    assert_eq!(coordinate_columns.len(), 78);
    assert!(coordinate_columns
        .iter()
        .all(|&column| column.weight() == 28));
    assert!(coordinate_columns
        .iter()
        .all(|&column| rows.iter().all(|&row| !row.dot(column))));
    let (rank, basis) = kernel_basis(rows.clone());
    assert_eq!(rank, 145);
    assert_eq!(basis.len(), 37);
    assert!(basis
        .iter()
        .all(|&vector| rows.iter().all(|&row| !row.dot(vector))));
    assert!(args.bits <= basis.len() && args.bits < 63);

    if let Some(threads) = args.threads {
        rayon::ThreadPoolBuilder::new()
            .num_threads(threads)
            .build_global()?;
    }

    if !args.no_self_check {
        let check_bits = args.self_check_bits.min(args.bits);
        let reference = enumerate_reference(&basis, check_bits);
        let optimized = enumerate_gray(&basis, check_bits, args.low_bits);
        assert_eq!(optimized.counts, reference.counts);
        assert_eq!(
            optimized.minimum_nonzero_weight,
            reference.minimum_nonzero_weight
        );
        assert_eq!(optimized.minimum_coefficient, reference.minimum_coefficient);
        assert_eq!(optimized.minimum_word, reference.minimum_word);
        eprintln!("self_check_bits={check_bits} PASS");
    }

    let started = Instant::now();
    let stats = enumerate_gray(&basis, args.bits, args.low_bits);
    let elapsed = started.elapsed();
    let total: u64 = stats.counts.iter().sum();
    assert_eq!(total, 1u64 << args.bits);
    assert_eq!(stats.counts[0], 1);
    if args.bits == basis.len() {
        assert_eq!(stats.counts[28], 78);
        assert!(stats.counts[1..28].iter().all(|&count| count == 0));
        let mut minimum_words: Vec<Word3> = stats
            .words_at_or_below_coordinate_weight
            .iter()
            .map(|&(word, _)| word)
            .collect();
        minimum_words.sort_by_key(|word| word.0);
        minimum_words.dedup();
        coordinate_columns.sort_by_key(|word| word.0);
        coordinate_columns.dedup();
        assert_eq!(minimum_words, coordinate_columns);
        for weight in 0..=LENGTH {
            assert_eq!(stats.counts[weight], stats.counts[LENGTH - weight]);
        }
    }

    let weight_enumerator: Vec<_> = stats
        .counts
        .iter()
        .enumerate()
        .filter(|&(_, &count)| count != 0)
        .map(|(weight, &count)| json!({"weight": weight, "count": count}))
        .collect();
    let result = json!({
        "schema": "c682-paper-iv-frame-metacode-enumerator-v1",
        "source_schema": certificate.schema,
        "length": LENGTH,
        "dimension": basis.len(),
        "rank": rank,
        "enumerated_basis_bits": args.bits,
        "enumerated_codewords": total,
        "minimum_nonzero_weight": stats.minimum_nonzero_weight,
        "minimum_witness_coefficient": format!("0x{:x}", stats.minimum_coefficient),
        "minimum_witness_words_le": stats.minimum_word.0.map(|word| format!("0x{word:016x}")),
        "minimum_words_equal_paired_coordinate_columns": args.bits == basis.len(),
        "weight_enumerator": weight_enumerator,
        "trusted_inputs": ["notes/2026-08-04-c682-paper-iv-orbit-correspondence.json"],
    });
    let encoded = serde_json::to_string_pretty(&result)? + "\n";
    print!("{encoded}");
    eprintln!(
        "enumerated_codewords={total} elapsed_seconds={:.6} threads={}",
        elapsed.as_secs_f64(),
        rayon::current_num_threads()
    );
    if let Some(output) = args.output {
        fs::write(output, &encoded)?;
    }
    if let Some(check) = args.check {
        assert_eq!(fs::read_to_string(check)?, encoded);
        eprintln!("tracked_certificate=PASS");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gray_matches_from_scratch_on_small_basis() {
        let basis = [
            Word3([0b0011, 0, 0]),
            Word3([0b0101, 0, 0]),
            Word3([0b1001, 0, 0]),
        ];
        let reference = enumerate_reference(&basis, basis.len());
        let gray = enumerate_gray(&basis, basis.len(), 2);
        assert_eq!(gray.counts, reference.counts);
        assert_eq!(
            gray.minimum_nonzero_weight,
            reference.minimum_nonzero_weight
        );
        assert_eq!(gray.minimum_coefficient, reference.minimum_coefficient);
        assert_eq!(gray.minimum_word, reference.minimum_word);
    }
}
