#!/usr/bin/env python3
"""Generate the manuscript's compact R6 exceptional-orbit table."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


PAPER = Path(__file__).resolve().parent.parent
SOURCE = PAPER / "supplement" / "CLASSIFICATION-RECORDS.json"
OUTPUT = PAPER / "frontmatter" / "r6-exceptional-table.tex"
FIELDS = (7, 8, 9, 11, 13)


def representative(values: list[int]) -> str:
    return r"\([" + ":".join(str(value) for value in values) + r"]\)"


def factor_type(value: str | None) -> str:
    return "--" if value is None else rf"\({value}\)"


def render() -> str:
    records = json.loads(SOURCE.read_text())["records"]["R6"]
    families = records["exceptional_semilinear_normal_forms"]
    lines = [
        r"% Generated by supplement/build_r6_paper_table.py from the",
        r"% hash-pinned supplement/CLASSIFICATION-RECORDS.json.",
        r"\begin{longtable}{c l r r c r l}",
        r"\caption{Exceptional redundancy-six classes.  Each row is one",
        r"projective-semilinear class.  The columns give a canonical syndrome",
        r"representative, the size and stabilizer order of each constituent",
        r"\(\PGL_2(q)\)-orbit, the number \(\phi\) of such orbits fused by",
        r"coefficient Frobenius, the shared-root pair count \(E\), and the binary-quintic",
        r"factor type \(\tau_5\) in odd characteristic.}",
        r"\label{tab:r6-exceptional}\\",
        r"\toprule",
        r"\(q\) & representative & \(|\mathcal O|\) & \(|G_f|\) & \(\phi\) & \(E\) & \(\tau_5\)\\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"\(q\) & representative & \(|\mathcal O|\) & \(|G_f|\) & \(\phi\) & \(E\) & \(\tau_5\)\\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endfoot",
    ]
    pgl_counts: list[int] = []
    point_counts: list[int] = []
    for q in FIELDS:
        block = families[str(q)]
        normal_forms = block["normal_forms"]
        pgl_counts.append(sum(row["frobenius_cycle_length"] for row in normal_forms))
        point_counts.append(
            sum(
                row["frobenius_cycle_length"] * row["pgl2_orbit_size"]
                for row in normal_forms
            )
        )
        for row in normal_forms:
            lines.append(
                " & ".join(
                    (
                        str(q),
                        representative(row["normal_form"]),
                        str(row["pgl2_orbit_size"]),
                        str(row["pgl2_stabilizer_order"]),
                        str(row["frobenius_cycle_length"]),
                        str(row["shared_root_collision_energy"]),
                        factor_type(row.get("binary_quintic_factor_type")),
                    )
                )
                + r"\\"
            )
    lines.extend(
        (
            r"\end{longtable}",
            r"\noindent For \(q=8\), integers are binary polynomial-basis codes",
            r"with \(\alpha^3=\alpha+1\); for \(q=9\), they are ternary",
            r"polynomial-basis codes with \(\alpha^2=-1\).  Thus",
            rf"\(\sum\phi={tuple(pgl_counts)}\) and",
            rf"\(\sum\phi|\mathcal O|={tuple(point_counts)}\),",
            r"in the field order \(7,8,9,11,13\).",
            "",
        )
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            raise SystemExit(f"stale generated table: {OUTPUT.relative_to(PAPER)}")
        print("R6 manuscript table: PASS")
        return
    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT.relative_to(PAPER)}")


if __name__ == "__main__":
    main()
