//! Exact lock counts for finite actions on a cyclic carrier.
//!
//! A labeling invariant under an action is constant on every action orbit.
//! Therefore, at a cyclic shift `s`, positions whose endpoints occupy the same
//! orbit cannot change.  [`CyclicOrbitLocks`] compiles the orbit partition once
//! and exposes allocation-free shift queries.

use std::error::Error;
use std::fmt::{self, Display, Formatter};

use crate::group_action::FinitePermutationAction;

/// Failure while compiling a cyclic action into its orbit partition.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CyclicOrbitLockError<E> {
    EmptyCarrier,
    CarrierTooLarge,
    Action(E),
    NotPermutation { generator: u32 },
}

impl<E: Display> Display for CyclicOrbitLockError<E> {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyCarrier => formatter.write_str("cyclic carrier must be nonempty"),
            Self::CarrierTooLarge => {
                formatter.write_str("cyclic carrier exceeds addressable storage")
            }
            Self::Action(error) => write!(formatter, "action evaluation failed: {error}"),
            Self::NotPermutation { generator } => {
                write!(
                    formatter,
                    "action generator {generator} is not a permutation"
                )
            }
        }
    }
}

impl<E: Error + 'static> Error for CyclicOrbitLockError<E> {}

/// A compiled action-orbit partition on `Z / n Z`.
///
/// The hot representation is one dense orbit ID per carrier position.  Shift
/// queries traverse two contiguous slice pairs, avoiding remainder operations
/// and allocating no memory.
#[repr(C)]
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CyclicOrbitLocks {
    orbit_of: Box<[u32]>,
    orbit_sizes: Box<[u32]>,
}

#[cfg(target_pointer_width = "64")]
const _: () = assert!(
    std::mem::size_of::<CyclicOrbitLocks>() == 32 && std::mem::align_of::<CyclicOrbitLocks>() == 8
);

impl CyclicOrbitLocks {
    /// Compile the orbits generated by a finite permutation action.
    pub fn compile<A>(action: &A) -> Result<Self, CyclicOrbitLockError<A::Error>>
    where
        A: FinitePermutationAction,
    {
        let point_count = action.point_count();
        if point_count == 0 {
            return Err(CyclicOrbitLockError::EmptyCarrier);
        }
        let count =
            usize::try_from(point_count).map_err(|_| CyclicOrbitLockError::CarrierTooLarge)?;
        let mut parent: Vec<u32> = (0..point_count).collect();
        let mut rank = vec![0_u8; count];
        let mut seen = vec![false; count];

        for generator in 0..action.generator_count() {
            seen.fill(false);
            for point in 0..point_count {
                let image = action
                    .apply(generator, point)
                    .map_err(CyclicOrbitLockError::Action)?;
                if image >= point_count || seen[image as usize] {
                    return Err(CyclicOrbitLockError::NotPermutation { generator });
                }
                seen[image as usize] = true;
                union(&mut parent, &mut rank, point, image);
            }
        }

        let mut root_to_orbit = vec![u32::MAX; count];
        let mut orbit_of = vec![0_u32; count];
        let mut orbit_sizes = Vec::<u32>::new();
        for point in 0..point_count {
            let root = find_compress(&mut parent, point);
            let slot = &mut root_to_orbit[root as usize];
            let orbit = if *slot == u32::MAX {
                let orbit = u32::try_from(orbit_sizes.len())
                    .map_err(|_| CyclicOrbitLockError::CarrierTooLarge)?;
                *slot = orbit;
                orbit_sizes.push(0);
                orbit
            } else {
                *slot
            };
            orbit_of[point as usize] = orbit;
            orbit_sizes[orbit as usize] += 1;
        }

        Ok(Self {
            orbit_of: orbit_of.into_boxed_slice(),
            orbit_sizes: orbit_sizes.into_boxed_slice(),
        })
    }

    #[inline]
    pub fn point_count(&self) -> u32 {
        self.orbit_of.len() as u32
    }

    #[inline]
    pub fn orbit_count(&self) -> u32 {
        self.orbit_sizes.len() as u32
    }

    pub fn orbit_sizes(&self) -> &[u32] {
        &self.orbit_sizes
    }

    #[inline]
    pub fn orbit_of(&self, point: u32) -> Option<u32> {
        self.orbit_of.get(point as usize).copied()
    }

    /// Count positions locked by the given cyclic shift.
    ///
    /// Returns `None` when `shift >= point_count()`.  The query allocates no
    /// memory and contains no integer remainder in its scan loop.
    #[inline]
    pub fn locked_at_shift(&self, shift: u32) -> Option<u32> {
        let shift = usize::try_from(shift).ok()?;
        let count = self.orbit_of.len();
        if shift >= count {
            return None;
        }
        let split = count - shift;
        let direct = self.orbit_of[..split]
            .iter()
            .zip(&self.orbit_of[shift..])
            .filter(|(left, right)| left == right)
            .count();
        let wrapped = self.orbit_of[split..]
            .iter()
            .zip(&self.orbit_of[..shift])
            .filter(|(left, right)| left == right)
            .count();
        u32::try_from(direct + wrapped).ok()
    }

    /// Fill lock counts for shifts `0..point_count()` without allocation.
    pub fn write_locked_counts(&self, output: &mut [u32]) -> bool {
        if output.len() != self.orbit_of.len() {
            return false;
        }
        for (shift, slot) in output.iter_mut().enumerate() {
            *slot = self
                .locked_at_shift(shift as u32)
                .expect("enumerated shift is in range");
        }
        true
    }

    /// Maximum total number of changed positions across invariant labelings.
    ///
    /// Each labeling can change at most `n - locked_at_shift(shift)` positions.
    #[inline]
    pub fn joint_change_upper_bound(&self, shift: u32, labeling_count: u32) -> Option<u64> {
        let locked = self.locked_at_shift(shift)?;
        Some(u64::from(self.point_count() - locked) * u64::from(labeling_count))
    }

    /// Whether the orbit lock rules out a required joint change count.
    #[inline]
    pub fn excludes_joint_change(
        &self,
        shift: u32,
        labeling_count: u32,
        required: u64,
    ) -> Option<bool> {
        Some(self.joint_change_upper_bound(shift, labeling_count)? < required)
    }
}

#[inline]
fn find_compress(parent: &mut [u32], mut point: u32) -> u32 {
    let mut root = point;
    while parent[root as usize] != root {
        root = parent[root as usize];
    }
    while parent[point as usize] != point {
        let next = parent[point as usize];
        parent[point as usize] = root;
        point = next;
    }
    root
}

#[inline]
fn union(parent: &mut [u32], rank: &mut [u8], left: u32, right: u32) {
    let left = find_compress(parent, left);
    let right = find_compress(parent, right);
    if left == right {
        return;
    }
    let left_rank = rank[left as usize];
    let right_rank = rank[right as usize];
    if left_rank < right_rank {
        parent[left as usize] = right;
    } else {
        parent[right as usize] = left;
        if left_rank == right_rank {
            rank[left as usize] += 1;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::convert::Infallible;

    struct HalfTurn;

    impl FinitePermutationAction for HalfTurn {
        type Error = Infallible;

        fn point_count(&self) -> u32 {
            6
        }

        fn generator_count(&self) -> u32 {
            1
        }

        fn apply(&self, generator: u32, point: u32) -> Result<u32, Self::Error> {
            assert_eq!(generator, 0);
            Ok((point + 3) % 6)
        }
    }

    #[test]
    fn half_turn_has_expected_lock_counts() {
        let locks = CyclicOrbitLocks::compile(&HalfTurn).unwrap();
        assert_eq!(locks.orbit_sizes(), &[2, 2, 2]);
        let mut counts = [0_u32; 6];
        assert!(locks.write_locked_counts(&mut counts));
        assert_eq!(counts, [6, 0, 0, 6, 0, 0]);
        assert_eq!(locks.joint_change_upper_bound(3, 2), Some(0));
        assert_eq!(locks.excludes_joint_change(3, 2, 1), Some(true));
    }
}
