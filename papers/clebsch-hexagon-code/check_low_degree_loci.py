#!/usr/bin/env python3
"""Exact low-degree curve-locus census for uncovered sets in PG(2,11).

The fifteen canonical six-arcs are regenerated by ``check_global_conic_gap``;
no representative or uncovered set is supplied as opaque input.  For each
class this checker computes the ranks of the homogeneous evaluation maps in
degrees one through six and the least degree of a vanishing form.  It then
exhausts the projective vanishing kernels needed to decide whether a class
which has no lower-degree exact locus is the complete rational zero set of a
curve of degree at most five.  The exceptional degree-six kernel of C12 is
also exhausted.

Finally, every projective linear and quadratic form over F_11 is tested as a
possible divisor of the exact C02 quartic and C04 quintic.  These tests are
enough for irreducibility in degrees four and five.

Polynomial coefficient vectors use the monomial order

    x^a y^b z^c,  a = 0..d, b = 0..d-a, c = d-a-b.

All arithmetic is exact and uses only the Python standard library.
"""

from __future__ import annotations

from itertools import product
from math import comb

import check_global_conic_gap as gap


P = 11

# (rank, nullity) in degrees 1, ..., 5, in canonical-class order; degree six
# is recorded separately below so the low-degree exactness boundary is clear.
EXPECTED_RANK_NULLITY = (
    ((3, 0), (6, 0), (10, 0), (15, 0), (19, 2)),
    ((3, 0), (6, 0), (10, 0), (14, 1), (17, 4)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (18, 3)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (18, 3)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (19, 2)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (19, 2)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (20, 1)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (19, 2)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (19, 2)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (18, 3)),
    ((3, 0), (6, 0), (10, 0), (13, 2), (15, 6)),
    ((3, 0), (6, 0), (10, 0), (15, 0), (21, 0)),
    ((3, 0), (6, 0), (10, 0), (14, 1), (17, 4)),
    ((3, 0), (6, 0), (10, 0), (14, 1), (17, 4)),
    ((3, 0), (5, 1), (7, 3), (9, 6), (11, 10)),
)
EXPECTED_MINIMUM_DEGREES = (5, 4, 5, 5, 5, 5, 5, 5, 5, 5, 4, 6, 4, 4, 2)
EXPECTED_U_SIZES = (20, 18, 19, 19, 20, 20, 21, 20, 20, 19, 16, 22, 18, 18, 12)
EXPECTED_DEGREE6_RANK_NULLITY = (
    (20, 8), (18, 10), (19, 9), (19, 9), (20, 8),
    (20, 8), (21, 7), (20, 8), (20, 8), (19, 9),
    (16, 12), (22, 6), (18, 10), (18, 10), (12, 16),
)

# Canonically scaled coefficient vectors in the monomial order documented
# above.  The C12 value is filled from the independently regenerated sextic
# kernel and is checked to have exactly U(C12) as its 22 rational zeros.
EXPECTED_EXACT_FORMS = {
    2: (1, 0, 6, 5, 8, 3, 4, 3, 8, 6, 10, 9, 10, 8, 8),
    4: (1, 3, 0, 5, 7, 1, 5, 6, 5, 8, 6, 3, 7, 6, 0, 0, 6, 7, 9, 2, 10),
    15: (1, 2, 5, 2, 8, 5),
}


def homogeneous_monomials(degree: int) -> tuple[tuple[int, int, int], ...]:
    return tuple(
        (a, b, degree - a - b)
        for a in range(degree + 1)
        for b in range(degree + 1 - a)
    )


def point_features(
    point: gap.Point, monomials: tuple[tuple[int, int, int], ...]
) -> tuple[int, ...]:
    x, y, z = point
    return tuple(
        pow(x, a, P) * pow(y, b, P) * pow(z, c, P) % P
        for a, b, c in monomials
    )


def rref(matrix: list[tuple[int, ...]]) -> tuple[list[list[int]], list[int]]:
    work = [[entry % P for entry in row] for row in matrix]
    if not work:
        return work, []
    row_count = len(work)
    column_count = len(work[0])
    pivots: list[int] = []
    row = 0
    for column in range(column_count):
        pivot = next(
            (candidate for candidate in range(row, row_count) if work[candidate][column]),
            None,
        )
        if pivot is None:
            continue
        work[row], work[pivot] = work[pivot], work[row]
        inverse = pow(work[row][column], P - 2, P)
        work[row] = [entry * inverse % P for entry in work[row]]
        for other in range(row_count):
            if other == row or not work[other][column]:
                continue
            coefficient = work[other][column]
            work[other] = [
                (left - coefficient * right) % P
                for left, right in zip(work[other], work[row])
            ]
        pivots.append(column)
        row += 1
        if row == row_count:
            break
    return work, pivots


def nullspace(matrix: list[tuple[int, ...]]) -> tuple[tuple[int, ...], ...]:
    reduced, pivots = rref(matrix)
    column_count = len(matrix[0])
    free = [column for column in range(column_count) if column not in pivots]
    basis = []
    for free_column in free:
        vector = [0] * column_count
        vector[free_column] = 1
        for row, pivot in enumerate(pivots):
            vector[pivot] = -reduced[row][free_column] % P
        basis.append(tuple(vector))
    return tuple(basis)


def projective_vectors(dimension: int):
    """Normalized nonzero vectors in PG(dimension-1,11)."""
    for pivot in range(dimension):
        prefix = (0,) * pivot + (1,)
        for tail in product(range(P), repeat=dimension - pivot - 1):
            yield prefix + tail


def linear_combination(
    coefficients: tuple[int, ...], basis: tuple[tuple[int, ...], ...]
) -> tuple[int, ...]:
    return tuple(
        sum(coefficients[i] * basis[i][j] for i in range(len(basis))) % P
        for j in range(len(basis[0]))
    )


def canonical_polynomial(coefficients: tuple[int, ...]) -> tuple[int, ...]:
    pivot = next(entry for entry in coefficients if entry)
    scale = pow(pivot, P - 2, P)
    return tuple(scale * entry % P for entry in coefficients)


FEATURE_CACHE: dict[int, tuple[tuple[int, ...], ...]] = {}


def all_point_features(degree: int) -> tuple[tuple[int, ...], ...]:
    if degree not in FEATURE_CACHE:
        monomials = homogeneous_monomials(degree)
        FEATURE_CACHE[degree] = tuple(
            point_features(point, monomials) for point in gap.POINTS
        )
    return FEATURE_CACHE[degree]


def evaluation_matrix(point_mask: int, degree: int) -> list[tuple[int, ...]]:
    features = all_point_features(degree)
    return [features[index] for index in range(len(gap.POINTS)) if point_mask >> index & 1]


def polynomial_zero_mask(coefficients: tuple[int, ...], degree: int) -> int:
    mask = 0
    for index, features in enumerate(all_point_features(degree)):
        if sum(a * b for a, b in zip(coefficients, features)) % P == 0:
            mask |= 1 << index
    return mask


def exact_forms(
    point_mask: int, degree: int, kernel: tuple[tuple[int, ...], ...]
) -> tuple[tuple[int, ...], ...]:
    forms = []
    for coordinates in projective_vectors(len(kernel)):
        form = canonical_polynomial(linear_combination(coordinates, kernel))
        if polynomial_zero_mask(form, degree) == point_mask:
            forms.append(form)
    return tuple(sorted(set(forms)))


def multiplication_matrix(
    divisor: tuple[int, ...], divisor_degree: int, total_degree: int
) -> list[tuple[int, ...]]:
    divisor_monomials = homogeneous_monomials(divisor_degree)
    quotient_monomials = homogeneous_monomials(total_degree - divisor_degree)
    product_monomials = homogeneous_monomials(total_degree)
    product_index = {monomial: index for index, monomial in enumerate(product_monomials)}
    matrix = [[0] * len(quotient_monomials) for _ in product_monomials]
    for left_index, left in enumerate(divisor_monomials):
        if not divisor[left_index]:
            continue
        for right_index, right in enumerate(quotient_monomials):
            product_monomial = tuple(left[i] + right[i] for i in range(3))
            row = product_index[product_monomial]
            matrix[row][right_index] = (
                matrix[row][right_index] + divisor[left_index]
            ) % P
    return [tuple(row) for row in matrix]


def solve_linear_system(
    matrix: list[tuple[int, ...]], target: tuple[int, ...]
) -> tuple[int, ...] | None:
    augmented = [tuple(row) + (entry,) for row, entry in zip(matrix, target)]
    reduced, pivots = rref(augmented)
    variable_count = len(matrix[0])
    if any(
        all(row[column] == 0 for column in range(variable_count))
        and row[variable_count] != 0
        for row in reduced
    ):
        return None
    solution = [0] * variable_count
    for row, pivot in enumerate(pivots):
        if pivot < variable_count:
            solution[pivot] = reduced[row][variable_count]
    return tuple(solution)


def has_factor_of_degree(coefficients: tuple[int, ...], degree: int, factor_degree: int) -> bool:
    factor_dimension = len(homogeneous_monomials(factor_degree))
    tested = 0
    for factor in projective_vectors(factor_dimension):
        tested += 1
        matrix = multiplication_matrix(factor, factor_degree, degree)
        if solve_linear_system(matrix, coefficients) is not None:
            return True
    expected = (P**factor_dimension - 1) // (P - 1)
    assert tested == expected
    return False


def format_polynomial(coefficients: tuple[int, ...], degree: int) -> str:
    terms = []
    for coefficient, (a, b, c) in zip(coefficients, homogeneous_monomials(degree)):
        if not coefficient:
            continue
        powers = "".join(
            variable if exponent == 1 else f"{variable}^{exponent}"
            for variable, exponent in (("x", a), ("y", b), ("z", c))
            if exponent
        )
        terms.append(str(coefficient) if not powers else f"{coefficient}{powers}")
    return " + ".join(terms)


def derivative(
    coefficients: tuple[int, ...], degree: int, variable: int
) -> tuple[int, ...]:
    target_monomials = homogeneous_monomials(degree - 1)
    target_index = {monomial: index for index, monomial in enumerate(target_monomials)}
    result = [0] * len(target_monomials)
    for coefficient, monomial in zip(coefficients, homogeneous_monomials(degree)):
        exponent = monomial[variable]
        if not coefficient or not exponent:
            continue
        reduced = list(monomial)
        reduced[variable] -= 1
        index = target_index[tuple(reduced)]
        result[index] = coefficient * exponent % P
    return tuple(result)


def rational_singular_points(
    coefficients: tuple[int, ...], degree: int
) -> tuple[gap.Point, ...]:
    derivatives = tuple(derivative(coefficients, degree, variable) for variable in range(3))
    features = all_point_features(degree - 1)
    return tuple(
        point
        for point, values in zip(gap.POINTS, features)
        if all(sum(a * b for a, b in zip(partial, values)) % P == 0 for partial in derivatives)
    )


def affine_translation(
    coefficients: tuple[int, ...], degree: int, x0: int, y0: int
) -> dict[tuple[int, int], int]:
    """Coefficients after x=X+x0, y=Y+y0, z=1."""
    result: dict[tuple[int, int], int] = {}
    for coefficient, (a, b, _c) in zip(coefficients, homogeneous_monomials(degree)):
        for i in range(a + 1):
            for j in range(b + 1):
                contribution = (
                    coefficient
                    * comb(a, i)
                    * pow(x0, a - i, P)
                    * comb(b, j)
                    * pow(y0, b - j, P)
                )
                result[i, j] = (result.get((i, j), 0) + contribution) % P
    return result


def main() -> None:
    representatives = gap.frame_normalized_census()
    classes: dict[gap.Arc, list[gap.Arc]] = {}
    for arc in representatives:
        classes.setdefault(gap.projective_class_key(arc), []).append(arc)
    canonical_arcs = sorted(classes)
    assert len(canonical_arcs) == 15

    kernels: dict[tuple[int, int], tuple[tuple[int, ...], ...]] = {}
    point_masks: dict[int, int] = {}
    observed_table = []
    observed_degree6 = []
    observed_minimum_degrees = []
    print("class|U_size|degree:(rank,nullity),d=1..6|minimum_degree")
    for class_index, arc in enumerate(canonical_arcs, start=1):
        point_mask = gap.uncovered_mask(arc)
        point_masks[class_index] = point_mask
        assert point_mask.bit_count() == EXPECTED_U_SIZES[class_index - 1]
        row = []
        minimum_degree = None
        for degree in range(1, 7):
            matrix = evaluation_matrix(point_mask, degree)
            kernel = nullspace(matrix)
            kernels[class_index, degree] = kernel
            rank = len(homogeneous_monomials(degree)) - len(kernel)
            if degree <= 5:
                row.append((rank, len(kernel)))
            else:
                observed_degree6.append((rank, len(kernel)))
            if minimum_degree is None and kernel:
                minimum_degree = degree
        assert minimum_degree is not None
        observed_table.append(tuple(row))
        observed_minimum_degrees.append(minimum_degree)
        metrics = ",".join(
            f"{degree}:({rank},{nullity})"
            for degree, (rank, nullity) in enumerate(row, start=1)
        )
        degree6_rank, degree6_nullity = observed_degree6[-1]
        print(
            f"C{class_index:02d}|{point_mask.bit_count()}|{metrics},"
            f"6:({degree6_rank},{degree6_nullity})|{minimum_degree}"
        )
    assert tuple(observed_table) == EXPECTED_RANK_NULLITY
    assert tuple(observed_degree6) == EXPECTED_DEGREE6_RANK_NULLITY
    assert tuple(observed_minimum_degrees) == EXPECTED_MINIMUM_DEGREES

    # Exhaust every relevant kernel through degree five.  Once a class is an
    # exact lower-degree locus, higher-degree equations add no new class to
    # the classification and are deliberately not enumerated.
    exact_by_class: dict[int, tuple[int, tuple[tuple[int, ...], ...]]] = {}
    for class_index in range(1, 16):
        for degree in range(1, 6):
            kernel = kernels[class_index, degree]
            if not kernel:
                continue
            assert len(kernel) <= 6 or class_index == 15
            if len(kernel) > 6:
                # C15 was already certified as an exact conic at degree two.
                assert class_index in exact_by_class
                break
            forms = exact_forms(point_masks[class_index], degree, kernel)
            if forms:
                exact_by_class[class_index] = (degree, forms)
                break

    assert set(exact_by_class) == {2, 4, 15}
    assert exact_by_class[2] == (4, (EXPECTED_EXACT_FORMS[2],))
    assert exact_by_class[4] == (5, (EXPECTED_EXACT_FORMS[4],))
    assert exact_by_class[15] == (2, (EXPECTED_EXACT_FORMS[15],))

    # C12 is the only class with no equation through degree five.  Its full
    # six-dimensional sextic kernel is still small enough to exhaust.
    c12_exact = exact_forms(point_masks[12], 6, kernels[12, 6])
    assert len(c12_exact) == 16
    c12_witness = c12_exact[0]
    assert polynomial_zero_mask(c12_witness, 6) == point_masks[12]

    print("exact_minimal_loci=C02:4,C04:5,C12:6,C15:2")
    for class_index, degree, form in (
        (2, 4, EXPECTED_EXACT_FORMS[2]),
        (4, 5, EXPECTED_EXACT_FORMS[4]),
        (12, 6, c12_witness),
        (15, 2, EXPECTED_EXACT_FORMS[15]),
    ):
        assert polynomial_zero_mask(form, degree) == point_masks[class_index]
        print(
            f"C{class_index:02d}_degree={degree}"
            f" coefficients={form} equation={format_polynomial(form, degree)}"
        )
    print(f"C12_exact_sextics={len(c12_exact)}")

    assert rational_singular_points(EXPECTED_EXACT_FORMS[2], 4) == ()
    assert rational_singular_points(EXPECTED_EXACT_FORMS[4], 5) == ((1, 8, 10),)
    assert rational_singular_points(c12_witness, 6) == ()
    c04_local = affine_translation(EXPECTED_EXACT_FORMS[4], 5, 10, 3)
    assert all(coefficient == 0 for (i, j), coefficient in c04_local.items() if i + j < 2)
    assert (c04_local[2, 0], c04_local[1, 1], c04_local[0, 2]) == (1, 4, 5)
    tangent_discriminant = (4 * 4 - 4 * 1 * 5) % P
    assert tangent_discriminant == 7
    assert pow(tangent_discriminant, (P - 1) // 2, P) == P - 1
    print("C02_rational_singularities=0 C12_rational_singularities=0")
    print("C04_rational_singularity=(10:3:1) tangent_cone=X^2+4XY+5Y^2 nonsplit=True")

    c15_linear_factor = has_factor_of_degree(EXPECTED_EXACT_FORMS[15], 2, 1)
    assert not c15_linear_factor
    print("C15_linear_factors=0/133 nonsingular_conic=True")

    # A reducible quartic or quintic has a factor of degree at most two.
    for class_index, degree in ((2, 4), (4, 5)):
        form = EXPECTED_EXACT_FORMS[class_index]
        linear_factor = has_factor_of_degree(form, degree, 1)
        quadratic_factor = has_factor_of_degree(form, degree, 2)
        assert not linear_factor
        assert not quadratic_factor
        print(
            f"C{class_index:02d}_linear_factors=0/133"
            f" quadratic_factors=0/177156 irreducible_over_F11=True"
        )

    print("all assertions passed")


if __name__ == "__main__":
    main()
