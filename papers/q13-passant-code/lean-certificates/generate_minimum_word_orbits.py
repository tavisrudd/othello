#!/usr/bin/env python3
"""Generate the four minimum-word orbits of the normalized projective action."""

from __future__ import annotations

import argparse
from pathlib import Path


Q = 13
OUTPUT = Path(__file__).parent / "PassantCodeQ13" / "MinimumWords" / "OrbitData.lean"

REPRESENTATIVES = {
    "orbitSymmetricSupports": [
        (1, 0, 2), (1, 0, 5), (1, 1, 3), (1, 1, 6),
        (1, 2, 9), (1, 3, 4), (1, 3, 7), (1, 6, 5),
        (1, 8, 7), (1, 11, 2), (1, 11, 12), (1, 12, 6),
    ],
    "orbitDihedralASupports": [
        (1, 0, 2), (1, 0, 5), (1, 1, 3), (1, 1, 6),
        (1, 2, 12), (1, 5, 5), (1, 6, 2), (1, 6, 4),
        (1, 8, 4), (1, 8, 6), (1, 9, 9), (1, 12, 9),
    ],
    "orbitDihedralBSupports": [
        (1, 0, 2), (1, 3, 2), (1, 4, 5), (1, 1, 8),
        (1, 4, 8), (1, 1, 7), (1, 7, 12), (1, 3, 3),
        (1, 9, 11), (1, 10, 11), (1, 0, 5), (1, 8, 7),
    ],
    "orbitDihedralCSupports": [
        (1, 0, 2), (1, 0, 7), (1, 1, 6), (1, 2, 11),
        (1, 3, 7), (1, 3, 11), (1, 5, 1), (1, 5, 10),
        (1, 6, 4), (1, 7, 2), (1, 8, 1), (1, 8, 6),
    ],
}

DOCSTRINGS = {
    "orbitSymmetricSupports":
        "Orbit of the representative with stabilizer isomorphic to the symmetric group on four "
        "letters.",
    "orbitDihedralASupports":
        "Orbit of the first representative with a dihedral stabilizer of order 24.",
    "orbitDihedralBSupports":
        "Orbit of the second representative with a dihedral stabilizer of order 24.",
    "orbitDihedralCSupports":
        "Orbit of the third representative with a dihedral stabilizer of order 24.",
}


def projective_triples() -> list[tuple[int, int, int]]:
    return (
        [(1, y, z) for y in range(Q) for z in range(Q)]
        + [(0, 1, z) for z in range(Q)]
        + [(0, 0, 1)]
    )


def internal_points() -> list[tuple[int, int, int]]:
    squares = {value * value % Q for value in range(1, Q)}
    return [
        point for point in projective_triples()
        if (point[1] * point[1] - point[0] * point[2]) % Q not in squares | {0}
    ]


def projective_matrices() -> list[tuple[int, int, int, int]]:
    candidates = (
        [(1, b, c, d) for b in range(Q) for c in range(Q) for d in range(Q)]
        + [(0, 1, c, d) for c in range(Q) for d in range(Q)]
        + [(0, 0, 1, d) for d in range(Q)]
        + [(0, 0, 0, 1)]
    )
    return [m for m in candidates if (m[0] * m[3] - m[1] * m[2]) % Q != 0]


def normalize(point: tuple[int, int, int]) -> tuple[int, int, int]:
    x, y, z = (value % Q for value in point)
    if x != 0:
        inverse = pow(x, Q - 2, Q)
        return (1, y * inverse % Q, z * inverse % Q)
    if y != 0:
        inverse = pow(y, Q - 2, Q)
        return (0, 1, z * inverse % Q)
    return (0, 0, 1)


def act(matrix: tuple[int, int, int, int], point: tuple[int, int, int]) -> tuple[int, int, int]:
    a, b, c, d = matrix
    x, y, z = point
    return normalize((
        a * a * x + 2 * a * b * y + b * b * z,
        a * c * x + (a * d + b * c) * y + b * d * z,
        c * c * x + 2 * c * d * y + d * d * z,
    ))


def support_orbit(representative: list[tuple[int, int, int]]) -> list[int]:
    index = {point: position for position, point in enumerate(internal_points())}
    failure = len(index)
    orbit: list[int] = []
    for matrix in projective_matrices():
        code = 0
        for point in representative:
            code |= 1 << index.get(act(matrix, point), failure)
        if code not in orbit:
            orbit.append(code)
    return orbit


def render(name: str, orbit: list[int]) -> str:
    lines = []
    for start in range(0, len(orbit), 3):
        lines.append("  " + ", ".join(str(code) for code in orbit[start:start + 3]) + ",")
    body = "\n".join(lines).rstrip(",")
    return f"/-- {DOCSTRINGS[name]} -/\ndef {name} : List Nat := [\n{body}]\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the tracked module differs from the generated text")
    arguments = parser.parse_args()

    blocks = []
    for name, representative in REPRESENTATIVES.items():
        orbit = support_orbit(representative)
        if len(orbit) != 91:
            raise SystemExit(f"{name}: expected 91 supports, computed {len(orbit)}")
        blocks.append(render(name, orbit))

    text = (
        "/-!\n"
        "# Generated minimum-word orbit supports\n"
        "\n"
        "This file is generated by `generate_minimum_word_orbits.py`.  Each list holds the 91\n"
        "supports of one orbit of the symmetric-square action of `PGL(2,13)` on the displayed\n"
        "weight-twelve representative, in the order in which the normalized projective matrices\n"
        "first produce them.  A support is the 78-bit natural number whose set bits are the\n"
        "positions of its points in the normalized internal-point order.  Lean checks each list\n"
        "against the projective action itself; the lists carry no trust of their own.\n"
        "-/\n"
        "\n"
        "namespace PassantCodeQ13.MinimumWords\n"
        "\n"
        + "\n".join(blocks)
        + "\nend PassantCodeQ13.MinimumWords\n"
    )

    if arguments.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise SystemExit(f"{OUTPUT} differs from the generated text")
        return
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
