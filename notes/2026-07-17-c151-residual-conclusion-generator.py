#!/usr/bin/env python3
"""Generate C151 normalized-row conclusions from dispatchers and canonical bounds."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import sys
from pathlib import Path
from typing import Sequence


HERE = Path(__file__).resolve().parent
CLASS_LINK_GENERATOR = HERE / "2026-07-16-c151-residual-class-link-generator.py"
EXPECTED_ROWS = 46056
EXPECTED_PAYLOAD_LEAVES = 1071


def load_class_link_generator():
    spec = importlib.util.spec_from_file_location(
        "c151_residual_class_link_generator", CLASS_LINK_GENERATOR
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class_link = load_class_link_generator()
transport = class_link.transport


def source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def conclusion_module_name(payload_leaf) -> str:
    return f"C_{payload_leaf.module_name}"


def generated_header(csv_hash: str, transport_fnv: int, description: str) -> str:
    return f"""/-!
# Generated C151 normalized-row conclusions

DO NOT EDIT: generated by `notes/2026-07-17-c151-residual-conclusion-generator.py`.

* payload: {description}
* canonical CSV SHA256: `{csv_hash}`
* cover-generator SHA256: `{transport.cover.source_sha256()}`
* transport-generator SHA256: `{transport.source_sha256()}`
* class-link generator SHA256: `{class_link.source_sha256()}`
* conclusion-generator SHA256: `{source_sha256()}`
* transport FNV-1a-64: `{transport_fnv:016x}`
-/
"""


def render_leaf(
    payload_leaf,
    link_modules: Sequence[str],
    csv_hash: str,
    transport_fnv: int,
) -> str:
    imports = [
        f"import RelativeConicArcs.Q25ResidualDispatchData.D_{payload_leaf.module_name}\n"
    ]
    imports.extend(
        f"import RelativeConicArcs.Q25ResidualClassLinkData.{name}\n"
        for name in link_modules
    )
    count = len(payload_leaf.records)
    branches = []
    for row in payload_leaf.records:
        if row.valid:
            prefix = transport.theorem_prefix(row)
            branches.append(
                "  · exact ValidRowPayload.source_card_ge_of_canonical hvalid hraw\n"
                f"      Q25ResidualClassLinkData.{prefix}_canonical_card_ge_32\n"
            )
        else:
            branches.append(
                "  · exact (BadRowPayload.not_rawCap hvalid hraw).elim\n"
            )
    return "".join(imports) + f"""
{generated_header(
        csv_hash,
        transport_fnv,
        f"{count} normalized-row conclusions in {payload_leaf.module_name}",
    )}

namespace RelativeConicArcs
namespace Q25ResidualConclusionData

open Q25Coordinates Q25MinimumMask Q25ResidualCoverData

set_option maxHeartbeats 300000000
set_option maxRecDepth 100000

theorem conclude{payload_leaf.module_name} (i : Fin {count})
    (hraw : RawCap (rowConfig ⟨{payload_leaf.b}, by decide⟩
      ({payload_leaf.array_name}[i]).c)) :
    32 ≤ (legalOrbitSet (rowConfig ⟨{payload_leaf.b}, by decide⟩
      ({payload_leaf.array_name}[i]).c)).card := by
  have hvalid := Q25ResidualDispatchData.dispatch{payload_leaf.module_name} i
  fin_cases i
{"".join(branches)}
end Q25ResidualConclusionData
end RelativeConicArcs
"""


def render_aggregate(
    module_names: Sequence[str], csv_hash: str, transport_fnv: int, description: str
) -> str:
    imports = "".join(
        f"import RelativeConicArcs.Q25ResidualConclusionData.{name}\n"
        for name in module_names
    )
    return imports + "\n" + generated_header(csv_hash, transport_fnv, description)


def write_modules(output_directory: Path, csv: Path) -> None:
    if output_directory.name != "Q25ResidualConclusionData":
        raise ValueError("output directory must be named Q25ResidualConclusionData")
    rows, _ = transport.cover.read_records(csv)
    assert len(rows) == EXPECTED_ROWS
    payloads = transport.payload_leaves(rows)
    assert len(payloads) == EXPECTED_PAYLOAD_LEAVES
    valid_records = tuple(
        transport.transport_permutation(row) for row in rows if row.valid
    )
    transport_leaves = transport.transport_leaves(rows, valid_records)
    links_by_payload: dict[tuple[int, int, int], list[str]] = {}
    for leaf in transport_leaves:
        payload = leaf.payload_leaf
        key = (payload.b, payload.first_c, payload.last_c)
        links_by_payload.setdefault(key, []).append(class_link.link_module_name(leaf))

    leaf_names = tuple(conclusion_module_name(payload) for payload in payloads)
    aggregate_names = tuple(f"B_{b:03d}" for b in range(6, 309))
    expected = {f"{name}.lean" for name in (*leaf_names, *aggregate_names)} | {"All.lean"}
    output_directory.mkdir(parents=True, exist_ok=True)
    unexpected = sorted(
        path.name for path in output_directory.iterdir() if path.name not in expected
    )
    if unexpected:
        raise RuntimeError(f"refusing output directory with unexpected entries: {unexpected}")

    csv_hash = transport.cover.sha256(csv)
    transport_fnv = transport.transport_fnv1a64(valid_records)
    written = []
    for payload, leaf_name in zip(payloads, leaf_names, strict=True):
        key = (payload.b, payload.first_c, payload.last_c)
        path = output_directory / f"{leaf_name}.lean"
        path.write_text(
            render_leaf(payload, tuple(links_by_payload.get(key, ())), csv_hash, transport_fnv),
            encoding="utf-8",
        )
        written.append(path)

    for b, aggregate_name in zip(range(6, 309), aggregate_names, strict=True):
        modules = tuple(
            name
            for payload, name in zip(payloads, leaf_names, strict=True)
            if payload.b == b
        )
        path = output_directory / f"{aggregate_name}.lean"
        path.write_text(
            render_aggregate(
                modules,
                csv_hash,
                transport_fnv,
                f"import-only aggregate for all normalized-row conclusions with b = {b}",
            ),
            encoding="utf-8",
        )
        written.append(path)

    all_path = output_directory / "All.lean"
    all_path.write_text(
        render_aggregate(
            aggregate_names,
            csv_hash,
            transport_fnv,
            "import-only aggregate for all 46,056 normalized-row conclusions",
        ),
        encoding="utf-8",
    )
    written.append(all_path)

    assert len(written) == len(expected)
    print(
        f"generated_files={len(written)} conclusion_modules={len(payloads)} "
        f"b_aggregates={len(aggregate_names)} rows={len(rows)}"
    )
    print(f"max_rows_per_module={max(len(payload.records) for payload in payloads)}")
    print(f"generated_source_bytes={sum(path.stat().st_size for path in written)}")
    print(f"output_directory={output_directory.resolve()}")
    print(f"csv_sha256={csv_hash}")
    print(f"class_link_generator_sha256={class_link.source_sha256()}")
    print(f"conclusion_generator_sha256={source_sha256()}")
    print(f"transport_fnv1a64={transport_fnv:016x}")
    print(f"generated_tree_sha256={transport.tree_sha256(written, output_directory)}")
    print("recommended_first_leaf=C_R_031_C_032_081.lean")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path)
    parser.add_argument("--write-lean-modules", required=True, type=Path)
    args = parser.parse_args()
    write_modules(args.write_lean_modules, args.csv)


if __name__ == "__main__":
    main()
