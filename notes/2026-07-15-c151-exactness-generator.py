#!/usr/bin/env python3
"""Generate the five-row C151 exactness tail from shared obstruction masks."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path
from typing import Sequence

HERE = Path(__file__).resolve().parent
SHARED_GENERATOR = HERE / "2026-07-15-c151-shared-line-composition.py"


def load_shared_generator():
    spec = importlib.util.spec_from_file_location("c151_shared_line_composition", SHARED_GENERATOR)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


shared = load_shared_generator()


def source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def mask_or(masks: Sequence[Sequence[int]]) -> tuple[int, int, int, int, int]:
    words = [0] * 5
    for mask in masks:
        for index, word in enumerate(mask):
            words[index] |= word
    return tuple(words)  # type: ignore[return-value]


def build_exact_rows():
    dataset = shared.linegen.build_dataset()
    rows, carriers = shared.build_rows(dataset)
    selected = []
    for class_index, record in enumerate(rows):
        if record.legal_count != 32:
            continue
        secant = mask_or(tuple(dataset.lines[w.line_index].words for w in record.secants))
        for number in range(310):
            covered = (
                shared.mask_bit(record.legal, number)
                or shared.mask_bit(record.freshness, number)
                or shared.mask_bit(secant, number)
                or shared.mask_bit(record.carrier, number)
            )
            assert covered
        selected.append((class_index, record, secant))
    assert [(index, record.row) for index, record, _ in selected] == [
        (65, (5, 58, 169)),
        (267, (5, 61, 81)),
        (445, (5, 63, 141)),
        (772, (5, 97, 109)),
        (1002, (5, 113, 194)),
    ]
    return dataset, rows, carriers, tuple(selected)


def semantic_payload(selected) -> list[dict[str, object]]:
    return [
        {
            "class_index": class_index,
            "row": record.row,
            "allowed": record.legal,
            "fresh_blocked": record.freshness,
            "secant_blocked": secant,
            "carrier_blocked": record.carrier,
        }
        for class_index, record, secant in selected
    ]


def data_sha256(selected) -> str:
    encoded = json.dumps(semantic_payload(selected), sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(encoded).hexdigest()


def lean_mask(mask: Sequence[int]) -> str:
    return "![" + ", ".join(map(str, mask)) + "]"


def leaf_name(class_index: int) -> str:
    first = (class_index // 5) * 5
    last = min(first + 4, 1188)
    return f"C_{first:04d}_{last:04d}"


def exact_leaf_module_name(class_index: int) -> str:
    return f"C_{class_index:04d}"


def render_leaf(class_index, record, secant, exactness_data_sha256: str) -> str:
    stem = f"class{class_index:04d}"
    pieces = [
        "import RelativeConicArcs.Q25ExactnessComposition\n",
        f"import RelativeConicArcs.Q25RowCompositionData.{leaf_name(class_index)}\n",
        "\n/-!\n",
        f"# Generated exactness tail for minimum Q25 residual class {class_index:04d}\n\n",
        "DO NOT EDIT: generated by `notes/2026-07-15-c151-exactness-generator.py`.\n\n",
        f"* generator SHA256: `{source_sha256()}`\n",
        f"* exactness data SHA256: `{exactness_data_sha256}`\n",
        f"* shared generator SHA256: `{shared.source_sha256()}`\n",
        "-/\n\n",
        "namespace RelativeConicArcs\n",
        "namespace Q25ExactMinimumRows\n\n",
        "open Q25PairCertificate Q25MinimumMask Q25ExactnessComposition Q25RowCompositionData\n\n",
        "set_option maxHeartbeats 300000000\n",
        "set_option maxRecDepth 100000\n\n",
        f"def {stem}FreshBlocked : OrbitMask := {lean_mask(record.freshness)}\n\n",
        f"def {stem}SecantBlocked : OrbitMask := {lean_mask(secant)}\n\n",
        f"def {stem}CarrierBlocked : OrbitMask := {lean_mask(record.carrier)}\n\n",
        f"theorem {stem}ComplementCovered :\n",
        f"    MaskComplementCovered {stem}Allowed {stem}FreshBlocked\n",
        f"      {stem}SecantBlocked {stem}CarrierBlocked := by\n",
        "  decide\n\n",
        f"theorem {stem}FreshBlockedSound :\n",
        f"    FreshBlockedSound {stem}A {stem}B {stem}C {stem}FreshBlocked := by\n",
        "  decide\n\n",
        f"theorem {stem}SecantBlockedSound :\n",
        f"    SecantBlockedSound {stem}A {stem}B {stem}C\n",
        f"      {stem}SecantCertificate.lineNumber {stem}SecantBlocked := by\n",
        "  decide\n\n",
        f"theorem {stem}CarrierBlockedSound :\n",
        f"    CarrierBlockedSound {stem}A {stem}B {stem}C {stem}CarrierBlocked := by\n",
        "  decide\n\n",
        f"theorem {stem}ExactnessCertificate :\n",
        f"    RowExactnessCertificate {stem}A {stem}B {stem}C {stem}Allowed\n",
        f"      {stem}FreshBlocked {stem}SecantBlocked {stem}CarrierBlocked\n",
        f"      {stem}SecantCertificate where\n",
        f"  cover := {stem}ComplementCovered\n",
        f"  fresh := {stem}FreshBlockedSound\n",
        f"  secant := {stem}SecantBlockedSound\n",
        f"  carrier := {stem}CarrierBlockedSound\n\n",
        f"theorem {stem}LegalOrbitSet_card_le_32 :\n",
        f"    (legalOrbitSet (normalizedConfig {stem}A {stem}B {stem}C)).card ≤ 32 := by\n",
        "  calc\n",
        f"    _ ≤ (maskOrbitSet {stem}Allowed).card :=\n",
        f"      card_legalOrbitSet_le_maskOrbitSet {stem}ExactnessCertificate\n",
        "    _ = 32 := by decide\n\n",
        f"theorem {stem}LegalOrbitSet_card_eq_32 :\n",
        f"    (legalOrbitSet (normalizedConfig {stem}A {stem}B {stem}C)).card = 32 :=\n",
        f"  Nat.le_antisymm {stem}LegalOrbitSet_card_le_32\n",
        f"    {stem}LegalOrbitSet_card_ge_32\n\n",
        "end Q25ExactMinimumRows\n",
        "end RelativeConicArcs\n",
    ]
    return "".join(pieces)


def render_all(selected) -> str:
    return "".join(
        f"import RelativeConicArcs.Q25ExactMinimumRows.{exact_leaf_module_name(index)}\n"
        for index, _, _ in selected
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-lean-dir", type=Path, metavar="Q25ExactMinimumRows")
    args = parser.parse_args()
    _, _, _, selected = build_exact_rows()
    exactness_data_sha256 = data_sha256(selected)
    leaves = {
        exact_leaf_module_name(index): render_leaf(index, record, secant, exactness_data_sha256)
        for index, record, secant in selected
    }
    aggregate = render_all(selected)
    print(f"minimum_classes={len(selected)}")
    print("class_indices=" + ",".join(str(index) for index, _, _ in selected))
    print(f"source_sha256={source_sha256()}")
    print(f"data_sha256={exactness_data_sha256}")
    for module_name, rendered in leaves.items():
        print(f"{module_name}_bytes={len(rendered.encode())}")
        print(f"{module_name}_sha256={hashlib.sha256(rendered.encode()).hexdigest()}")
    print(f"All_bytes={len(aggregate.encode())}")
    print(f"All_sha256={hashlib.sha256(aggregate.encode()).hexdigest()}")
    if args.write_lean_dir is not None:
        if args.write_lean_dir.name != "Q25ExactMinimumRows":
            raise ValueError("--write-lean-dir must name Q25ExactMinimumRows")
        args.write_lean_dir.mkdir(parents=True, exist_ok=True)
        for module_name, rendered in leaves.items():
            (args.write_lean_dir / f"{module_name}.lean").write_text(rendered, encoding="utf-8")
        (args.write_lean_dir / "All.lean").write_text(aggregate, encoding="utf-8")


if __name__ == "__main__":
    main()
