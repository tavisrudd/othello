#!/usr/bin/env python3
"""Generate C151 equality classification from checked residual payloads."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import sys
from pathlib import Path
from typing import Sequence


HERE = Path(__file__).resolve().parent
CONCLUSION_GENERATOR = HERE / "2026-07-17-c151-residual-conclusion-generator.py"
EXPECTED_ROWS = 46_056
MINIMUM_CLASSES = (65, 267, 445, 772, 1002)


def load_conclusion_generator():
    spec = importlib.util.spec_from_file_location(
        "c151_residual_conclusion_generator_for_equality", CONCLUSION_GENERATOR
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


conclusion = load_conclusion_generator()
transport = conclusion.transport


def source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def generated_header(csv_hash: str, description: str) -> str:
    return f"""/-!
# Generated C151 equality classification

DO NOT EDIT: generated by `notes/2026-07-17-c151-residual-equality-generator.py`.

* payload: {description}
* canonical CSV SHA256: `{csv_hash}`
* conclusion-generator SHA256: `{conclusion.source_sha256()}`
* equality-generator SHA256: `{source_sha256()}`
-/
"""


def equality_module_name(payload) -> str:
    return f"E_{payload.module_name}"


def class_bound_module(class_index: int) -> str:
    first = class_index // 10 * 10
    last = min(first + 9, 1188)
    return f"C_{first:04d}_{last:04d}"


def minimum_tactic(class_index: int) -> str:
    position = MINIMUM_CLASSES.index(class_index)
    return "  · " + "right; " * position + "left\n" if position < 4 else "  · right; right; right; right\n"


def render_valid_branch(row) -> str:
    prefix = transport.theorem_prefix(row)
    payload = f"Q25ResidualTransportData.{prefix}Payload"
    transport_valid = f"Q25ResidualTransportData.{prefix}_transportValid"
    class_link = f"Q25ResidualClassLinkData.{prefix}_canonicalClassLink"
    if row.class_index in MINIMUM_CLASSES:
        return minimum_tactic(row.class_index) + f"""    refine ⟨⟨⟨{payload}.y, {transport_valid}.1⟩,
      ⟨{payload}.z, {transport_valid}.2.1⟩⟩, ?_⟩
    change (rowConfig ⟨{row.b}, by decide⟩ {payload}.c).map
      (residualEmbedding {payload}.y {payload}.z
        {transport_valid}.1 {transport_valid}.2.1) = _
    rw [ValidRowPayload.map_eq_canonicalConfig {transport_valid}, {class_link}]
    rfl
"""
    return f"""  · have hge : 33 ≤ (legalOrbitSet (rowConfig ⟨{row.b}, by decide⟩
        {payload}.c)).card := by
      apply ValidRowPayload.source_card_ge_of_canonical {transport_valid} hraw
      rw [{class_link}]
      exact Q25ClassBoundData.class{row.class_index:04d}LegalOrbitSet_card_ge_33
    omega
"""


def render_leaf(payload, csv_hash: str) -> str:
    imports = [
        "import RelativeConicArcs.Q25ResidualEquality\n",
        "import RelativeConicArcs.Q25ResidualConclusionData."
        f"{conclusion.conclusion_module_name(payload)}\n",
    ]
    bound_modules = sorted(
        {
            class_bound_module(row.class_index)
            for row in payload.records
            if row.valid and row.class_index not in MINIMUM_CLASSES
        }
    )
    imports.extend(
        f"import RelativeConicArcs.Q25ClassBoundData.{name}\n"
        for name in bound_modules
    )
    branches = []
    for row in payload.records:
        if row.valid:
            branches.append(render_valid_branch(row))
        else:
            branches.append("  · exact (BadRowPayload.not_rawCap hvalid hraw).elim\n")
    count = len(payload.records)
    return "".join(imports) + f"""
{generated_header(csv_hash, f"{count} equality conclusions in {payload.module_name}")}

namespace RelativeConicArcs
namespace Q25ResidualEqualityData

open Q25Coordinates Q25MinimumMask Q25ResidualAction Q25ResidualCoverData
  Q25ResidualEquality

set_option maxHeartbeats 300000000
set_option maxRecDepth 100000

theorem classify{payload.module_name} (i : Fin {count})
    (hraw : RawCap (rowConfig ⟨{payload.b}, by decide⟩ ({payload.array_name}[i]).c))
    (heq : (legalOrbitSet
      (rowConfig ⟨{payload.b}, by decide⟩ ({payload.array_name}[i]).c)).card = 32) :
    IsMinimumResidualClass
      (rowConfig ⟨{payload.b}, by decide⟩ ({payload.array_name}[i]).c) := by
  have hvalid := Q25ResidualDispatchData.dispatch{payload.module_name} i
  fin_cases i
{"".join(branches)}
end Q25ResidualEqualityData
end RelativeConicArcs
"""


def render_b(b: int, payloads: Sequence[object], csv_hash: str) -> str:
    imports = "".join(
        f"import RelativeConicArcs.Q25ResidualEqualityData.{equality_module_name(p)}\n"
        for p in payloads
    )
    row_locations = {
        row.c: (payload.module_name, index)
        for payload in payloads
        for index, row in enumerate(payload.records)
    }
    assert set(row_locations) == set(range(b + 1, 310))
    branches = []
    for c in range(310):
        if c <= b:
            branches.append("  · simp at hbc\n")
        else:
            module_name, index = row_locations[c]
            branches.append(
                f"  · exact classify{module_name} ⟨{index}, by decide⟩ hraw heq\n"
            )
    return imports + f"""
{generated_header(csv_hash, f"equality dispatcher with b = {b}")}

namespace RelativeConicArcs
namespace Q25ResidualEqualityData

open Q25Coordinates Q25MinimumMask Q25ResidualCoverData Q25ResidualEquality

set_option maxHeartbeats 300000000
set_option maxRecDepth 100000

theorem classifyB_{b:03d} (c : Fin 310) (hbc : {b} < c.val)
    (hraw : RawCap (rowConfig ⟨{b}, by decide⟩ c))
    (heq : (legalOrbitSet (rowConfig ⟨{b}, by decide⟩ c)).card = 32) :
    IsMinimumResidualClass (rowConfig ⟨{b}, by decide⟩ c) := by
  fin_cases c
{"".join(branches)}
end Q25ResidualEqualityData
end RelativeConicArcs
"""


def render_all(csv_hash: str) -> str:
    imports = "".join(
        f"import RelativeConicArcs.Q25ResidualEqualityData.B_{b:03d}\n"
        for b in range(6, 309)
    )
    branches = []
    for b in range(310):
        if b < 6 or b == 309:
            branches.append("  · simp at hb hbc\n")
        else:
            branches.append(f"  · exact classifyB_{b:03d} c hbc hraw heq\n")
    return imports + f"""
{generated_header(csv_hash, "universal equality classification for normalized rows")}

namespace RelativeConicArcs
namespace Q25ResidualEqualityData

open Q25Coordinates Q25MinimumMask Q25ResidualCoverData Q25ResidualEquality

set_option maxHeartbeats 300000000
set_option maxRecDepth 100000

theorem classifyNormalizedRow (b c : Fin 310) (hb : 5 < b.val) (hbc : b.val < c.val)
    (hraw : RawCap (rowConfig b c))
    (heq : (legalOrbitSet (rowConfig b c)).card = 32) :
    IsMinimumResidualClass (rowConfig b c) := by
  fin_cases b
{"".join(branches)}
end Q25ResidualEqualityData
end RelativeConicArcs
"""


def write_modules(output_directory: Path, csv: Path) -> None:
    if output_directory.name != "Q25ResidualEqualityData":
        raise ValueError("output directory must be named Q25ResidualEqualityData")
    rows, _ = transport.cover.read_records(csv)
    assert len(rows) == EXPECTED_ROWS
    payloads = transport.payload_leaves(rows)
    csv_hash = transport.cover.sha256(csv)
    leaf_names = tuple(equality_module_name(payload) for payload in payloads)
    b_names = tuple(f"B_{b:03d}" for b in range(6, 309))
    expected = {f"{name}.lean" for name in (*leaf_names, *b_names)} | {"All.lean"}
    output_directory.mkdir(parents=True, exist_ok=True)
    unexpected = sorted(p.name for p in output_directory.iterdir() if p.name not in expected)
    if unexpected:
        raise RuntimeError(f"refusing output directory with unexpected entries: {unexpected}")

    written = []
    for payload, name in zip(payloads, leaf_names, strict=True):
        path = output_directory / f"{name}.lean"
        path.write_text(render_leaf(payload, csv_hash), encoding="utf-8")
        written.append(path)
    for b, name in zip(range(6, 309), b_names, strict=True):
        b_payloads = tuple(payload for payload in payloads if payload.b == b)
        path = output_directory / f"{name}.lean"
        path.write_text(render_b(b, b_payloads, csv_hash), encoding="utf-8")
        written.append(path)
    all_path = output_directory / "All.lean"
    all_path.write_text(render_all(csv_hash), encoding="utf-8")
    written.append(all_path)

    assert len(written) == len(expected)
    print(f"generated_files={len(written)} equality_leaves={len(payloads)}")
    print(f"b_dispatchers={len(b_names)} rows={len(rows)}")
    print(f"generated_source_bytes={sum(p.stat().st_size for p in written)}")
    print(f"output_directory={output_directory.resolve()}")
    print(f"csv_sha256={csv_hash}")
    print(f"equality_generator_sha256={source_sha256()}")
    print(f"generated_tree_sha256={transport.tree_sha256(written, output_directory)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path)
    parser.add_argument("--write-lean-modules", required=True, type=Path)
    args = parser.parse_args()
    write_modules(args.write_lean_modules, args.csv)


if __name__ == "__main__":
    main()
