#!/usr/bin/env python3
"""C912 -- the surface obligation, step (iii), in Serre-operator terms.

Two things are checked here.

(A) Which Serre relation the cubic threefold's residual component actually
    satisfies.  The frame-transport memo records Katzarkov--Kontsevich--Pantev--Yu's
    Example 6.21 as giving the graded minimal polynomial S^5 = [3], while
    Kuznetsov's fractional Calabi--Yau relation for the same category is
    S^3 = [5].  On the numerical Grothendieck group a shift [k] acts by (-1)^k,
    so the two readings make incompatible predictions, and the lattice decides.

(B) Whether the surface obligation can be phrased for admissible subcategories
    or must be phrased for atoms.  It must: a smooth rational surface already
    carries an admissible subcategory whose numerical Serre operator has the
    primitive sixth roots of unity as eigenvalues, so the weakened form of step
    (iii) is false.  The example is the pair generated by O_E(-1) and O_X on the
    blow-up of the projective plane at one point, E the exceptional curve.

Conventions for surfaces.  A class is written (r, v, c) for
ch = r + v + c[pt] with v in Pic tensor Q; the Picard lattice is given by its
Gram matrix and the canonical class by its coordinates.  Riemann--Roch reads
chi(E) = r chi(O_S) + (1/2) c_1(E).c_1(S) + c, and the Euler form is
chi(E,F) = int ch(E)^dual ch(F) td(S) with ^dual negating the odd part.
Numerical Serre operator: S = E^{-1}E^T for the Gram matrix E_ij = chi(e_i,e_j).
"""

from sympy import Rational, Matrix, Poly, symbols, factor_list, eye, simplify

lam, x = symbols('lam x')
PHI6 = Poly(lam**2 - lam + 1, lam)


def serre(E):
    return E.inv() * E.T


def charpoly(E):
    return Poly(serre(E).charpoly(lam).as_expr().expand(), lam)


def phi6_count(cp):
    return 2 * sum(m for f, m in factor_list(cp.as_expr(), lam)[1]
                   if Poly(f, lam) == PHI6)


# ---------------------------------------------------------------------------
# 0. The general rank-two exceptional pair.
# ---------------------------------------------------------------------------
Epair = Matrix([[1, x], [0, 1]])
cp_pair = Poly(simplify((Epair.inv() * Epair.T).charpoly(lam).as_expr()).expand(), lam)
print("Rank-two subcategory generated by an exceptional pair with chi(e1,e2) = x:")
print(f"  char poly of the numerical Serre operator = {cp_pair.as_expr()}")
print("  trace = 2 - x^2, det = 1; the eigenvalues are primitive sixth roots of")
print("  unity exactly when x^2 = 1, i.e. when consecutive exceptional objects")
print("  pair to +-1.  x = 0 gives (lam-1)^2, x^2 = 4 gives (lam+1)^2, and")
print("  x^2 > 4 gives real eigenvalues off the unit circle.")
print()


# ---------------------------------------------------------------------------
# 1. Cubic threefold: which relation holds on the numerical K-group.
# ---------------------------------------------------------------------------
# Euler Gram matrix of N(Ku(Y_3)) as derived from Riemann--Roch in
# 2026-08-15-c912-gm-genus-six-serre-check.py (row "CALIBRATION").
E_cubic = Matrix([[-1, -1], [-2, -3]])
S_cubic = serre(E_cubic)
order = next(k for k in range(1, 25) if (S_cubic ** k) == eye(2))
print("Cubic threefold, Kuznetsov component, numerical Serre operator:")
print(f"  S = {S_cubic.tolist()}, char poly = {charpoly(E_cubic).as_expr()}, order = {order}")
print(f"  S^3 = {(S_cubic ** 3).tolist()}   S^5 = {(S_cubic ** 5).tolist()}")
print("  On K-num a shift [k] acts by (-1)^k, so:")
print(f"    Kuznetsov's S^3 = [5] predicts S^3 = -I : {(S_cubic ** 3) == -eye(2)}")
print(f"    the memo's S^5 = [3] predicts S^5 = -I : {(S_cubic ** 5) == -eye(2)}")
print("  S^5 = [3] would force eigenvalues that are primitive tenth roots of")
print("  unity, contradicting the characteristic polynomial Phi_6 above and the")
print("  manuscript's own exponents -1/6, -5/6.")
print()


# ---------------------------------------------------------------------------
# 2. Surfaces.
# ---------------------------------------------------------------------------
class Surface:
    def __init__(self, name, gram, c1, chiO=1):
        self.name = name
        self.gram = Matrix(gram)
        self.c1 = Matrix(c1)
        self.chiO = Rational(chiO)

    def dot(self, u, v):
        return (Matrix(u).T * self.gram * Matrix(v))[0, 0]

    def chi(self, cls):
        r, v, c = cls
        return self.chiO * r + Rational(1, 2) * self.dot(v, self.c1) + c

    def mul(self, a, b):
        r1, v1, c1_ = a
        r2, v2, c2_ = b
        v = [r1 * v2[i] + r2 * v1[i] for i in range(len(v1))]
        return (r1 * r2, v, r1 * c2_ + r2 * c1_ + self.dot(v1, v2))

    @staticmethod
    def dual(cls):
        r, v, c = cls
        return (r, [-t for t in v], c)

    def euler(self, a, b):
        return self.chi(self.mul(self.dual(a), b))

    def knum_basis(self):
        n = self.gram.shape[0]
        out = [(Rational(1), [Rational(0)] * n, Rational(0))]
        for i in range(n):
            v = [Rational(1) if j == i else Rational(0) for j in range(n)]
            out.append((Rational(0), v, Rational(0)))
        out.append((Rational(0), [Rational(0)] * n, Rational(1)))
        return out


P2 = Surface("P^2", [[1]], [3])
Q = Surface("P^1 x P^1", [[0, 1], [1, 0]], [2, 2])
F1 = Surface("Bl_1 P^2", [[1, 0], [0, -1]], [3, -1])   # basis (H, E), E^2 = -1

print("Serre operator on the FULL numerical K-group of a surface:")
for S_ in (P2, Q, F1):
    B = S_.knum_basis()
    G = Matrix(len(B), len(B), lambda i, j: S_.euler(B[i], B[j]))
    cp = charpoly(G)
    print(f"  {S_.name}: char poly = {cp.as_expr()}, factored = "
          f"{factor_list(cp.as_expr(), lam)[1]}, primitive-sixth count = {phi6_count(cp)}")
print("  Structural reason: the Serre functor of a surface is (- tensor omega)[2],")
print("  and [2] acts by +1 on K-num, so the ambient operator is multiplication by")
print("  exp(K), which is unipotent.  Any primitive sixth eigenvalue therefore has")
print("  to come from a proper semiorthogonal component, never from the ambient.")
print()

# The counterexample to the weakened step (iii).
O_X = (Rational(1), [Rational(0), Rational(0)], Rational(0))
# ch(O_E(-1)) = (0, E, -E^2/2 + deg) = (0, E, 1/2 - 1) with E^2 = -1.
O_E_m1 = (Rational(0), [Rational(0), Rational(1)], Rational(-1, 2))
print("Blow-up of the projective plane at one point, E the exceptional curve:")
print(f"  chi(O_E(-1))            = {F1.chi(O_E_m1)}   (degree -1 on a rational curve)")
print(f"  chi(O_E(-1), O_E(-1))   = {F1.euler(O_E_m1, O_E_m1)}   (exceptional)")
print(f"  chi(O_X, O_X)           = {F1.euler(O_X, O_X)}   (exceptional)")
print(f"  chi(O_X, O_E(-1))       = {F1.euler(O_X, O_E_m1)}   (semiorthogonality of "
      f"<O_E(-1), O_X>)")
print(f"  chi(O_E(-1), O_X)       = {F1.euler(O_E_m1, O_X)}")
G2 = Matrix(2, 2, lambda i, j: F1.euler((O_E_m1, O_X)[i], (O_E_m1, O_X)[j]))
cp2 = charpoly(G2)
ord2 = next((k for k in range(1, 25) if (serre(G2) ** k) == eye(2)), None)
print(f"  Euler Gram = {G2.tolist()}, Serre operator = {serre(G2).tolist()}")
print(f"  char poly = {cp2.as_expr()}, order = {ord2}, "
      f"primitive-sixth count = {phi6_count(cp2)}")
print("  So an admissible subcategory of a smooth rational surface can have a")
print("  numerical Serre operator of order six.  Step (iii) is false for")
print("  admissible subcategories and must be stated for atoms; this subcategory")
print("  is not an atom, being generated by an exceptional pair and hence")
print("  decomposable into two rank-one pieces, each with Serre operator 1.")
