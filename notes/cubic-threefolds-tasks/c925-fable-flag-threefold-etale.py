#!/usr/bin/env python3
"""C925: the flag threefold Fl(1,2;C^3) (Mori--Mukai 2-32, the (1,1)
divisor in P^2 x P^2) is quantum-etale at the canonical point.

Presentation (Givental--Kim): QH*(Fl_3) = C[x1,x2,x3,q1,q2]/I with I
generated by the coefficients of the quantum characteristic polynomial
    det(lam - A) = lam^3 - e1 lam^2 + (e2 + q1 + q2) lam
                   - (e3 + q2 x1 + q1 x3),
i.e. I = (e1, e2 + q1 + q2, e3 + q2 x1 + q1 x3).  At the canonical point
q1 = q2 = 1 the scheme is: x1 + x2 + x3 = 0, e2 = -2, e3 = -(x1 + x3) = x2.

Checks (exact):
  1. dimension of the quotient is 6 = chi(Fl_3), at q = (1,1) and at the
     classical point q = (0,0);
  2. the q = (1,1) scheme consists of six distinct reduced points, computed
     in closed form: x2 must satisfy x2^3 - 3 x2 = 0, and for each of the
     three values of x2 the pair (x1, x3) solves a separable quadratic, so
     the algebra is a product of six fields -- etale;
  3. the trace form of the 6-dimensional quotient algebra at q = (1,1) has
     nonzero determinant (independent Gram computation of etaleness).

Consequence (with the blow-up proposition of the companion report): the
carrier ledger of MM 2-32 over any Iritani bulk-curve coefficient field is
a sum of simple sheets.

Replay:
    uv run --with sympy python3 \
      notes/cubic-threefolds-tasks/c925-fable-flag-threefold-etale.py
"""
import itertools

import sympy as sp

x1, x2, x3, lam = sp.symbols("x1 x2 x3 lam")
e1 = x1 + x2 + x3
e2 = x1 * x2 + x1 * x3 + x2 * x3
e3 = x1 * x2 * x3


def quotient_dim(q1, q2):
    ideal = [e1, e2 + q1 + q2, e3 + q2 * x1 + q1 * x3]
    G = sp.groebner(ideal, x1, x2, x3, order="grevlex")

    # standard monomials: those not divisible by any leading monomial
    def divisible(mon, lt):
        quo = sp.simplify(mon / lt)
        return quo.is_polynomial(x1, x2, x3) and \
            sp.denom(sp.together(quo)) == 1
    basis = []
    for exps in itertools.product(range(7), repeat=3):
        mon = x1 ** exps[0] * x2 ** exps[1] * x3 ** exps[2]
        if not any(divisible(mon, sp.LM(g, order="grevlex"))
                   for g in G.exprs):
            basis.append(mon)
    return G, basis


G0, basis0 = quotient_dim(0, 0)
assert len(basis0) == 6, basis0
G1, basis1 = quotient_dim(1, 1)
assert len(basis1) == 6, basis1
print("quotient dimensions: classical", len(basis0), ", canonical point",
      len(basis1), "(both equal chi(Fl_3) = 6)")

# ---- closed-form points at q = (1,1) -------------------------------------
# e1 = 0, e2 = -2, e3 = x2  =>  each xi is a root of t^3 - 2 t - x2, and
# substituting t = x2 gives x2^3 - 3 x2 = 0.
t = sp.symbols("t")
x2_poly = sp.expand((t**3 - 2 * t - t))          # t^3 - 3t
assert x2_poly == t**3 - 3 * t
count = 0
for v2 in sp.roots(sp.Poly(t**3 - 3 * t, t)):
    quo, rem = sp.div(t**3 - 2 * t - v2, t - v2, t)
    assert sp.simplify(rem) == 0, (v2, rem)
    quad = sp.Poly(sp.expand(quo), t)
    disc = sp.discriminant(quad)
    assert sp.simplify(disc) != 0, (v2, disc)
    count += 2          # ordered (x1, x3): the two root orderings
assert count == 6
print("q=(1,1) scheme: x2 in {0, +sqrt(3), -sqrt(3)}, each with a"
      " separable quadratic for (x1,x3): six distinct reduced points")

# ---- trace form ----------------------------------------------------------
mult = {}
for b in basis1:
    row = []
    for c in basis1:
        red = G1.reduce(sp.expand(b * c))[1]
        row.append(red)
    mult[b] = row
coords = {m: i for i, m in enumerate(basis1)}


def to_vec(poly):
    v = [sp.S(0)] * 6
    p = sp.Poly(sp.expand(poly), x1, x2, x3)
    for monom, coeff in p.terms():
        mon = x1 ** monom[0] * x2 ** monom[1] * x3 ** monom[2]
        assert mon in coords, (mon, poly)
        v[coords[mon]] += coeff
    return v


trace_gram = sp.zeros(6, 6)
for i, b in enumerate(basis1):
    for j, c in enumerate(basis1):
        # trace of multiplication by b*c
        prod = G1.reduce(sp.expand(b * c))[1]
        M = sp.zeros(6, 6)
        for k, d in enumerate(basis1):
            red = G1.reduce(sp.expand(prod * d))[1]
            for l, coeff in enumerate(to_vec(red)):
                M[l, k] = coeff
        trace_gram[i, j] = sp.trace(M)
det = sp.simplify(trace_gram.det())
assert det != 0, det
print("trace-form determinant at q=(1,1):", det, "(nonzero -> etale)")
print("Fl(1,2;3) = MM 2-32 is quantum-etale at the canonical point")
