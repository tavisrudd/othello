#!/usr/bin/env python3
"""C925: discharge (GS-carrier) for the rank-one b3=0 Fano threefolds.

The four smooth Fano threefolds with Picard rank one and b3 = 0 are P^3, the
quadric Q^3, V5 (= B5, the degree-five del Pezzo threefold, index two), and
V22.  (GS-carrier) asks that the even quantum algebra be semisimple at the
canonical small point; since each of these has H^even generated by the
hyperplane class, the algebra is C[c1*] on the rank-four cyclic basis, and
semisimplicity/etale-ness is exactly squarefreeness of the characteristic
polynomial of c1* at q = 1.

Periods (Coates--Corti--Galkin--Kasprzyk, arXiv:1303.3288, cached):
  P^3 : G = sum_d t^{4d} / (d!)^4
  Q^3 : G = sum_d t^{3d} (2d)! / (d!)^5
  V5  : G = sum_{l,m} (-1)^{l+m} t^{2l+2m} ((l+m)!)^3/((l!)^5 (m!)^5)
            (1 - 5(m-l) H_m)                      [their B5 section]
  V22 : Theorem F.1 on Gr(3,7) with d = 3, a=b=c=e=0, evaluated by the
        same degree-three truncation as the V16 computation; validated
        against the nine printed regularized coefficients.

Each series is run through the operator-guess / companion pipeline of
c925-fable-rank-one-exponents.py (imported unmodified).  For every variety
the script asserts gcd(charpoly, charpoly') = 1 at q = 1: the operator is
semisimple with distinct eigenvalues, hence QH is etale there, which is the
hypothesis of the Hensel closure of the b3=0 tail
(2026-08-23-c925-fable-b3zero-tail-a2-reduction.md, section 2).

Replay:
    uv run --with sympy python3 \
      notes/cubic-threefolds-tasks/c925-fable-gs-carrier-rank-one.py
"""
import importlib.util
import itertools
import sys
from fractions import Fraction as F
from math import factorial as fa

import sympy as sp
from sympy import Rational as Q

_dir = __file__.rsplit("/", 1)[0]
spec = importlib.util.spec_from_file_location(
    "rank_one", _dir + "/c925-fable-rank-one-exponents.py")
rank_one = importlib.util.module_from_spec(spec)
sys.modules["rank_one"] = rank_one
spec.loader.exec_module(rank_one)

N = 40

# ---------------- periods with closed formulas ----------------------------


def period_P3(n):
    G = [F(0)] * (n + 1)
    for d in range(0, n + 1, 4):
        G[d] = F(1, fa(d // 4) ** 4)
    return G


def period_Q3(n):
    G = [F(0)] * (n + 1)
    for d in range(0, n + 1, 3):
        G[d] = F(fa(2 * (d // 3)), fa(d // 3) ** 5)
    return G


def period_V5(n):
    H = [F(0)]
    for m in range(1, n + 1):
        H.append(H[-1] + F(1, m))
    G = [F(0)] * (n + 1)
    for l in range(n // 2 + 1):
        for m in range(n // 2 + 1 - l):
            d = 2 * (l + m)
            G[d] += (-1) ** (l + m) * F(fa(l + m) ** 3, fa(l) ** 5 * fa(m) ** 5) \
                * (1 - 5 * (m - l) * H[m])
    return G


# ---------------- V22 via Theorem F.1 (r=3, n=7, d=3) ---------------------
# Same degree-<=3 truncated ring trick as c925-fable-v16-exponents.py: the
# H^0 part of the Omega-quotient is the coefficient of p2 p3^2 in the
# total-degree-3 part.
MONS = [m for m in sorted(itertools.product(range(4), repeat=3))
        if sum(m) <= 3]
IDX = {m: i for i, m in enumerate(MONS)}
DIM = len(MONS)


def unit():
    v = [F(0)] * DIM
    v[IDX[(0, 0, 0)]] = F(1)
    return v


def mul_linear(v, const, coeffs):
    w = [x * const for x in v]
    for m, x in zip(MONS, v):
        if x == 0 or sum(m) == 3:
            continue
        for j in range(3):
            if coeffs[j]:
                mm = list(m)
                mm[j] += 1
                w[IDX[tuple(mm)]] += x * coeffs[j]
    return w


def mul(v, w):
    out = [F(0)] * DIM
    for m1, x in zip(MONS, v):
        if x == 0:
            continue
        for m2, y in zip(MONS, w):
            if y == 0:
                continue
            m = (m1[0] + m2[0], m1[1] + m2[1], m1[2] + m2[2])
            if sum(m) <= 3:
                out[IDX[m]] += x * y
    return out


def inv_linear(const, coeffs):
    c = F(const)
    out = [F(0)] * DIM
    term = unit()
    for _ in range(4):
        for i in range(DIM):
            out[i] += term[i] / c
        term = mul_linear(term, 0, [-x / c for x in coeffs])
    return out


def period_V22(n):
    nproj = 7          # ambient (P^6)^3
    # d-part: for each axis j, prod_{k=1..m} (p1+p2+p3 - p_j + k), cubed
    d_part = {}
    for j in range(3):
        coeffs = [F(1)] * 3
        coeffs[j] = F(0)
        acc = unit()
        d_part[(j, 0)] = acc
        for m in range(1, n + 1):
            acc = mul_linear(acc, m, coeffs)
            d_part[(j, m)] = acc
    den_part = {}
    for j in range(3):
        coeffs = [F(1) if t == j else F(0) for t in range(3)]
        acc = unit()
        den_part[(j, 0)] = acc
        for m in range(1, n + 1):
            invp = inv_linear(m, coeffs)
            pn = unit()
            for _ in range(nproj):
                pn = mul(pn, invp)
            acc = mul(acc, pn)
            den_part[(j, m)] = acc
    target = IDX[(0, 1, 2)]
    itw = [F(0)] * (n + 1)
    for l1 in range(n + 1):
        for l2 in range(n + 1 - l1):
            for l3 in range(n + 1 - l1 - l2):
                D = l1 + l2 + l3
                l = (l1, l2, l3)
                v = unit()
                for j in range(3):
                    cube = d_part[(j, D - l[j])]
                    v = mul(mul(mul(v, cube), cube), cube)
                    if l[j]:
                        v = mul(v, den_part[(j, l[j])])
                for (i, j) in [(0, 1), (0, 2), (1, 2)]:
                    coeffs = [F(0)] * 3
                    coeffs[j], coeffs[i] = F(1), F(-1)
                    v = mul_linear(v, l[j] - l[i], coeffs)
                itw[D] += v[target]
    assert itw[0] == 1
    alpha = -itw[1]
    return [sum(F(alpha) ** k / fa(k) * itw[d - k] for k in range(d + 1))
            for d in range(n + 1)]


# ---------------- pipeline: operator -> companion -> c1* at q=1 -----------


def gs_check(name, G, r, expect_reg):
    reg = [fa(d) * G[d] for d in range(len(expect_reg))]
    assert reg == [F(x) for x in expect_reg], (name, reg)
    S = G[::r]
    for degree in range(1, 7):
        p, k = rank_one.guess_operator(S, 4, degree)
        if p is not None:
            break
    assert p is not None and k == 1, (name, k)
    q, z = sp.symbols("q z")
    C = rank_one.companion_from_operator(p, 4, degree, r, q, z)
    U0 = (r * C).subs(z, 0).subs(q, 1)
    U0 = U0.applyfunc(sp.nsimplify)
    lam = sp.symbols("lam")
    cp = sp.expand(U0.charpoly(lam).as_expr())
    g = sp.gcd(cp, sp.diff(cp, lam))
    assert g.is_number and g != 0, (name, g)
    print(f"{name}: regularized coefficients match CCGK; "
          f"charpoly of c1* at q=1: {sp.factor(cp)}; squarefree -> "
          f"semisimple, QH etale at the canonical point")


gs_check("P^3", period_P3(N), 4, [1, 0, 0, 0, 24])
gs_check("Q^3", period_Q3(N), 3, [1, 0, 0, 12, 0, 0, 540])
gs_check("V5", period_V5(N), 2, [1, 0, 6, 0, 114, 0, 2940, 0, 87570])
gs_check("V22", period_V22(N), 1,
         [1, 0, 12, 60, 636, 5760, 58620, 604800, 6447420, 70022400])
print("(GS-carrier) holds for every rank-one b3=0 Fano threefold")
