#!/usr/bin/env python3
"""Generate C151 links from valid residual transports to literal composition classes."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import sys
from pathlib import Path
from typing import Sequence


HERE = Path(__file__).resolve().parent
TRANSPORT_GENERATOR = HERE / "2026-07-15-c151-residual-transport-generator.py"
EXPECTED_VALID_ROWS = 7044
EXPECTED_TRANSPORT_LEAVES = 1036
EXPECTED_CLASSES = 1189


def load_transport_generator():
    spec = importlib.util.spec_from_file_location(
        "c151_residual_transport_generator", TRANSPORT_GENERATOR
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


transport = load_transport_generator()


def source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def class_name(index: int) -> str:
    assert 0 <= index < EXPECTED_CLASSES
    return f"class{index:04d}"


def class_module_name(index: int) -> str:
    first = index // 5 * 5
    last = min(first + 4, EXPECTED_CLASSES - 1)
    return f"C_{first:04d}_{last:04d}"


def link_module_name(leaf) -> str:
    assert leaf.module_name.startswith("T_")
    return "L_" + leaf.module_name.removeprefix("T_")


def generated_header(csv_hash: str, transport_fnv: int, description: str) -> str:
    return f"""/-!
# Generated C151 residual canonical-class links

DO NOT EDIT: generated by `notes/2026-07-16-c151-residual-class-link-generator.py`.

* payload: {description}
* canonical CSV SHA256: `{csv_hash}`
* cover-generator SHA256: `{transport.cover.source_sha256()}`
* transport-generator SHA256: `{transport.source_sha256()}`
* class-link generator SHA256: `{source_sha256()}`
* transport FNV-1a-64: `{transport_fnv:016x}`
-/
"""


def render_record(record) -> str:
    row = record.row
    prefix = transport.theorem_prefix(row)
    cls = class_name(row.class_index)
    return f"""theorem {prefix}_canonicalClassLink :
    Q25ResidualTransportData.{prefix}Payload.canonicalConfig =
      normalizedConfig Q25RowCompositionData.{cls}A Q25RowCompositionData.{cls}B
        Q25RowCompositionData.{cls}C := by
  rfl

theorem {prefix}_canonical_card_ge_32 :
    32 ≤ (legalOrbitSet
      Q25ResidualTransportData.{prefix}Payload.canonicalConfig).card := by
  rw [{prefix}_canonicalClassLink]
  exact Q25RowCompositionData.{cls}LegalOrbitSet_card_ge_32

theorem {prefix}_source_card_ge_32
    (hsource : RawCap (rowConfig ⟨{row.b}, by decide⟩
      Q25ResidualTransportData.{prefix}Payload.c)) :
    32 ≤ (legalOrbitSet (rowConfig ⟨{row.b}, by decide⟩
      Q25ResidualTransportData.{prefix}Payload.c)).card := by
  exact ValidRowPayload.source_card_ge_of_canonical
    Q25ResidualTransportData.{prefix}_transportValid hsource
    {prefix}_canonical_card_ge_32

"""


def render_leaf(leaf, csv_hash: str, transport_fnv: int) -> str:
    class_modules = sorted(
        {class_module_name(record.row.class_index) for _, record in leaf.records}
    )
    imports = [
        f"import RelativeConicArcs.Q25ResidualTransportData.{leaf.module_name}\n"
    ]
    imports.extend(
        f"import RelativeConicArcs.Q25RowCompositionData.{name}\n"
        for name in class_modules
    )
    rows = [record.row for _, record in leaf.records]
    pieces = [
        "".join(imports),
        "\n",
        generated_header(
            csv_hash,
            transport_fnv,
            f"{len(rows)} class links ({rows[0].b},{rows[0].c}) through "
            f"({rows[-1].b},{rows[-1].c}), aligned to {leaf.module_name}",
        ),
        "\nnamespace RelativeConicArcs\n",
        "namespace Q25ResidualClassLinkData\n\n",
        "open Q25Coordinates Q25PairCertificate Q25MinimumMask Q25ResidualCoverData\n\n",
    ]
    pieces.extend(render_record(record) for _, record in leaf.records)
    pieces.extend(
        [
            "end Q25ResidualClassLinkData\n",
            "end RelativeConicArcs\n",
        ]
    )
    return "".join(pieces)


def render_aggregate(
    module_names: Sequence[str], csv_hash: str, transport_fnv: int, description: str
) -> str:
    imports = "".join(
        f"import RelativeConicArcs.Q25ResidualClassLinkData.{name}\n"
        for name in module_names
    )
    return imports + "\n" + generated_header(csv_hash, transport_fnv, description)


def write_modules(output_directory: Path, csv: Path) -> None:
    if output_directory.name != "Q25ResidualClassLinkData":
        raise ValueError("output directory must be named Q25ResidualClassLinkData")
    rows, _ = transport.cover.read_records(csv)
    records = tuple(transport.transport_permutation(row) for row in rows if row.valid)
    assert len(records) == EXPECTED_VALID_ROWS
    leaves = transport.transport_leaves(rows, records)
    assert len(leaves) == EXPECTED_TRANSPORT_LEAVES
    leaf_names = tuple(link_module_name(leaf) for leaf in leaves)
    aggregate_names = tuple(f"B_{b:03d}" for b in range(6, 309))
    expected = {f"{name}.lean" for name in (*leaf_names, *aggregate_names)} | {"All.lean"}
    output_directory.mkdir(parents=True, exist_ok=True)
    unexpected = sorted(path.name for path in output_directory.iterdir() if path.name not in expected)
    if unexpected:
        raise RuntimeError(f"refusing output directory with unexpected entries: {unexpected}")

    csv_hash = transport.cover.sha256(csv)
    transport_fnv = transport.transport_fnv1a64(records)
    written = []
    for leaf, name in zip(leaves, leaf_names, strict=True):
        path = output_directory / f"{name}.lean"
        path.write_text(render_leaf(leaf, csv_hash, transport_fnv), encoding="utf-8")
        written.append(path)

    for b, aggregate_name in zip(range(6, 309), aggregate_names, strict=True):
        modules = tuple(
            name
            for leaf, name in zip(leaves, leaf_names, strict=True)
            if leaf.payload_leaf.b == b
        )
        path = output_directory / f"{aggregate_name}.lean"
        path.write_text(
            render_aggregate(
                modules,
                csv_hash,
                transport_fnv,
                f"import-only aggregate for all canonical-class links with b = {b}",
            ),
            encoding="utf-8",
        )
        written.append(path)

    all_path = output_directory / "All.lean"
    all_path.write_text(
        render_aggregate(
            aggregate_names,
            csv_hash,
            transport_fnv,
            "import-only aggregate for all 7,044 canonical-class links",
        ),
        encoding="utf-8",
    )
    written.append(all_path)

    assert len(written) == len(expected)
    print(
        f"generated_files={len(written)} link_modules={len(leaves)} "
        f"b_aggregates={len(aggregate_names)} valid_rows={len(records)}"
    )
    print(f"max_links_per_module={max(len(leaf.records) for leaf in leaves)}")
    print(f"generated_source_bytes={sum(path.stat().st_size for path in written)}")
    print(f"output_directory={output_directory.resolve()}")
    print(f"csv_sha256={csv_hash}")
    print(f"transport_generator_sha256={transport.source_sha256()}")
    print(f"class_link_generator_sha256={source_sha256()}")
    print(f"transport_fnv1a64={transport_fnv:016x}")
    print(f"generated_tree_sha256={transport.tree_sha256(written, output_directory)}")
    print("recommended_first_leaf=L_031_C_032_081_V_00.lean")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path)
    parser.add_argument("--write-lean-modules", required=True, type=Path)
    args = parser.parse_args()
    write_modules(args.write_lean_modules, args.csv)


if __name__ == "__main__":
    main()
