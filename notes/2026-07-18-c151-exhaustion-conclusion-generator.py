#!/usr/bin/env python3
"""Generate the C151 per-row exhaustion disjunctions.

For every normalized row this emits

    33 <= (legalOrbitSet (rowConfig b c)).card \\/ IsMinimumResidualClass (rowConfig b c)

which `mem_minimumOrbitUnion_of_card_eq_32` turns into membership in the 1600-element union of the
five certified minimizer orbits.  Three branch shapes cover every row:

* a bad payload contradicts the assumed `RawCap`;
* a valid payload over a non-minimizer class transports the strict class bound back to its source
  row, using the `Q25RowCompositionStrictData` bound directly -- `fin_cases` inlines the payload
  structure literal, and `.canonicalConfig` of that literal is definitionally the class triple, so
  `exact` unifies without any per-row link theorem;
* a valid payload over one of the five minimizer classes lands on the representative definitionally,
  so `rfl` supplies the equality that `isMinimumResidualClass_of_transport` needs.

The committed `>= 32` closure is untouched; this is a parallel tree at threshold 33.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import sys
from pathlib import Path
from typing import Sequence


HERE = Path(__file__).resolve().parent
STRICT_GENERATOR = HERE / "2026-07-18-c151-strict-class-bound-generator.py"
TRANSPORT_GENERATOR = HERE / "2026-07-15-c151-residual-transport-generator.py"
EXPECTED_ROWS = 46_056
EXPECTED_PAYLOAD_LEAVES = 1_071
EXPECTED_VALID_ROWS = 7_044
MINIMIZER_CLASSES = (65, 267, 445, 772, 1002)


def load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


strict = load(STRICT_GENERATOR, "c151_strict_class_bound_generator")
transport = load(TRANSPORT_GENERATOR, "c151_residual_transport_generator")


def source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def conclusion_module_name(payload_leaf) -> str:
    return f"C_{payload_leaf.module_name}"


def minimizer_witness(class_index: int) -> str:
    """`rfl` at the correct disjunct of the five-way minimizer equality."""
    position = MINIMIZER_CLASSES.index(class_index)
    term = "rfl" if position == len(MINIMIZER_CLASSES) - 1 else "Or.inl rfl"
    for _ in range(position):
        term = f"Or.inr ({term})"
    return term


def generated_header(csv_hash: str, mask_digest: str, description: str) -> str:
    return f"""/-!
# Generated C151 per-row exhaustion disjunctions

DO NOT EDIT: generated by `notes/2026-07-18-c151-exhaustion-conclusion-generator.py`.

* payload: {description}
* canonical CSV SHA256: `{csv_hash}`
* mask-stream digest: `{mask_digest}`
* cover-generator SHA256: `{transport.cover.source_sha256()}`
* transport-generator SHA256: `{transport.source_sha256()}`
* strict-bound generator SHA256: `{strict.source_sha256()}`
* exhaustion-conclusion generator SHA256: `{source_sha256()}`
-/
"""


def render_leaf(payload_leaf, csv_hash: str, mask_digest: str) -> str:
    classes = sorted(
        {row.class_index for row in payload_leaf.records if row.valid}
        - set(MINIMIZER_CLASSES)
    )
    strict_modules = sorted({strict.class_module_name(index) for index in classes})
    imports = [
        f"import RelativeConicArcs.Q25ResidualDispatchData.D_{payload_leaf.module_name}\n"
    ]
    imports.extend(
        f"import RelativeConicArcs.Q25RowCompositionStrictData.{name}\n"
        for name in strict_modules
    )
    imports.append("import RelativeConicArcs.Q25ExhaustionBridge\n")

    branches = []
    for row in payload_leaf.records:
        if not row.valid:
            branches.append("  · exact (BadRowPayload.not_rawCap hvalid hraw).elim\n")
        elif row.class_index in MINIMIZER_CLASSES:
            branches.append(
                "  · exact Or.inr "
                "(Q25ExhaustionBridge.isMinimumResidualClass_of_transport hvalid\n"
                f"      ({minimizer_witness(row.class_index)}))\n"
            )
        else:
            branches.append(
                "  · exact Or.inl (ValidRowPayload.source_card_ge_of_canonical hvalid hraw\n"
                f"      Q25RowCompositionStrictData."
                f"class{row.class_index:04d}LegalOrbitSet_card_ge_33)\n"
            )

    count = len(payload_leaf.records)
    return "".join(imports) + f"""
{generated_header(
        csv_hash,
        mask_digest,
        f"{count} per-row exhaustion disjunctions in {payload_leaf.module_name}",
    )}

namespace RelativeConicArcs
namespace Q25ExhaustionConclusionData

open Q25Coordinates Q25MinimumMask Q25ResidualCoverData Q25ResidualEquality

set_option maxHeartbeats 300000000
set_option maxRecDepth 100000

theorem concludeExh{payload_leaf.module_name} (i : Fin {count})
    (hraw : RawCap (rowConfig ⟨{payload_leaf.b}, by decide⟩
      ({payload_leaf.array_name}[i]).c)) :
    33 ≤ (legalOrbitSet (rowConfig ⟨{payload_leaf.b}, by decide⟩
      ({payload_leaf.array_name}[i]).c)).card ∨
      IsMinimumResidualClass (rowConfig ⟨{payload_leaf.b}, by decide⟩
        ({payload_leaf.array_name}[i]).c) := by
  have hvalid := Q25ResidualDispatchData.dispatch{payload_leaf.module_name} i
  fin_cases i
{"".join(branches)}
end Q25ExhaustionConclusionData
end RelativeConicArcs
"""


def render_aggregate(
    module_names: Sequence[str], csv_hash: str, mask_digest: str, description: str
) -> str:
    imports = "".join(
        f"import RelativeConicArcs.Q25ExhaustionConclusionData.{name}\n"
        for name in module_names
    )
    return imports + "\n" + generated_header(csv_hash, mask_digest, description)


def write_modules(output_directory: Path, csv: Path, composition_root: Path) -> None:
    if output_directory.name != "Q25ExhaustionConclusionData":
        raise ValueError("output directory must be named Q25ExhaustionConclusionData")
    rows, _ = transport.cover.read_records(csv)
    assert len(rows) == EXPECTED_ROWS
    valid = tuple(row for row in rows if row.valid)
    assert len(valid) == EXPECTED_VALID_ROWS
    payloads = transport.payload_leaves(rows)
    assert len(payloads) == EXPECTED_PAYLOAD_LEAVES

    cards = strict.read_mask_cardinalities(composition_root)
    mask_digest = strict.spectrum.mask_stream_digest(
        strict.spectrum.parse_masks(composition_root)
    )
    for row in valid:
        if row.class_index not in MINIMIZER_CLASSES and cards[row.class_index] < 33:
            raise RuntimeError(
                f"row ({row.b},{row.c}) links to class {row.class_index} without a strict bound"
            )

    csv_hash = transport.cover.sha256(csv)
    leaf_names = tuple(conclusion_module_name(payload) for payload in payloads)
    aggregate_names = tuple(f"B_{b:03d}" for b in range(6, 309))
    expected = {f"{name}.lean" for name in (*leaf_names, *aggregate_names)} | {"All.lean"}
    output_directory.mkdir(parents=True, exist_ok=True)
    unexpected = sorted(
        path.name for path in output_directory.iterdir() if path.name not in expected
    )
    if unexpected:
        raise RuntimeError(f"refusing output directory with unexpected entries: {unexpected}")

    written = []
    for payload, leaf_name in zip(payloads, leaf_names, strict=True):
        path = output_directory / f"{leaf_name}.lean"
        path.write_text(render_leaf(payload, csv_hash, mask_digest), encoding="utf-8")
        written.append(path)

    for b, aggregate_name in zip(range(6, 309), aggregate_names, strict=True):
        modules = tuple(
            name
            for payload, name in zip(payloads, leaf_names, strict=True)
            if payload.b == b
        )
        path = output_directory / f"{aggregate_name}.lean"
        path.write_text(
            render_aggregate(
                modules,
                csv_hash,
                mask_digest,
                f"import-only aggregate for all exhaustion disjunctions with b = {b}",
            ),
            encoding="utf-8",
        )
        written.append(path)

    all_path = output_directory / "All.lean"
    all_path.write_text(
        render_aggregate(
            aggregate_names,
            csv_hash,
            mask_digest,
            f"import-only aggregate for all {EXPECTED_ROWS} exhaustion disjunctions",
        ),
        encoding="utf-8",
    )
    written.append(all_path)

    assert len(written) == len(expected)
    minimizer_rows = tuple(row for row in valid if row.class_index in MINIMIZER_CLASSES)
    print(
        f"generated_files={len(written)} conclusion_modules={len(payloads)} "
        f"b_aggregates={len(aggregate_names)} rows={len(rows)}"
    )
    print(f"valid_rows={len(valid)} minimizer_rows={len(minimizer_rows)}")
    print(f"max_rows_per_module={max(len(payload.records) for payload in payloads)}")
    print(f"generated_source_bytes={sum(path.stat().st_size for path in written)}")
    print(f"output_directory={output_directory.resolve()}")
    print(f"csv_sha256={csv_hash}")
    print(f"mask_stream_digest={mask_digest}")
    print(f"exhaustion_conclusion_generator_sha256={source_sha256()}")
    print(f"generated_tree_sha256={strict.tree_sha256(written, output_directory)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path)
    parser.add_argument(
        "--composition-root",
        type=Path,
        default=Path("lean/RelativeConicArcs/Q25RowCompositionData"),
    )
    parser.add_argument("--write-lean-modules", required=True, type=Path)
    args = parser.parse_args()
    write_modules(args.write_lean_modules, args.csv, args.composition_root)


if __name__ == "__main__":
    main()
