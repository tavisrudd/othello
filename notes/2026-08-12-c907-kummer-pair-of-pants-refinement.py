#!/usr/bin/env python3
"""Generate the compact certificate for the C907 Kummer support atlas.

This is deliberately a proof-generating atlas, not a several-million-row
chart dump.  Its input is the exact six-weight support complex.  At the
translated (1,1) corner it takes the common refinement with the star fan of
Bl_(delta,U,V), and then records the canonical barycentric Kummer atlas.

The Kummer chart attached to a flag of nonzero faces F_1 < ... < F_d has rays
    q_F = primitive(sum of the primitive extremal rays of F).
It is A^d times its transverse torus in the lattice generated by the q_F,
with diagonal finite quotient N_flag/(sum Z q_F) on its coarse toroidal chart.
Thus it is regular after
the displayed finite Kummer cover, with no arbitrary desingularization choice.

Requires the exact PPL backend used by the input certificate.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import math
import os
import subprocess
import sys
import tempfile
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
INPUT = HERE / "2026-08-12-c907-tripod-hyperplane-refinement.json"
SOURCE = HERE / "2026-08-12-c907-tripod-hyperplane-refinement.py"
OUT = HERE / "2026-08-12-c907-kummer-pair-of-pants-refinement.json"
SUM = HERE / "2026-08-12-c907-kummer-pair-of-pants-refinement.sha256"
VERTICES = ("g", "0", "1", "infinity")
REES_TYPE = ("1", "1")
# Coordinates are (t,p1,p2,p3,beta,gamma).  This is e_delta+e_U+e_V.
REES_RAY = (1, 0, 0, 0, 1, 1)
REES_CUTS = (
    ("t=beta", (1, 0, 0, 0, -1, 0)),
    ("t=gamma", (1, 0, 0, 0, 0, -1)),
    ("beta=gamma", (0, 0, 0, 0, 1, -1)),
)


def load_support_module():
    spec = importlib.util.spec_from_file_location("c907_tripod_support", SOURCE)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot load the pinned support generator")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def primitive(vector: list[Fraction] | tuple[int, ...]) -> tuple[int, ...]:
    vals = [Fraction(x) for x in vector]
    if not any(vals):
        raise RuntimeError("zero ray")
    scale = math.lcm(*(x.denominator for x in vals))
    ints = [int(scale * x) for x in vals]
    divisor = math.gcd(*(abs(x) for x in ints if x))
    return tuple(x // divisor for x in ints)


def dot(left: list[int], right: tuple[int, ...]) -> int:
    return sum(a * b for a, b in zip(left, right))


def kept_faces(raw: dict, case: tuple[str, str]) -> dict[int, list[dict]]:
    """Put polymake's homogeneous cones in the certificate's t=1 order."""
    item = raw[f"{case[0]},{case[1]}"]
    rays = item["rays"]
    kept: dict[int, list[dict]] = {}
    for dim, faces in item["faces"].items():
        cells = [face for face in faces if any(rays[index][0] > 0 for index in face)]
        if cells:
            kept[dim - 1] = [{"rays": tuple(sorted(face))} for face in cells]
    return kept


def rees_perl(module) -> str:
    """The common refinement with the three affine charts of Bl_(d,U,V)."""
    case = REES_TYPE
    pairs = [(i, j) for i in range(6) for j in range(i + 1, 6)]
    weights = module.weights(*case)
    support = module.support(*case)
    data = json.dumps([["1,1", weights, support]])
    extra = json.dumps([list(vector) for _, vector in REES_CUTS])
    return f'''use application "fan";
my $cases = {data};
my $extra = {extra};
for my $case (@$cases) {{
  my ($name,$w,$input) = @{{$case}}; my @h;
  for my $i (0..5) {{ for my $j (($i+1)..5) {{
    push @h, [map {{$w->[$i]->[$_] - $w->[$j]->[$_]}} (0..5)];
  }} }}
  push @h, @$extra;
  my $ha = new HyperplaneArrangement(HYPERPLANES=>\\@h,
    "SUPPORT.INPUT_RAYS"=>$input);
  my $fan = $ha->CHAMBER_DECOMPOSITION;
  print "CASE|$name\\nRAYS\\n", $fan->RAYS, "ENDRAYS\\n";
  for my $d (1..$fan->COMBINATORIAL_DIM+1) {{
    print "DIM|$d\\n", $fan->cones_of_dim($d), "ENDDIM\\n";
  }}
  print "ENDCASE\\n";
}}
'''


def run_rees_refinement(module) -> dict:
    with tempfile.TemporaryDirectory() as temporary:
        directory = Path(temporary)
        script = directory / "rees-refinement.pl"
        script.write_text(rees_perl(module))
        environment = os.environ.copy()
        environment["POLYMAKE_USER_DIR"] = temporary
        run = subprocess.run(
            ["nix", "shell", "nixpkgs#polymake", "--command", "polymake", "--script", str(script)],
            text=True, capture_output=True, env=environment,
        )
        if run.returncode:
            raise RuntimeError("Rees common-refinement replay failed:\n" + run.stderr)
    return module.parse(run.stdout, [REES_TYPE])


def full_record(case: tuple[str, str], rays: list[list[Fraction]], face: tuple[int, ...], module) -> dict:
    q = primitive([sum(rays[index][coordinate] for index in face) for coordinate in range(6)])
    a, b = case
    # A vanishing beta/gamma coefficient is precisely the face map to g.
    base = (a if q[4] else "g", b if q[5] else "g")
    values = [dot(weight, q) for weight in module.weights(*case)]
    top = max(values)
    mask = "".join(str(index) for index, value in enumerate(values) if value == top)
    result = {
        "case": list(case),
        "face": list(face),
        "q": list(q),
        "tripod_base_face": list(base),
        "upper_mask": mask,
        "barycentric_exceptional": len(face) > 1,
    }
    if case == REES_TYPE:
        minima = min(q[0], q[4], q[5])
        result["rees_charts"] = [
            name for name, value in (("delta", q[0]), ("U", q[4]), ("V", q[5])) if value == minima
        ]
    return result


def process_case(case: tuple[str, str], faces: dict[int, list[dict]], rays: list[list[Fraction]], module) -> tuple[dict, str]:
    digest = hashlib.sha256()
    counts: dict[str, int] = {}
    base_maps: dict[str, int] = {}
    masks: dict[str, int] = {}
    rees_charts: dict[str, int] = {}
    exceptional = 0
    for dim in sorted(faces):
        cells = sorted((entry["rays"] for entry in faces[dim]))
        counts[str(dim)] = len(cells)
        for face in cells:
            record = full_record(case, rays, face, module)
            digest.update((json.dumps(record, sort_keys=True, separators=(",", ":")) + "\n").encode())
            key = "/".join(record["tripod_base_face"])
            base_maps[key] = base_maps.get(key, 0) + 1
            masks[record["upper_mask"]] = masks.get(record["upper_mask"], 0) + 1
            if record["barycentric_exceptional"]:
                exceptional += 1
            for chart in record.get("rees_charts", []):
                rees_charts[chart] = rees_charts.get(chart, 0) + 1
    return {
        "slice_face_counts": counts,
        "barycentric_exceptional_vectors": exceptional,
        "tripod_base_face_counts": base_maps,
        "upper_mask_counts": masks,
        "rees_chart_face_counts": rees_charts,
    }, digest.hexdigest()


def canonical(data: dict) -> bytes:
    return (json.dumps(data, sort_keys=True, separators=(",", ":")) + "\n").encode()


def sums(data: bytes) -> bytes:
    return (
        f"{hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}  {Path(__file__).name}\n"
        f"{hashlib.sha256(data).hexdigest()}  {OUT.name}\n"
    ).encode()


def build() -> dict:
    module = load_support_module()
    source = json.loads(INPUT.read_text())
    input_hash = hashlib.sha256(INPUT.read_bytes()).hexdigest()
    support_generator_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    raw_rees = run_rees_refinement(module)
    refined_rees_faces = kept_faces(raw_rees, REES_TYPE)
    refined_rees_rays = raw_rees["1,1"]["rays"]

    # The new ray is forced by the all-tie support face and the three Rees cuts.
    if REES_RAY not in {primitive(ray) for ray in refined_rees_rays}:
        raise RuntimeError("the Rees ray is absent from the common refinement")
    if [dot(weight, REES_RAY) for weight in module.weights(*REES_TYPE)] != [0] * 6:
        raise RuntimeError("the Rees ray is not in the six-weight all-tie locus")
    if any(dot(list(cut), REES_RAY) for _, cut in REES_CUTS):
        raise RuntimeError("the Rees ray fails a Rees-chart tie")

    rows = []
    full_digest = hashlib.sha256()
    total = 0
    exceptional = 0
    for entry in source["cones"]:
        case = tuple(entry["ordered_type"])
        if case == REES_TYPE:
            faces = refined_rees_faces
            rays = refined_rees_rays
        else:
            faces = {int(dim): [{"rays": tuple(item["rays"])} for item in cells]
                     for dim, cells in entry["slice_faces"].items()}
            rays = [[Fraction(value) for value in ray] for ray in entry["rays"]]
        row, digest = process_case(case, faces, rays, module)
        row["ordered_type"] = list(case)
        row["record_sha256"] = digest
        rows.append(row)
        full_digest.update((json.dumps(row, sort_keys=True, separators=(",", ":")) + "\n").encode())
        total += sum(row["slice_face_counts"].values())
        exceptional += row["barycentric_exceptional_vectors"]

    old_rees = next(entry for entry in source["cones"] if tuple(entry["ordered_type"]) == REES_TYPE)
    old_count = sum(old_rees["slice_face_counts"].values())
    new_count = sum(refined_rees_faces[dim].__len__() for dim in refined_rees_faces)
    return {
        "schema_version": 1,
        "input": {
            "file": INPUT.name,
            "sha256": input_hash,
            "generator_file": SOURCE.name,
            "generator_sha256": support_generator_hash,
            "backend": "polymake 4.15 (exact rational PPL)",
        },
        "rees_common_refinement": {
            "ordered_type": list(REES_TYPE),
            "ray": list(REES_RAY),
            "ray_meaning": "e_delta+e_U+e_V, the exceptional ray of Bl_(delta,U,V)",
            "cuts": [name for name, _ in REES_CUTS],
            "old_slice_cells": old_count,
            "new_slice_cells": new_count,
            "all_tie_weights": True,
            "all_rees_cut_ties": True,
        },
        "kummer_atlas": {
            "construction": "for each nonzero support face F use q_F=primitive(sum primitive rays(F)); maximal charts are flags F_1<...<F_d",
            "regular_cover": "Spec k[z_F1,...,z_Fd] times the transverse torus in the lattice sum Z q_Fi",
            "coarse_group": "(span_R(q_Fi) intersect Z^6)/(sum Z q_Fi)",
            "chart_map": "chi^m maps to product z_Fi^(<m,q_Fi>); pair-of-pants residues use the formulas in the companion note",
            "exceptional_divisor_rule": "D_F is exceptional exactly when dim(F)>1; its genuine vector is q_F",
            "vertical_only": "all added barycentric vectors have positive t because only faces meeting t=1 are refined",
            "imbalanced_rule": "in the U and V Rees charts v=V/U and w=U/V are ordinary interior coordinates, never Kummer boundary generators",
        },
        "checks": {
            "ordered_product_cones": len(rows),
            "slice_cells_after_rees_common_refinement": total,
            "barycentric_exceptional_vector_records": exceptional,
            "all_face_records_sha256": full_digest.hexdigest(),
            "rows": rows,
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = canonical(build())
    if args.write:
        OUT.write_bytes(data)
        SUM.write_bytes(sums(data))
        print(f"wrote {OUT.name}: {len(data)} bytes")
        return 0
    if OUT.read_bytes() != data or SUM.read_bytes() != sums(data):
        print("Kummer refinement certificate drift", file=sys.stderr)
        return 1
    print(f"ok {OUT.name}: {len(data)} bytes sha256={hashlib.sha256(data).hexdigest()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
