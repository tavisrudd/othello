#!/usr/bin/env python3
"""C874 -- bounded submodule lattice of the 120-point E8-carrier permutation module.

Re-examines the C868 claim that the only equivariant code of the right size on
the 120 nonsingular points of the plus-type quadratic space F_2^8 is the
affine code [120,9,56] (over F_2) and its scalar extension (over F_4).  C868
inferred this from adjacency-matrix ranks; this script computes the actual
lattice of G-invariant subspaces of dimension at most CAP, over F_2 and over
F_4, for G the group generated by all 120 reflections in nonsingular vectors
(the full orthogonal group GO8+(2) acting on the points).

Method.  Every nonzero invariant subspace W over a field of characteristic
two has nonzero fixed points under any 2-subgroup P of G.  Take P of order
2^12 (a Sylow 2-subgroup of Omega8+(2)); its fixed space M^P is spanned by
its orbit indicators (4 orbits).  Every minimal invariant subspace is the
G-span of some nonzero vector of M^P, so spinning all candidates finds every
minimal submodule; iterating on quotients (fixed vectors of P modulo W,
then spinning W + v) finds every invariant subspace of dimension <= CAP.
This is a complete enumeration up to the cap, not a heuristic.

Replay:  python3 notes/2026-08-05-c874-e8-carrier-submodule-lattice.py --check
Writes/compares notes/2026-08-05-c874-e8-carrier-submodule-lattice.json.
Standard library only, no randomness.
"""
import json, sys, hashlib, itertools, os

CAP = 12

# ---------------------------------------------------------------- geometry
def Q(v):
    x, y = v & 15, v >> 4
    return bin(x & y).count('1') & 1

PTS = [v for v in range(256) if Q(v)]
assert len(PTS) == 120
PIDX = {v: i for i, v in enumerate(PTS)}

def Bform(u, v):
    return Q(u ^ v) ^ Q(u) ^ Q(v)

def perm_of(f):
    return tuple(PIDX[f(v)] for v in PTS)

# all 120 reflections r_a: v -> v + B(v,a) a   (generate GO8+(2))
REFL = []
for a in PTS:
    REFL.append(perm_of(lambda v, a=a: v ^ (a if Bform(v, a) else 0)))

# Sylow 2-subgroup generators: symmetric-zero-diagonal maps and GL4 unipotents
def uA(i, j):
    def f(v):
        x, y = v & 15, v >> 4
        y ^= ((x >> j) & 1) << i
        y ^= ((x >> i) & 1) << j
        return x | (y << 4)
    return f

def gE(i, j):
    def f(v):
        x, y = v & 15, v >> 4
        x ^= ((x >> j) & 1) << i
        y ^= ((y >> i) & 1) << j
        return x | (y << 4)
    return f

PGENS = []
for i in range(4):
    for j in range(i + 1, 4):
        PGENS.append(perm_of(uA(i, j)))
        PGENS.append(perm_of(gE(i, j)))

def group_order(gens):
    ident = tuple(range(120))
    seen = {ident}
    frontier = [ident]
    while frontier:
        nf = []
        for p in frontier:
            for g in gens:
                q = tuple(p[g[i]] for i in range(120))
                if q not in seen:
                    seen.add(q)
                    nf.append(q)
        frontier = nf
    return len(seen)

def orbits_of(gens):
    seen = [False] * 120
    out = []
    for s in range(120):
        if seen[s]:
            continue
        orb = {s}
        fr = [s]
        while fr:
            nf = []
            for a in fr:
                for g in gens:
                    b = g[a]
                    if b not in orb:
                        orb.add(b)
                        nf.append(b)
            fr = nf
        for a in orb:
            seen[a] = True
        out.append(sorted(orb))
    return sorted(out, key=len)

# ------------------------------------------------------------- F2 machinery
def apply_perm(p, m):
    w = 0
    while m:
        b = m & -m
        i = b.bit_length() - 1
        w |= 1 << p[i]
        m ^= b
    return w

def rref2(rows):
    basis = {}
    for r in rows:
        r = reduce2(basis, r)
        if r:
            basis[r.bit_length() - 1] = r
    # full reduction
    for piv in sorted(basis, reverse=True):
        r = basis[piv]
        for p2 in list(basis):
            if p2 != piv and (basis[p2] >> piv) & 1:
                basis[p2] ^= r
    return basis

def reduce2(basis, v):
    while v:
        p = v.bit_length() - 1
        if p in basis:
            v ^= basis[p]
        else:
            return v
    return 0

def spin2(seed_rows, cap):
    """G-span (all 120 reflections) of seed rows; None if dim > cap."""
    basis = {}
    queue = []
    for r in seed_rows:
        r = reduce2(basis, r)
        if r:
            basis[r.bit_length() - 1] = r
            queue.append(r)
            if len(basis) > cap:
                return None
    while queue:
        v = queue.pop()
        for p in REFL:
            w = reduce2(basis, apply_perm(p, v))
            if w:
                basis[w.bit_length() - 1] = w
                queue.append(w)
                if len(basis) > cap:
                    return None
    return rref2(list(basis.values()))

def key2(basis):
    return tuple(sorted(basis.values()))

def nullspace2(eqs, nvars):
    """Nullspace basis of the given F2 equation rows over nvars variables."""
    basis = {}
    for e in eqs:
        e = reduce2(basis, e)
        if e:
            basis[e.bit_length() - 1] = e
    # full reduction so each pivot occurs in exactly one row
    for piv in sorted(basis, reverse=True):
        r = basis[piv]
        for p2 in list(basis):
            if p2 != piv and (basis[p2] >> piv) & 1:
                basis[p2] ^= r
    pivs = set(basis)
    null = []
    for f in range(nvars):
        if f in pivs:
            continue
        v = 1 << f
        for p, row in basis.items():
            if (row >> f) & 1:
                v |= 1 << p
        null.append(v)
    return null

def fix2_mod(Wbasis):
    """Basis of {x : (g-1)x in W for all g in PGENS} over F2."""
    eqs = []
    for g in PGENS:
        cols = []
        for i in range(120):
            img = apply_perm(g, 1 << i) ^ (1 << i)
            cols.append(reduce2(Wbasis, img))
        for j in range(120):
            eq = 0
            for i in range(120):
                if (cols[i] >> j) & 1:
                    eq |= 1 << i
            if eq:
                eqs.append(eq)
    return nullspace2(eqs, 120)

def lattice2(cap):
    zero = {}
    found = {key2(zero): (zero, 0)}
    frontier = [zero]
    while frontier:
        nf = []
        for W in frontier:
            fix = fix2_mod(W)
            comp = []
            tmp = dict(W)
            for v in fix:
                r = reduce2(tmp, v)
                if r:
                    tmp[r.bit_length() - 1] = r
                    comp.append(r)
            f = len(comp)
            assert f <= 20, "unexpectedly large fixed space"
            for mask in range(1, 1 << f):
                v = 0
                for t in range(f):
                    if (mask >> t) & 1:
                        v ^= comp[t]
                mod = spin2(list(W.values()) + [v], cap)
                if mod is not None:
                    k = key2(mod)
                    if k not in found:
                        found[k] = (mod, len(mod))
                        nf.append(mod)
        frontier = nf
    return found

# ------------------------------------------------------------- F4 machinery
# vector = (a, b) meaning sum (a_i + w b_i) e_i, w^2 = w + 1
def f4_scale(c, v):
    a, b = v
    if c == 1:
        return v
    if c == 2:  # w
        return (b, a ^ b)
    return (a ^ b, a)  # w^2

def f4_add(u, v):
    return (u[0] ^ v[0], u[1] ^ v[1])

def f4_lead(v):
    a, b = v
    m = a | b
    if not m:
        return None, None
    p = m.bit_length() - 1
    c = ((a >> p) & 1) | (((b >> p) & 1) << 1)  # 1, 2(=w), 3(=w^2) index
    return p, c

F4INV = {1: 1, 2: 3, 3: 2}

def f4_reduce(basis, v):
    while True:
        p, c = f4_lead(v)
        if p is None:
            return v
        if p not in basis:
            return v
        v = f4_add(v, f4_scale(F4MUL[c][F4INV[f4_lead(basis[p])[1]]], basis[p]))

# multiplication table for coefficient indices 0..3 (0,1,w,w^2)
F4MUL = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]

def f4_norm(v):
    p, c = f4_lead(v)
    if p is None:
        return v
    return f4_scale(F4INV[c], v)

def f4_rref(rows):
    basis = {}
    for r in rows:
        r = f4_reduce(basis, r)
        p, c = f4_lead(r)
        if p is not None:
            basis[p] = f4_norm(r)
    for piv in sorted(basis, reverse=True):
        r = basis[piv]
        for p2 in list(basis):
            if p2 == piv:
                continue
            a, b = basis[p2]
            c = ((a >> piv) & 1) | (((b >> piv) & 1) << 1)
            if c:
                basis[p2] = f4_add(basis[p2], f4_scale(c, r))
    return basis

def f4_apply(p, v):
    return (apply_perm(p, v[0]), apply_perm(p, v[1]))

def spin4(seed_rows, cap):
    basis = {}
    queue = []
    for r in seed_rows:
        r = f4_reduce(basis, r)
        if f4_lead(r)[0] is not None:
            basis[f4_lead(r)[0]] = f4_norm(r)
            queue.append(r)
            if len(basis) > cap:
                return None
    while queue:
        v = queue.pop()
        for p in REFL:
            w = f4_reduce(basis, f4_apply(p, v))
            if f4_lead(w)[0] is not None:
                basis[f4_lead(w)[0]] = f4_norm(w)
                queue.append(w)
                if len(basis) > cap:
                    return None
    return f4_rref(list(basis.values()))

def key4(basis):
    return tuple(sorted(basis.values()))

def fix4_mod(Wbasis):
    """F4-basis of {x : (g-1)x in W_F4 for all g in PGENS}.

    Solve over F2 by writing x = a + w b: the permutation matrices are
    F2-rational, so the condition splits into two coupled F2 systems on the
    240-bit unknown (a, b), with membership in W tested by f4_reduce.
    """
    # column-wise construction (as in F2 case, but 240 unknowns / 240 eq rows per gen)
    eqrows = {}
    for gi, g in enumerate(PGENS):
        cols = []
        for i in range(240):
            if i < 120:
                v = (apply_perm(g, 1 << i) ^ (1 << i), 0)
            else:
                v = (0, apply_perm(g, 1 << (i - 120)) ^ (1 << (i - 120)))
            cols.append(f4_reduce(Wbasis, v))
        for j in range(240):
            eq = 0
            for i in range(240):
                a, b = cols[i]
                bit = (a >> j) & 1 if j < 120 else (b >> (j - 120)) & 1
                if bit:
                    eq |= 1 << i
            if eq:
                eqrows[(gi, j)] = eq
    null = [(v & ((1 << 120) - 1), v >> 120)
            for v in nullspace2(list(eqrows.values()), 240)]
    # F4-reduce the F2-solution set to an F4-basis (close under w-multiplication:
    # if x is a solution so is wx since W is an F4-space and perms are F4-linear)
    f4b = {}
    for v in null:
        for c in (1, 2):
            r = f4_reduce(f4b, f4_scale(c, v))
            if f4_lead(r)[0] is not None:
                f4b[f4_lead(r)[0]] = f4_norm(r)
    return list(f4_rref(list(f4b.values())).values())

def lattice4(cap):
    zero = {}
    found = {key4(zero): (zero, 0)}
    frontier = [zero]
    while frontier:
        nf = []
        for W in frontier:
            fix = fix4_mod(W)
            comp = []
            tmp = dict(W)
            for v in fix:
                r = f4_reduce(tmp, v)
                if f4_lead(r)[0] is not None:
                    tmp[f4_lead(r)[0]] = f4_norm(r)
                    comp.append(r)
            f = len(comp)
            assert f <= 12, "unexpectedly large F4 fixed space"
            # enumerate nonzero F4-combinations up to scalar: first nonzero coeff = 1
            for lead in range(f):
                for tail in itertools.product(range(4), repeat=f - lead - 1):
                    v = comp[lead]
                    for t, c in enumerate(tail):
                        if c:
                            v = f4_add(v, f4_scale(c, comp[lead + 1 + t]))
                    mod = spin4(list(W.values()) + [v], cap)
                    if mod is not None:
                        k = key4(mod)
                        if k not in found:
                            found[k] = (mod, len(mod))
                            nf.append(mod)
        frontier = nf
    return found

# ------------------------------------------------------------ known objects
def known_codes():
    # affine code [120,9,56]: constants + linear functionals restricted
    ones = (1 << 120) - 1
    rows = [ones]
    for a in range(1, 256):
        # B(a, v) with a arbitrary (not necessarily nonsingular)
        r = 0
        for i, v in enumerate(PTS):
            if Q(a ^ v) ^ Q(a) ^ Q(v):
                r |= 1 << i
        rows.append(r)
    C = rref2(rows)
    lin = rref2(rows[1:])
    return C, lin, ones

def weight_check(C):
    """Full enumeration of the 2^9 code: return sorted weight distribution."""
    from collections import Counter
    rows = list(C.values())
    k = len(rows)
    cnt = Counter()
    for m in range(1 << k):
        v = 0
        mm = m
        t = 0
        while mm:
            if mm & 1:
                v ^= rows[t]
            mm >>= 1
            t += 1
        cnt[bin(v).count('1')] += 1
    return dict(sorted(cnt.items()))

# ---------------------------------------------------------------------- main
def main():
    check = '--check' in sys.argv
    report = {}

    ordP = group_order(PGENS)
    orbs = orbits_of(PGENS)
    report['sylow_order'] = ordP
    report['sylow_is_2group'] = (ordP & (ordP - 1) == 0)
    report['sylow_orbit_sizes'] = [len(o) for o in orbs]
    assert ordP == 4096 and report['sylow_is_2group']

    C, lin, ones = known_codes()
    assert len(C) == 9 and len(lin) == 8
    wd = weight_check(C)
    report['affine_code_weight_distribution'] = {str(k): v for k, v in wd.items()}
    assert wd == {0: 1, 56: 255, 64: 255, 120: 1}

    # calibration: the P-fixed space of the full module must be exactly the
    # orbit-indicator span, in both fields
    fix0 = fix2_mod({})
    assert len(rref2(fix0)) == len(orbs), (len(fix0), len(orbs))
    for v in fix0:
        for g in PGENS:
            assert apply_perm(g, v) == v
    fix0_4 = fix4_mod({})
    assert len(f4_rref(fix0_4)) == len(orbs)
    report['fixed_space_calibration'] = 'P-fixed spaces equal orbit-indicator spans (dim %d)' % len(orbs)

    lat2 = lattice2(CAP)
    dims2 = sorted(d for _, d in lat2.values())
    report['f2_cap'] = CAP
    report['f2_submodule_dims'] = dims2
    # identify the nonzero ones
    ids = []
    keyC = key2(C)
    keyL = key2(lin)
    keyO = key2(rref2([ones]))
    for k, (mod, d) in sorted(lat2.items(), key=lambda t: t[1][1]):
        if d == 0:
            continue
        name = {keyC: 'affine_code_dim9', keyL: 'linear_functionals_dim8',
                keyO: 'constants_dim1'}.get(k, 'UNEXPECTED_dim%d' % d)
        ids.append(name)
    report['f2_submodules'] = ids

    lat4 = lattice4(CAP)
    dims4 = sorted(d for _, d in lat4.values())
    report['f4_cap'] = CAP
    report['f4_submodule_dims'] = dims4
    ids4 = []
    C4 = f4_rref([(r, 0) for r in C.values()])
    L4 = f4_rref([(r, 0) for r in lin.values()])
    O4 = f4_rref([(ones, 0)])
    for k, (mod, d) in sorted(lat4.items(), key=lambda t: t[1][1]):
        if d == 0:
            continue
        name = {key4(C4): 'f4_extension_of_affine_code_dim9',
                key4(L4): 'f4_extension_of_linear_functionals_dim8',
                key4(O4): 'f4_constants_dim1'}.get(k, 'UNEXPECTED_dim%d' % d)
        ids4.append(name)
    report['f4_submodules'] = ids4

    report['verdict_f2'] = (
        'complete list of GO8+(2)-invariant F2-subspaces of F2^120 with dim <= %d' % CAP)
    report['verdict_f4'] = (
        'complete list of GO8+(2)-invariant F4-subspaces of F4^120 with dim <= %d' % CAP)

    out = json.dumps(report, indent=1, sort_keys=True)
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        '2026-08-05-c874-e8-carrier-submodule-lattice.json')
    if check and os.path.exists(path):
        with open(path) as fh:
            prev = fh.read()
        if json.loads(prev) != report:
            print('MISMATCH against tracked certificate', file=sys.stderr)
            sys.exit(1)
        print('certificate matches; sha256 =',
              hashlib.sha256(prev.encode()).hexdigest())
    else:
        with open(path, 'w') as fh:
            fh.write(out)
        print('wrote', path)
    print(json.dumps(report, indent=1, sort_keys=True))

if __name__ == '__main__':
    main()
