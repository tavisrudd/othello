def projective_points(p, n):
    """Representatives of P^{n-1}(F_p), first nonzero coordinate equal to one."""
    for lead in range(n):
        tail_len = n - lead - 1
        for tail in range(p ** tail_len):
            pt = [0] * lead + [1]
            v = tail
            for _ in range(tail_len):
                pt.append(v % p)
                v //= p
            yield tuple(pt)


def normalise(pt, p):
    for v in pt:
        if v % p:
            inv = pow(v % p, p - 2, p)
            return tuple((c * inv) % p for c in pt)
    return pt


def check_exhaustive(primes=(11, 19)):
    for name, B, U in GAUGES:
        quads = restricted_partials(B)
        for p in primes:
            sols = []
            for pt in projective_points(p, 5):
                if all(eval_quad(q, pt, p) == 0 for q in quads):
                    sols.append(pt)
            want = sorted(normalise(pt, p) for pt in AXIS_CLASSES)
            got = sorted(sols)
            ok = (len(got) == 6 and got == want)
            report("check F  %s: exhaustive projective solve of grad C = 0 over the field "
                   "of %d elements" % (name, p), ok,
                   "%d solutions, all six axis classes" % len(got))


