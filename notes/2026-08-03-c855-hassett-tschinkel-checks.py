# check H: Hilbert function of the Jacobian ideal in degree six
# --------------------------------------------------------------------------

RANK_PRIME = 2147483647          # 2^31 - 1, prime


def monomials(nvars, deg):
    return [tuple(sum(1 for v in c if v == i) for i in range(nvars))
            for c in combinations_with_replacement(range(nvars), deg)]


def rank_mod(rows, ncols, p):
    m = [r[:] for r in rows]
    rank = 0
    col = 0
    nrows = len(m)
    while col < ncols and rank < nrows:
        piv = None
        for r in range(rank, nrows):
            if m[r][col] % p:
                piv = r
                break
        if piv is None:
            col += 1
            continue
        m[rank], m[piv] = m[piv], m[rank]
        inv = pow(m[rank][col], p - 2, p)
        prow = [(v * inv) % p for v in m[rank]]
        m[rank] = prow
        for r in range(rank + 1, nrows):
            f = m[r][col]
            if f:
                mr = m[r]
                m[r] = [(mr[k] - f * prow[k]) % p for k in range(ncols)]
        rank += 1
        col += 1
    return rank


def rank_exact(rows, ncols):
    m = [[Fraction(v) for v in r] for r in rows]
    rank = 0
    col = 0
    while col < ncols and rank < len(m):
        piv = None
        for r in range(rank, len(m)):
            if m[r][col] != 0:
                piv = r
                break
        if piv is None:
            col += 1
            continue
        m[rank], m[piv] = m[piv], m[rank]
        prow = [v / m[rank][col] for v in m[rank]]
        m[rank] = prow
        for r in range(rank + 1, len(m)):
            f = m[r][col]
            if f:
                m[r] = [m[r][k] - f * prow[k] for k in range(ncols)]
        rank += 1
        col += 1
    return rank


def check_hilbert(deg=6):
    mons = monomials(5, deg)
    index = {m: i for i, m in enumerate(mons)}
    ncols = len(mons)
    mult = monomials(5, deg - 2)
    for name, B, U in GAUGES:
        quads = restricted_partials(B)

        # the six axis classes really are in the zero set
        vanish = all(eval_quad(q, pt) == 0 for q in quads for pt in AXIS_CLASSES)
        report("check H  %s: all partials vanish at the six axis classes" % name, vanish)

        rows = []
        for q in quads:
            for m in mult:
                row = [0] * ncols
                for e, c in q.items():
                    row[index[tuple(a + b for a, b in zip(e, m))]] += c
                rows.append(row)
        # A modular rank never exceeds the rational rank, so ncols minus it is an
        # upper bound for the rational Hilbert function in this degree.
        r = rank_mod(rows, ncols, RANK_PRIME)
        upper = ncols - r

        ev = []
        for pt in AXIS_CLASSES:
            row = []
            for m in mons:
                v = 1
                for i, k in enumerate(m):
                    if k:
                        v *= pt[i] ** k
                row.append(v)
            ev.append(row)
        lower = rank_exact(ev, ncols)

        ok = (upper == 6 and lower == 6)
        report("check H  %s: Hilbert function of the Jacobian ideal in degree %d is 6"
               % (name, deg), ok,
               "upper bound %d from a modular rank, lower bound %d from the six points"
               % (upper, lower))
        report("check H  %s: Macaulay persistence gives a degree-six zero-dimensional "
               "scheme, hence exactly the six reduced axis classes" % name, ok)


