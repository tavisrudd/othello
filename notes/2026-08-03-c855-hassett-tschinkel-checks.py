def check_lemma_a():
    allowed = {ONE, -ONE, T, -T}
    for name, B, U in GAUGES:
        Ut = U(T)
        values = []
        ok = True
        for S in combinations(range(6), 3):
            d = det3([Ut[i] for i in S])
            values.append(d)
            if d.is_zero() or not any((d - w).is_zero() for w in allowed):
                ok = False
        seen = []
        for v in values:
            if not any((v - w).is_zero() for w in seen):
                seen.append(v)
        report("check A  %s: twenty 3x3 minors of U(t) are units" % name, ok,
               "values %s" % sorted(repr(v) for v in seen))


# --------------------------------------------------------------------------
# check B: no conic through the six rows
# --------------------------------------------------------------------------

def check_lemma_b():
    for name, B, U in GAUGES:
        Ut = U(T)
        rows = []
        for (X, Y, Z) in Ut:
            rows.append([X * X, Y * Y, Z * Z, Y * Z, Z * X, X * Y])
        d = det_gauss(rows)
        report("check B  %s: Veronese determinant of the six rows is nonzero" % name,
               not d.is_zero(), "det = %s  (= sqrt5 * t^2 up to sign)" % d)


