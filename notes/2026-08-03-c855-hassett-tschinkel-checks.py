def check_det_identity():
    for name, B, U in GAUGES:
        phi = cross_block_poly(U)
        d = pm_det3(phi)
        c = support_cubic_poly(B)
        report("check D  %s: det(Phi_x) + C(x) = 0" % name, p_is_zero(p_add(d, c)))


# --------------------------------------------------------------------------
# check J: the Jacobi bridge
# --------------------------------------------------------------------------

def check_jacobi_bridge():
    for name, B, U in GAUGES:
        phi = cross_block_poly(U)
        adj = pm_adjugate3(phi)
        c = support_cubic_poly(B)
        ok = True
        for i in range(6):
            lhs = p_diff(c, i)
            rhs = p_neg(pm_trace_mul(adj, cross_block_axis(U, i)))
            if not p_is_zero(p_add(lhs, p_neg(rhs))):
                ok = False
        report("check J  %s: dC/dx_i = -trace(adj(Phi_x) Phi_{e_i}) for all i" % name, ok)


# --------------------------------------------------------------------------
# the five restricted partials, in the chart x_5 = 0
# --------------------------------------------------------------------------

def restricted_partials(B):
    """The five partials of C(x_0..x_4, 0), as integer quadrics in five variables.

    Each is a dict from a five-entry exponent tuple to an integer coefficient.
    The projective four-space of the note is the quotient of the six coordinates
    by the all-ones line; the section x_5 = 0 realizes it, and the sixth partial
    is minus the sum of these five, so it generates no further equations.
    """
    coeffs = support_cubic_int_coeffs(B)
    quads = []
    for i in range(5):
        q = {}
        for (a, b, c), s in coeffs.items():
            trip = (a, b, c)
            if i not in trip or 5 in trip:
                continue
            rest = [v for v in trip if v != i]
            e = [0] * 5
            for v in rest:
                e[v] += 1
            e = tuple(e)
            q[e] = q.get(e, 0) + s
        quads.append({e: v for e, v in q.items() if v != 0})
    return quads


AXIS_CLASSES = [tuple(1 if i == a else 0 for i in range(5)) for a in range(5)]
AXIS_CLASSES.append((1, 1, 1, 1, 1))          # the class of e_5, since e_5 - 1 ~ (1,1,1,1,1)


def eval_quad(q, pt, mod=None):
    tot = 0
    for e, c in q.items():
        term = c
        for i, k in enumerate(e):
            if k:
                term *= pt[i] ** k
        tot += term
    return tot % mod if mod else tot


