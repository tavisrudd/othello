"""Exact corroboration for the C855 Hassett-Tschinkel determinantal transfer.

Companion to notes/2026-08-03-c855-hassett-tschinkel-transfer.md.  Every check is
deterministic and uses only the Python standard library.

Arithmetic model
----------------
Golden field: elements ``a + b*t`` with ``a, b`` rational and ``t^2 = t + 1``.
This is ``Q(sqrt5)`` with ``sqrt5 = 2t - 1``; the ring ``Z[t]/(t^2 - t - 1)`` is a
subring and every value printed below lies in it.  Nothing is evaluated
numerically and no floating point is used anywhere.

Both conference gauges are checked: the gauge displayed in the manuscript and
the gauge used by ``RelativeConicArcs.ClebschGoldenConference.conferenceMatrix``.
They are related by a row permutation and diagonal sign switching, so every
statement below must hold in both.

Checks
------
0  conference identity ``B^2 = 5I``; ``B U(t) = (2t-1) U(t)`` for both golden
   roots; ``U(1-t)^T U(t) = 0``.
A  Lemma A: the twenty three-by-three minors of ``U(t)`` all lie in
   ``{1, -1, t, -t}``, hence are units; equivalently the six rows are a plane
   six-arc and every nonzero eigenvector has at least four nonzero coordinates.
B  Lemma B: the six-by-six Veronese determinant of the six rows is nonzero,
   i.e. the six rows lie on no conic.
D  ``det(Phi_x) = -C(x)`` as an exact polynomial identity in ``x_0..x_5``.
J  the Jacobi bridge ``dC/dx_i = -trace(adj(Phi_x) * Phi_{e_i})``, again as an
   exact polynomial identity.
H  the singular locus of the cubic threefold: the homogeneous ideal generated by
   the partial derivatives has Hilbert function exactly ``6`` in degree six.
   Since ``6 <= 6``, Macaulay's bound makes the Hilbert function constantly
   ``6`` from degree six on, so the projective scheme cut out by the partials is
   finite of degree six; it contains the six distinct axis classes, so it is
   exactly those six reduced points.  The upper bound is obtained from a rank
   computation modulo a prime (a modular rank never exceeds the rational rank,
   so it bounds the Hilbert function from above in the direction needed), and
   the lower bound from an exact integer rank of the six-point evaluation
   matrix.
F  an independent exhaustive solve: over the fields of eleven and nineteen
   elements, where the golden root exists and the characteristic avoids two,
   three and five, every point of the projective four-space is tested and
   exactly the six axis classes satisfy all partials.

Replay
------
    python3 notes/2026-08-03-c855-hassett-tschinkel-checks.py

Exits 0 if and only if every check passes.
"""

from fractions import Fraction
from itertools import combinations, combinations_with_replacement
import sys

FAILURES = []


def report(name, ok, detail=""):
    tag = "PASS" if ok else "FAIL"
    line = "%s  %s" % (tag, name)
    if detail:
        line += "  --  " + detail
    print(line)
    if not ok:
        FAILURES.append(name)


# --------------------------------------------------------------------------
# exact arithmetic in Q(t), t^2 = t + 1
# --------------------------------------------------------------------------

class G(object):
    """a + b*t with t^2 = t + 1."""

    __slots__ = ("a", "b")

    def __init__(self, a=0, b=0):
        self.a = Fraction(a)
        self.b = Fraction(b)

    def __add__(self, o):
        o = coerce_g(o)
        return G(self.a + o.a, self.b + o.b)

    __radd__ = __add__

    def __neg__(self):
        return G(-self.a, -self.b)

    def __sub__(self, o):
        return self + (-coerce_g(o))

    def __rsub__(self, o):
        return coerce_g(o) + (-self)

    def __mul__(self, o):
        o = coerce_g(o)
        a, b, c, d = self.a, self.b, o.a, o.b
        # (a+bt)(c+dt) = ac + (ad+bc)t + bd t^2 = (ac+bd) + (ad+bc+bd) t
        return G(a * c + b * d, a * d + b * c + b * d)

    __rmul__ = __mul__

    def inv(self):
        # conjugate of a+bt under t -> 1-t is (a+b) - b t; the product is the norm
        n = self.a * self.a + self.a * self.b - self.b * self.b
        if n == 0:
            raise ZeroDivisionError("zero in the golden field")
        return G((self.a + self.b) / n, -self.b / n)

    def __eq__(self, o):
        o = coerce_g(o)
        return self.a == o.a and self.b == o.b

    def __hash__(self):
        return hash((self.a, self.b))

    def is_zero(self):
        return self.a == 0 and self.b == 0

    def __repr__(self):
        if self.b == 0:
            return str(self.a)
        if self.a == 0:
            return ("t" if self.b == 1 else ("-t" if self.b == -1 else "%s*t" % self.b))
        sign = "+" if self.b > 0 else "-"
        mag = abs(self.b)
        tail = "t" if mag == 1 else "%s*t" % mag
        return "%s %s %s" % (self.a, sign, tail)


def coerce_g(v):
    return v if isinstance(v, G) else G(v)


ZERO = G(0)
ONE = G(1)
T = G(0, 1)
TBAR = G(1, -1)          # 1 - t, the conjugate golden root
SQRT5 = G(-1, 2)         # 2t - 1


# --------------------------------------------------------------------------
# the two gauges
# --------------------------------------------------------------------------

B_PAPER = [
    [0, 1, 1, 1, 1, 1],
    [1, 0, 1, 1, -1, -1],
    [1, 1, 0, -1, 1, -1],
    [1, 1, -1, 0, -1, 1],
    [1, -1, 1, -1, 0, 1],
    [1, -1, -1, 1, 1, 0],
]

B_REPO = [
    [0, 1, 1, 1, -1, -1],
    [1, 0, -1, -1, -1, -1],
    [1, -1, 0, 1, 1, -1],
    [1, -1, 1, 0, -1, 1],
    [-1, -1, 1, -1, 0, -1],
    [-1, -1, -1, 1, -1, 0],
]


def U_paper(t):
    return [[t, t, -ONE], [t, ONE, -t], [ONE, t, -t],
            [ONE, ZERO, ZERO], [ZERO, ONE, ZERO], [ZERO, ZERO, ONE]]


def U_repo(t):
    return [[t, t, -ONE], [t, ONE, -t], [ZERO, ZERO, ONE],
            [ZERO, ONE, ZERO], [-ONE, -t, t], [-ONE, ZERO, ZERO]]


GAUGES = (("manuscript gauge", B_PAPER, U_paper),
          ("repository gauge", B_REPO, U_repo))


# --------------------------------------------------------------------------
# small dense linear algebra over the golden field
# --------------------------------------------------------------------------

def det3(m):
    return (m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1])
            - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0])
            + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0]))


def det_gauss(mat):
    """Determinant over the golden field by fraction-free-free Gaussian elimination."""
    n = len(mat)
    m = [[coerce_g(v) for v in row] for row in mat]
    det = ONE
    for c in range(n):
        piv = None
        for r in range(c, n):
            if not m[r][c].is_zero():
                piv = r
                break
        if piv is None:
            return ZERO
        if piv != c:
            m[c], m[piv] = m[piv], m[c]
            det = -det
        det = det * m[c][c]
        inv = m[c][c].inv()
        for r in range(c + 1, n):
            if m[r][c].is_zero():
                continue
            f = m[r][c] * inv
            for k in range(c, n):
                m[r][k] = m[r][k] - f * m[c][k]
    return det


# --------------------------------------------------------------------------
# multivariate polynomials over the golden field, six variables
# --------------------------------------------------------------------------

def p_zero():
    return {}


def p_add(p, q):
    r = dict(p)
    for e, c in q.items():
        s = r.get(e, ZERO) + c
        if s.is_zero():
            r.pop(e, None)
        else:
            r[e] = s
    return r


def p_neg(p):
    return {e: -c for e, c in p.items()}


def p_mul(p, q):
    r = {}
    for e1, c1 in p.items():
        for e2, c2 in q.items():
            e = tuple(a + b for a, b in zip(e1, e2))
            s = r.get(e, ZERO) + c1 * c2
            if s.is_zero():
                r.pop(e, None)
            else:
                r[e] = s
    return r


def p_const(c):
    c = coerce_g(c)
    return {} if c.is_zero() else {(0,) * 6: c}


def p_var(i):
    e = [0] * 6
    e[i] = 1
    return {tuple(e): ONE}


def p_is_zero(p):
    return not p


def p_diff(p, i):
    r = {}
    for e, c in p.items():
        if e[i] == 0:
            continue
        ee = list(e)
        ee[i] -= 1
        k = tuple(ee)
        s = r.get(k, ZERO) + G(e[i]) * c
        if s.is_zero():
            r.pop(k, None)
        else:
            r[k] = s
    return r


def pm_det3(m):
    def mul(a, b):
        return p_mul(a, b)

    def sub(a, b):
        return p_add(a, p_neg(b))

    t1 = mul(m[0][0], sub(mul(m[1][1], m[2][2]), mul(m[1][2], m[2][1])))
    t2 = mul(m[0][1], sub(mul(m[1][0], m[2][2]), mul(m[1][2], m[2][0])))
    t3 = mul(m[0][2], sub(mul(m[1][0], m[2][1]), mul(m[1][1], m[2][0])))
    return p_add(p_add(t1, p_neg(t2)), t3)


def pm_adjugate3(m):
    """adj(A) with A * adj(A) = det(A) * I, i.e. the transposed cofactor matrix."""
    def minor(i, j):
        rows = [r for r in range(3) if r != i]
        cols = [c for c in range(3) if c != j]
        a = m[rows[0]][cols[0]]
        b = m[rows[0]][cols[1]]
        c = m[rows[1]][cols[0]]
        d = m[rows[1]][cols[1]]
        return p_add(p_mul(a, d), p_neg(p_mul(b, c)))

    adj = [[None] * 3 for _ in range(3)]
    for i in range(3):
        for j in range(3):
            cof = minor(j, i)
            if (i + j) % 2 == 1:
                cof = p_neg(cof)
            adj[i][j] = cof
    return adj


def pm_trace_mul(a, b):
    tot = p_zero()
    for i in range(3):
        for j in range(3):
            tot = p_add(tot, p_mul(a[i][j], b[j][i]))
    return tot


