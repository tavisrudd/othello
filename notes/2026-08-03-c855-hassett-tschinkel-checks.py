def cross_block_poly(U):
    """Phi_x = U(1-t)^T diag(x) U(t) as a matrix of linear polynomials."""
    Um, Up = U(TBAR), U(T)
    m = [[p_zero() for _ in range(3)] for _ in range(3)]
    for i in range(3):
        for j in range(3):
            acc = p_zero()
            for k in range(6):
                coef = Um[k][i] * Up[k][j]
                if not coef.is_zero():
                    acc = p_add(acc, {tuple(1 if v == k else 0 for v in range(6)): coef})
            m[i][j] = acc
    return m


def cross_block_axis(U, a):
    """Phi_{e_a} as a constant matrix."""
    Um, Up = U(TBAR), U(T)
    return [[p_const(Um[a][i] * Up[a][j]) for j in range(3)] for i in range(3)]


def support_cubic_poly(B):
    tot = p_zero()
    for i, j, k in combinations(range(6), 3):
        c = B[i][j] * B[j][k] * B[k][i]
        e = [0] * 6
        e[i] = e[j] = e[k] = 1
        tot = p_add(tot, {tuple(e): G(c)})
    return tot


def support_cubic_int_coeffs(B):
    """C as {sorted triple: +-1}, for the integer-side computations."""
    return {(i, j, k): B[i][j] * B[j][k] * B[k][i]
            for i, j, k in combinations(range(6), 3)}


