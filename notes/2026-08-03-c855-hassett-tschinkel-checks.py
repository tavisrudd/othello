def check_conference():
    for name, B, U in GAUGES:
        ok = True
        for i in range(6):
            for j in range(6):
                s = sum(B[i][k] * B[k][j] for k in range(6))
                if s != (5 if i == j else 0):
                    ok = False
        report("check 0  %s: B^2 = 5I" % name, ok)

        for t, lab, sign in ((T, "t", "+"), (TBAR, "1-t", "-")):
            Ut = U(t)
            lam = (G(2) * t) - ONE
            good = True
            for i in range(6):
                for j in range(3):
                    lhs = ZERO
                    for k in range(6):
                        lhs = lhs + G(B[i][k]) * Ut[k][j]
                    if not (lhs - lam * Ut[i][j]).is_zero():
                        good = False
            report("check 0  %s: B U(%s) = %ssqrt5 U(%s)" % (name, lab, sign, lab), good)

        Um, Up = U(TBAR), U(T)
        good = True
        for i in range(3):
            for j in range(3):
                s = ZERO
                for k in range(6):
                    s = s + Um[k][i] * Up[k][j]
                if not s.is_zero():
                    good = False
        report("check 0  %s: U(1-t)^T U(t) = 0" % name, good)


