fn vec_json(v: &[usize]) -> String {
    let s: Vec<String> = v.iter().map(|x| x.to_string()).collect();
    format!("[{}]", s.join(","))
}
fn edges_json(edges: &[(usize, usize)]) -> String {
    edges
        .iter()
        .map(|(u, v)| format!("[{},{}]", u, v))
        .collect::<Vec<_>>()
        .join(",")
}
fn c284_row_line(r: &TemplateRow) -> String {
    format!(
        "{{\"group\":\"{}\",\"pair_orders\":{},\"triple_product_orders\":{},\"triple_count\":{},\"K\":\"{}\",\"projective_line_stabilizer\":{},\"korder\":{},\"coset_size\":{},\"deleted\":{},\"residual_vertices\":{},\"components\":{},\"edges\":[{}],\"nimber\":{},\"nimber_plain\":{}}}",
        r.group,
        vec_json(&r.class[..3]),
        vec_json(&r.class[4..]),
        r.triple_count,
        r.kname,
        r.kname != "C2b",
        r.korder,
        r.coset_size,
        r.deleted,
        r.residual_vertices,
        vec_json(&r.components),
        edges_json(&r.edges),
        r.nimber,
        r.nimber_plain
    )
}

struct C284Cmp {
    template_rows: usize,
    template_matches: usize,
    conic_rows: usize,
    conic_rows_matched: usize,
    conic_triples: usize,
    orbit_mismatches: usize,
    value_comparisons: usize,
    value_mismatches: usize,
}

fn compare_c284(text: &str, rows: &[&TemplateRow], census: &[CensusRow]) -> C284Cmp {
    let mut cmp = C284Cmp {
        template_rows: rows.len(),
        template_matches: 0,
        conic_rows: 0,
        conic_rows_matched: 0,
        conic_triples: 0,
        orbit_mismatches: 0,
        value_comparisons: 0,
        value_mismatches: 0,
    };
    for r in rows {
        if text.contains(&c284_row_line(r)) {
            cmp.template_matches += 1;
        }
    }
    let domain: [(&str, usize); 10] = [
        ("A5", 11),
        ("A5", 19),
        ("A5", 29),
        ("A5", 31),
        ("A5", 41),
        ("S4", 7),
        ("S4", 17),
        ("S4", 23),
        ("S4", 31),
        ("S4", 41),
    ];
    for (gname, q) in domain {
        cmp.conic_rows += 1;
        let tag = format!("\"group\":\"{}\",\"q\":{},", gname, q);
        let start = match text.find(&tag) {
            Some(s) => s,
            None => continue,
        };
        let line = &text[start..text[start..].find('\n').map_or(text.len(), |e| start + e)];
        // orbit types
        let my = census
            .iter()
            .find(|c| c.gname == gname && c.q == q)
            .expect("census missing C284 domain row");
        let my_orbits: Vec<String> = my
            .orbit_size_stab
            .iter()
            .map(|(s, k)| format!("[{},{}]", s, k))
            .collect();
        let want = format!("\"orbit_size_stab\":[{}]", my_orbits.join(","));
        if !line.contains(&want) {
            cmp.orbit_mismatches += 1;
        }
        // triples tested
        let tt_key = "\"triples_tested\":";
        if let Some(tp) = line.find(tt_key) {
            let rest = &line[tp + tt_key.len()..];
            let num: usize = rest[..rest.find(',').unwrap()].parse().unwrap();
            cmp.conic_triples += num;
            if num == my.triples {
                cmp.conic_rows_matched += 1;
            }
        }
        // per-class board values
        for cc in &my.classes {
            let prefix = format!(
                "{{\"pair_orders\":{},\"triple_product_orders\":{},\"board_formula_values\":[",
                vec_json(&cc.sig[..3]),
                vec_json(&cc.sig[4..])
            );
            let cs = match line.find(&prefix) {
                Some(x) => x + prefix.len(),
                None => {
                    cmp.value_mismatches += 1;
                    continue;
                }
            };
            let rest = &line[cs..];
            let end = rest.find("]}").unwrap();
            let vals = &rest[..end]; // like "[0,0]" or "[0,0],[\"free-cited\",0]"
            for entry in vals.split("],[") {
                let e = entry.trim_start_matches('[').trim_end_matches(']');
                let parts: Vec<&str> = e.split(',').collect();
                assert_eq!(parts.len(), 2);
                cmp.value_comparisons += 1;
                let formula: u8 = parts[1].parse().unwrap();
                let direct_ok = if parts[0].starts_with('"') {
                    true // "free-cited": no direct value recorded by C284
                } else {
                    parts[0].parse::<u8>().unwrap() == cc.board_value
                };
                if formula != cc.board_value || !direct_ok {
                    cmp.value_mismatches += 1;
                }
            }
        }
    }
    cmp
}

