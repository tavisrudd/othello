// C288 -- Exhaustive tame polyhedral (S4/A5) projective-line embedding census for
// all odd prime powers q <= 101.  Self-contained deterministic enumerator/checker.
//
// Relation to C284: the abstract coset-template classifier (Part 1 of the C284
// script) is ported verbatim as the reference; everything field-side below is an
// INDEPENDENT computation.  The census enumerates, for every admissible tame q,
// an explicit matrix realization of S4 / A5 inside PGL_2(F_q) -- including the
// prime-power fields q = 25, 49 and every tame congruence class, not only the
// C284 sample -- and verifies orbit types, split indicators, refined (sigma,rho)
// triple classes, per-orbit residual nimbers, and full-board values.
//
// Conventions (load-bearing):
//   * Board = P^1(F_q), indexed 0..q-1 = [z:1], q = [1:0] (infinity).
//   * A realization is a subgroup G < PGL_2(q), G iso S4 or A5, generated by an
//     unordered generating involution triple T; involutions are the trace-zero
//     classes of PGL_2(q) (q^2 of them, asserted).
//   * DEAD set = union of rational fixed points of the three pair products;
//     residual = fixed-point-deleted Schreier graph, edges u -- t(u), t in T.
//   * value = Node-Kayles Grundy value (nimber) of the residual.
//   * REALIZATION EQUIVALENCE: subgroups are enumerated up to PGL_2(q)-conjugacy.
//     Dickson's subgroup classification gives exactly one class per admissible
//     (group, q); this reduction is verified exhaustively (every involution
//     triple, every subgroup, union-find under PGL_2-conjugation) at q = 7, 13
//     (S4) and q = 11 (A5), and the normalizer index |PGL_2(q)|/|N(G)| is
//     computed for every q (N(G) = G asserted).
//   * TAME (C283 boundary): p = char F_q does not divide |G|.  Excluded as wild:
//     p = 3 (q = 3, 9, 27, 81; both groups since 3 | 24 and 3 | 60) and p = 5
//     (q = 5, 25; A5 only since 5 | 60).  A5 additionally requires
//     q = +-1 mod 5; otherwise 5 does not divide |PGL_2(q)| = q^3 - q (asserted
//     arithmetically), so PGL_2(q) has no element of order 5 and no A5.
//   * Prime-power fields F_{p^2} are built as F_p[x]/(x^2+bx+c) with the
//     lexicographically smallest (b, c) making x^2+bx+c irreducible
//     (q = 25: x^2+2; q = 49: x^2+1).  Tame q <= 101 forces k <= 2.
//   * A5 regular values t_1 are cited from Appendix A / C260 plus the C284
//     regular-extra replay ((2,3,5):1, (2,5,5):1, others 0; both rho classes of
//     (3,5,5) are 0); S4 regular values are recomputed abstractly here.
//
// Determinism: fixed canonical enumeration everywhere, no randomness, no seeds,
// no timestamps, no host paths in the output.  JSON is sorted and canonical.
//
// Usage (working directory rust/):
//   rustc -O ../notes/2026-07-17-c288-polyhedral-embedding-census.rs -o /tmp/c288-census
//   /tmp/c288-census check ../notes/2026-07-17-c284-dihedral-polyhedral-coset-templates.json
