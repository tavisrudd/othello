use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};

// ----------------------------------------------------------------------------
// Node-Kayles Grundy engine over a <=64-vertex bitmask adjacency (C284 port).
// ----------------------------------------------------------------------------

fn component(mask: u64, start: u64, adj: &[u64]) -> u64 {
    let mut comp = start;
    loop {
        let mut nb = 0u64;
        let mut b = comp;
        while b != 0 {
            let v = b.trailing_zeros() as usize;
            nb |= adj[v];
            b &= b - 1;
        }
        let new = comp | (nb & mask);
        if new == comp {
            return comp;
        }
        comp = new;
    }
}

fn grundy_plain(mask: u64, adj: &[u64], closed: &[u64], memo: &mut HashMap<u64, u8>) -> u8 {
    if mask == 0 {
        return 0;
    }
    let mut rem = mask;
    let mut g = 0u8;
    while rem != 0 {
        let start = rem & rem.wrapping_neg();
        let comp = component(rem, start, adj);
        g ^= grundy_conn_plain(comp, adj, closed, memo);
        rem &= !comp;
    }
    g
}
fn grundy_conn_plain(mask: u64, adj: &[u64], closed: &[u64], memo: &mut HashMap<u64, u8>) -> u8 {
    if let Some(&v) = memo.get(&mask) {
        return v;
    }
    let mut opts = 0u64;
    let mut b = mask;
    while b != 0 {
        let v = b.trailing_zeros() as usize;
        let child = mask & !closed[v];
        let cg = grundy_plain(child, adj, closed, memo);
        opts |= 1u64 << cg;
        b &= b - 1;
    }
    let m = (!opts).trailing_zeros() as u8;
    memo.insert(mask, m);
    m
}

fn apply_perm(mask: u64, perm: &[u32]) -> u64 {
    let mut r = 0u64;
    let mut b = mask;
    while b != 0 {
        let v = b.trailing_zeros() as usize;
        r |= 1u64 << perm[v];
        b &= b - 1;
    }
    r
}
fn canonical(mask: u64, gperms: &[Vec<u32>]) -> u64 {
    let mut best = mask;
    for p in gperms {
        let m = apply_perm(mask, p);
        if m < best {
            best = m;
        }
    }
    best
}
fn grundy_canon(
    mask: u64,
    adj: &[u64],
    closed: &[u64],
    gperms: &[Vec<u32>],
    memo: &mut HashMap<u64, u8>,
) -> u8 {
    if mask == 0 {
        return 0;
    }
    let mut rem = mask;
    let mut g = 0u8;
    while rem != 0 {
        let start = rem & rem.wrapping_neg();
        let comp = component(rem, start, adj);
        g ^= grundy_conn_canon(comp, adj, closed, gperms, memo);
        rem &= !comp;
    }
    g
}
fn grundy_conn_canon(
    mask: u64,
    adj: &[u64],
    closed: &[u64],
    gperms: &[Vec<u32>],
    memo: &mut HashMap<u64, u8>,
) -> u8 {
    let key = canonical(mask, gperms);
    if let Some(&v) = memo.get(&key) {
        return v;
    }
    let mut opts = 0u64;
    let mut b = mask;
    while b != 0 {
        let v = b.trailing_zeros() as usize;
        let child = mask & !closed[v];
        let cg = grundy_canon(child, adj, closed, gperms, memo);
        opts |= 1u64 << cg;
        b &= b - 1;
    }
    let m = (!opts).trailing_zeros() as u8;
    memo.insert(key, m);
    m
}

// ----------------------------------------------------------------------------
// Abstract permutation groups and coset templates (C284 Part 1, ported).
// ----------------------------------------------------------------------------

fn pmul(p: &[usize], q: &[usize]) -> Vec<usize> {
    (0..q.len()).map(|i| p[q[i]]).collect()
}
fn pinv(p: &[usize]) -> Vec<usize> {
    let mut out = vec![0; p.len()];
    for (i, &pi) in p.iter().enumerate() {
        out[pi] = i;
    }
    out
}
fn is_ident(p: &[usize]) -> bool {
    p.iter().enumerate().all(|(i, &x)| i == x)
}
fn perm_order(p: &[usize]) -> usize {
    let mut x = p.to_vec();
    let mut o = 1;
    while !is_ident(&x) {
        x = pmul(p, &x);
        o += 1;
    }
    o
}
fn sign(p: &[usize]) -> i32 {
    let mut inv = 0;
    for i in 0..p.len() {
        for j in (i + 1)..p.len() {
            if p[i] > p[j] {
                inv += 1;
            }
        }
    }
    if inv % 2 == 0 {
        1
    } else {
        -1
    }
}
fn all_perms(n: usize) -> Vec<Vec<usize>> {
    let mut v: Vec<usize> = (0..n).collect();
    let mut out = Vec::new();
    permute(&mut v, 0, &mut out);
    out.sort();
    out
}
fn permute(v: &mut Vec<usize>, k: usize, out: &mut Vec<Vec<usize>>) {
    if k == v.len() {
        out.push(v.clone());
        return;
    }
    for i in k..v.len() {
        v.swap(k, i);
        permute(v, k + 1, out);
        v.swap(k, i);
    }
}
fn cyclic_powers(h: &[usize]) -> Vec<Vec<usize>> {
    let n = h.len();
    let ident: Vec<usize> = (0..n).collect();
    let mut out = vec![ident.clone()];
    let mut cur = h.to_vec();
    while !is_ident(&cur) {
        out.push(cur.clone());
        cur = pmul(h, &cur);
    }
    out.sort();
    out
}

struct TemplateRow {
    group: String,
    class: Vec<usize>,
    triple_count: usize,
    kname: String,
    korder: usize,
    coset_size: usize,
    deleted: usize,
    residual_vertices: usize,
    components: Vec<usize>,
    edges: Vec<(usize, usize)>,
    nimber: u8,
    nimber_plain: u8,
}

fn coset_of(g: &[usize], kelems: &[Vec<usize>], index: &HashMap<Vec<usize>, usize>) -> usize {
    kelems.iter().map(|k| index[&pmul(g, k)]).min().unwrap()
}

struct AbstractResult {
    rows: Vec<TemplateRow>,
    tk: HashMap<(String, Vec<usize>, usize), u8>,
    class_counts: BTreeMap<Vec<usize>, usize>,
}

fn abstract_group(
    gname: &str,
    n: usize,
    even_only: bool,
    kreps: &[(&str, Vec<usize>)],
    skip_regular: bool,
) -> AbstractResult {
    let automorphisms = all_perms(n);
    let els: Vec<Vec<usize>> = automorphisms
        .iter()
        .cloned()
        .filter(|p| !even_only || sign(p) == 1)
        .collect();
    let index: HashMap<Vec<usize>, usize> = els
        .iter()
        .cloned()
        .enumerate()
        .map(|(i, g)| (g, i))
        .collect();
    let target = els.len();
    let invols: Vec<Vec<usize>> = els
        .iter()
        .filter(|p| !is_ident(p) && is_ident(&pmul(p, p)))
        .cloned()
        .collect();

    let mut reps: BTreeMap<Vec<usize>, [Vec<usize>; 3]> = BTreeMap::new();
    let mut class_counts: BTreeMap<Vec<usize>, usize> = BTreeMap::new();
    let mut class_aut_orbits: BTreeMap<Vec<usize>, BTreeSet<Vec<usize>>> = BTreeMap::new();
    for i in 0..invols.len() {
        for j in (i + 1)..invols.len() {
            for k in (j + 1)..invols.len() {
                let tri = [invols[i].clone(), invols[j].clone(), invols[k].clone()];
                if closure_perm(&tri, n).len() != target {
                    continue;
                }
                let mut sig = vec![
                    perm_order(&pmul(&tri[0], &tri[1])),
                    perm_order(&pmul(&tri[0], &tri[2])),
                    perm_order(&pmul(&tri[1], &tri[2])),
                ];
                sig.sort();
                let mut triple_orders = vec![
                    perm_order(&pmul(&pmul(&tri[0], &tri[1]), &tri[2])),
                    perm_order(&pmul(&pmul(&tri[0], &tri[2]), &tri[1])),
                    perm_order(&pmul(&pmul(&tri[1], &tri[0]), &tri[2])),
                    perm_order(&pmul(&pmul(&tri[1], &tri[2]), &tri[0])),
                    perm_order(&pmul(&pmul(&tri[2], &tri[0]), &tri[1])),
                    perm_order(&pmul(&pmul(&tri[2], &tri[1]), &tri[0])),
                ];
                triple_orders.sort();
                sig.push(0);
                sig.extend(triple_orders);
                let mut aut_key: Option<Vec<usize>> = None;
                for a in &automorphisms {
                    let ai = pinv(a);
                    let mut ids: Vec<usize> =
                        tri.iter().map(|t| index[&pmul(&pmul(a, t), &ai)]).collect();
                    ids.sort();
                    if aut_key.as_ref().map_or(true, |best| ids < *best) {
                        aut_key = Some(ids);
                    }
                }
                *class_counts.entry(sig.clone()).or_default() += 1;
                class_aut_orbits
                    .entry(sig.clone())
                    .or_default()
                    .insert(aut_key.unwrap());
                reps.entry(sig).or_insert(tri);
            }
        }
    }
    assert!(class_aut_orbits.values().all(|orbits| orbits.len() == 1));

    let mut rows = Vec::new();
    let mut tk = HashMap::new();

    for (sig, tri) in &reps {
        for (kname, kgen) in kreps {
            let korder = perm_order(kgen).max(1);
            let kelems = cyclic_powers(kgen);
            if skip_regular && kelems.len() == 1 && korder == 1 {
                continue;
            }
            let mut coset_id: HashMap<usize, usize> = HashMap::new();
            let mut reps_g: Vec<Vec<usize>> = Vec::new();
            for g in &els {
                let cid = coset_of(g, &kelems, &index);
                if !coset_id.contains_key(&cid) {
                    coset_id.insert(cid, reps_g.len());
                    reps_g.push(els[cid].clone());
                }
            }
            let vcount = reps_g.len();
            if vcount > 62 {
                continue;
            }
            let mut adj = vec![0u64; vcount];
            for (ci, g) in reps_g.iter().enumerate() {
                for t in tri.iter() {
                    let ncid = coset_of(&pmul(t, g), &kelems, &index);
                    let cj = coset_id[&ncid];
                    if ci != cj {
                        adj[ci] |= 1u64 << cj;
                        adj[cj] |= 1u64 << ci;
                    }
                }
            }
            let pairprods = [
                pmul(&tri[0], &tri[1]),
                pmul(&tri[0], &tri[2]),
                pmul(&tri[1], &tri[2]),
            ];
            let mut alive = if vcount == 64 {
                u64::MAX
            } else {
                (1u64 << vcount) - 1
            };
            let mut deleted = 0usize;
            for (ci, g) in reps_g.iter().enumerate() {
                let gc = coset_of(g, &kelems, &index);
                let mut dead = false;
                for h in pairprods.iter() {
                    if coset_of(&pmul(h, g), &kelems, &index) == gc {
                        dead = true;
                        break;
                    }
                }
                if dead {
                    alive &= !(1u64 << ci);
                    deleted += 1;
                }
            }
            let mut radj = vec![0u64; vcount];
            for v in 0..vcount {
                if alive & (1u64 << v) != 0 {
                    radj[v] = adj[v] & alive;
                }
            }
            let closed: Vec<u64> = (0..vcount).map(|v| radj[v] | (1u64 << v)).collect();

            let rightmul: Vec<Vec<u32>> = els
                .iter()
                .filter(|a| {
                    let acid = coset_of(a, &kelems, &index);
                    kelems
                        .iter()
                        .all(|k| coset_of(&pmul(k, a), &kelems, &index) == acid)
                })
                .map(|a| {
                    reps_g
                        .iter()
                        .map(|g| coset_id[&coset_of(&pmul(g, a), &kelems, &index)] as u32)
                        .collect()
                })
                .collect();

            let mut memo_c: HashMap<u64, u8> = HashMap::new();
            let nimber = grundy_canon(alive, &radj, &closed, &rightmul, &mut memo_c);
            let nimber_plain = if vcount <= 40 {
                let mut memo_p: HashMap<u64, u8> = HashMap::new();
                grundy_plain(alive, &radj, &closed, &mut memo_p)
            } else {
                nimber
            };

            let mut comps = Vec::new();
            let mut rem = alive;
            while rem != 0 {
                let start = rem & rem.wrapping_neg();
                let c = component(rem, start, &radj);
                comps.push((c.count_ones()) as usize);
                rem &= !c;
            }
            comps.sort();

            let mut relabel = vec![usize::MAX; vcount];
            let mut next = 0usize;
            for v in 0..vcount {
                if alive & (1u64 << v) != 0 {
                    relabel[v] = next;
                    next += 1;
                }
            }
            let mut edges = Vec::new();
            for v in 0..vcount {
                if relabel[v] == usize::MAX {
                    continue;
                }
                for w in (v + 1)..vcount {
                    if relabel[w] != usize::MAX && radj[v] & (1u64 << w) != 0 {
                        edges.push((relabel[v], relabel[w]));
                    }
                }
            }

            rows.push(TemplateRow {
                group: gname.to_string(),
                class: sig.clone(),
                triple_count: class_counts[sig],
                kname: kname.to_string(),
                korder,
                coset_size: vcount,
                deleted,
                residual_vertices: (vcount - deleted),
                components: comps,
                edges,
                nimber,
                nimber_plain,
            });
            if *kname != "C2b" {
                tk.insert((gname.to_string(), sig.clone(), korder), nimber);
            }
        }
    }
    AbstractResult {
        rows,
        tk,
        class_counts,
    }
}

fn closure_perm(gens: &[Vec<usize>], n: usize) -> Vec<Vec<usize>> {
    let ident: Vec<usize> = (0..n).collect();
    let mut set: HashSet<Vec<usize>> = HashSet::new();
    set.insert(ident.clone());
    let mut frontier = vec![ident];
    while let Some(g) = frontier.pop() {
        for s in gens {
            let h = pmul(&g, s);
            if set.insert(h.clone()) {
                frontier.push(h);
            }
        }
    }
    set.into_iter().collect()
}

// ----------------------------------------------------------------------------
// Finite fields F_q, q = p^k, k <= 2, via full tables (q <= 101).
// ----------------------------------------------------------------------------

struct Fq {
    q: usize,
    p: usize,
    k: usize,
    addt: Vec<u16>,
    mult: Vec<u16>,
    negt: Vec<u16>,
    invt: Vec<u16>,
    poly: String,
}

impl Fq {
    fn build(p: usize, k: usize) -> Fq {
        assert!(k >= 1 && k <= 2, "tame q <= 101 forces k <= 2");
        let q = p.pow(k as u32);
        let mut addt = vec![0u16; q * q];
        let mut mult = vec![0u16; q * q];
        let mut negt = vec![0u16; q];
        let poly;
        if k == 1 {
            poly = "prime".to_string();
            for x in 0..q {
                negt[x] = ((q - x) % q) as u16;
                for y in 0..q {
                    addt[x * q + y] = ((x + y) % q) as u16;
                    mult[x * q + y] = ((x * y) % q) as u16;
                }
            }
        } else {
            // canonical irreducible x^2 + b x + c: lexicographically smallest (b, c)
            let mut fb = usize::MAX;
            let mut fc = usize::MAX;
            'outer: for b in 0..p {
                for c in 0..p {
                    if (0..p).all(|x| (x * x + b * x + c) % p != 0) {
                        fb = b;
                        fc = c;
                        break 'outer;
                    }
                }
            }
            assert!(fb != usize::MAX);
            poly = format!("x^2+{}x+{}", fb, fc);
            // element e = c0 + p*c1  <->  c0 + c1 x
            for x in 0..q {
                let (x0, x1) = (x % p, x / p);
                negt[x] = (((p - x0) % p) + p * ((p - x1) % p)) as u16;
                for y in 0..q {
                    let (y0, y1) = (y % p, y / p);
                    addt[x * q + y] = (((x0 + y0) % p) + p * ((x1 + y1) % p)) as u16;
                    // (x0 + x1 t)(y0 + y1 t), t^2 = -(fb t + fc)
                    let hi = x1 * y1 % p;
                    let c0 = (x0 * y0 + (p - fc % p) * hi) % p;
                    let c1 = (x0 * y1 + x1 * y0 + (p - fb % p) * hi) % p;
                    mult[x * q + y] = (c0 + p * c1) as u16;
                }
            }
        }
        let mut invt = vec![0u16; q];
        for x in 1..q {
            let mut found = false;
            for y in 1..q {
                if mult[x * q + y] == 1 {
                    invt[x] = y as u16;
                    found = true;
                    break;
                }
            }
            assert!(found, "no inverse: field construction broken");
        }
        Fq {
            q,
            p,
            k,
            addt,
            mult,
            negt,
            invt,
            poly,
        }
    }
    #[inline]
    fn a(&self, x: usize, y: usize) -> usize {
        self.addt[x * self.q + y] as usize
    }
    #[inline]
    fn m(&self, x: usize, y: usize) -> usize {
        self.mult[x * self.q + y] as usize
    }
    #[inline]
    fn n(&self, x: usize) -> usize {
        self.negt[x] as usize
    }
    #[inline]
    fn s(&self, x: usize, y: usize) -> usize {
        self.a(x, self.n(y))
    }
    #[inline]
    fn iv(&self, x: usize) -> usize {
        self.invt[x] as usize
    }
    fn mul_order(&self, x: usize) -> usize {
        assert!(x != 0);
        let mut cur = x;
        let mut o = 1;
        while cur != 1 {
            cur = self.m(cur, x);
            o += 1;
        }
        o
    }
}

// ----------------------------------------------------------------------------
// PGL_2(F_q): normalized matrices, action on P^1, involutions.
// ----------------------------------------------------------------------------

type M = [usize; 4];
const IDENT: M = [1, 0, 0, 1];

fn mnorm(f: &Fq, m: M) -> M {
    let mut fac = 0usize;
    for &x in m.iter() {
        if x != 0 {
            fac = x;
            break;
        }
    }
    assert!(fac != 0);
    let fi = f.iv(fac);
    [f.m(m[0], fi), f.m(m[1], fi), f.m(m[2], fi), f.m(m[3], fi)]
}
fn mmul(f: &Fq, x: M, y: M) -> M {
    mnorm(
        f,
        [
            f.a(f.m(x[0], y[0]), f.m(x[1], y[2])),
            f.a(f.m(x[0], y[1]), f.m(x[1], y[3])),
            f.a(f.m(x[2], y[0]), f.m(x[3], y[2])),
            f.a(f.m(x[2], y[1]), f.m(x[3], y[3])),
        ],
    )
}
fn minv(f: &Fq, m: M) -> M {
    mnorm(f, [m[3], f.n(m[1]), f.n(m[2]), m[0]])
}
fn morder(f: &Fq, m: M) -> usize {
    let m = mnorm(f, m);
    let mut cur = m;
    let mut k = 1usize;
    while cur != IDENT {
        cur = mmul(f, cur, m);
        k += 1;
        assert!(k <= f.q + 2, "element order exceeds q+1: broken arithmetic");
    }
    k
}
// P^1(F_q): 0..q-1 is [z:1], q is [1:0].
fn mact(f: &Fq, m: M, pt: usize) -> usize {
    let (num, den);
    if pt < f.q {
        num = f.a(f.m(m[0], pt), m[1]);
        den = f.a(f.m(m[2], pt), m[3]);
    } else {
        num = m[0];
        den = m[2];
    }
    if den == 0 {
        f.q
    } else {
        f.m(num, f.iv(den))
    }
}

// All q^2 involutions of PGL_2(q), as normalized trace-zero matrices.
fn involutions(f: &Fq) -> Vec<M> {
    let q = f.q;
    let mut v: Vec<M> = Vec::with_capacity(q * q);
    for c in 1..q {
        v.push([0, 1, c, 0]);
    }
    let n1 = f.n(1);
    for b in 0..q {
        for c in 0..q {
            if f.m(b, c) != n1 {
                v.push([1, b, c, n1]);
            }
        }
    }
    v.sort();
    assert_eq!(v.len(), q * q, "involutions count != q^2");
    for m in &v {
        assert_eq!(f.a(m[0], m[3]), 0);
        assert!(f.s(f.m(m[0], m[3]), f.m(m[1], m[2])) != 0);
    }
    v
}

// Iterate every element of PGL_2(q) exactly once (normalized forms, no dedup).
fn for_each_pgl2<F: FnMut(M)>(f: &Fq, mut cb: F) -> usize {
    let q = f.q;
    let mut count = 0usize;
    for b in 0..q {
        for c in 0..q {
            let bc = f.m(b, c);
            for d in 0..q {
                if d != bc {
                    cb([1, b, c, d]);
                    count += 1;
                }
            }
        }
    }
    for c in 1..q {
        for d in 0..q {
            cb([0, 1, c, d]);
            count += 1;
        }
    }
    assert_eq!(count, q * q * q - q, "|PGL_2(q)| != q^3 - q");
    count
}

fn find_elem_of_order(f: &Fq, r: usize) -> M {
    let q = f.q;
    for b in 0..q {
        for c in 0..q {
            let bc = f.m(b, c);
            for d in 0..q {
                if d != bc && morder(f, [1, b, c, d]) == r {
                    return [1, b, c, d];
                }
            }
        }
    }
    for c in 1..q {
        for d in 0..q {
            if morder(f, [0, 1, c, d]) == r {
                return [0, 1, c, d];
            }
        }
    }
    panic!("no element of order {} in PGL_2({})", r, q);
}

fn closure_mat(f: &Fq, gens: &[M], cap: usize) -> Vec<M> {
    let mut set: HashSet<M> = HashSet::new();
    set.insert(IDENT);
    let mut frontier = vec![IDENT];
    let gens: Vec<M> = gens.iter().map(|&g| mnorm(f, g)).collect();
    while let Some(g) = frontier.pop() {
        for &s in &gens {
            let h = mmul(f, g, s);
            if set.insert(h) {
                frontier.push(h);
                if set.len() > cap {
                    return set.into_iter().collect();
                }
            }
        }
    }
    let mut v: Vec<M> = set.into_iter().collect();
    v.sort();
    v
}

fn order_histogram(f: &Fq, elems: &[M]) -> BTreeMap<usize, usize> {
    let mut h = BTreeMap::new();
    for &e in elems {
        *h.entry(morder(f, e)).or_default() += 1;
    }
    h
}

fn signature_ok(f: &Fq, elems: &[M], gname: &str) -> bool {
    let h = order_histogram(f, elems);
    match gname {
        "S4" => h == BTreeMap::from([(1, 1), (2, 9), (3, 8), (4, 6)]),
        "A5" => h == BTreeMap::from([(1, 1), (2, 15), (3, 20), (5, 24)]),
        _ => false,
    }
}

// ----------------------------------------------------------------------------
// One tame realization per (group, q): find, tabulate, census.
// ----------------------------------------------------------------------------

struct Real {
    n: usize,
    elems: Vec<M>,
    mul: Vec<u16>,   // n*n index multiplication table
    ord: Vec<usize>, // element orders
    conj: Vec<usize>, // conjugacy class size within G
    perm: Vec<Vec<u16>>, // action on P^1
    ide: usize,
    invs: Vec<usize>, // involution indices
    gens: [M; 2],     // (order-r element, involution) found generators
}

fn find_realization(f: &Fq, gname: &str) -> Real {
    let (rord, target) = match gname {
        "S4" => (4usize, 24usize),
        "A5" => (5usize, 60usize),
        _ => unreachable!(),
    };
    let gr = find_elem_of_order(f, rord);
    let all_inv = involutions(f);
    let mut found: Option<(Vec<M>, M)> = None;
    for &t in &all_inv {
        let cl = closure_mat(f, &[gr, t], target + 4);
        if cl.len() == target && signature_ok(f, &cl, gname) {
            found = Some((cl, t));
            break;
        }
    }
    let (elems, t0) = found.unwrap_or_else(|| panic!("no {} found in PGL_2({})", gname, f.q));
    let n = elems.len();
    let idx: HashMap<M, usize> = elems.iter().cloned().enumerate().map(|(i, e)| (e, i)).collect();
    let mut mul = vec![0u16; n * n];
    for i in 0..n {
        for j in 0..n {
            mul[i * n + j] = idx[&mmul(f, elems[i], elems[j])] as u16;
        }
    }
    let ide = idx[&IDENT];
    let ord: Vec<usize> = elems.iter().map(|&e| morder(f, e)).collect();
    let inv_of: Vec<usize> = (0..n)
        .map(|i| (0..n).find(|&j| mul[i * n + j] as usize == ide).unwrap())
        .collect();
    let conj: Vec<usize> = (0..n)
        .map(|i| {
            let set: BTreeSet<usize> = (0..n)
                .map(|h| {
                    let hi = mul[h * n + i] as usize;
                    mul[hi * n + inv_of[h]] as usize
                })
                .collect();
            set.len()
        })
        .collect();
    let npts = f.q + 1;
    let perm: Vec<Vec<u16>> = elems
        .iter()
        .map(|&e| (0..npts).map(|pt| mact(f, e, pt) as u16).collect())
        .collect();
    let invs: Vec<usize> = (0..n).filter(|&i| ord[i] == 2).collect();
    Real {
        n,
        elems,
        mul,
        ord,
        conj,
        perm,
        ide,
        invs,
        gens: [gr, t0],
    }
}

struct ClassCensus {
    sig: Vec<usize>,
    count: usize,
    board_value: u8,
    board_direct: Option<u8>,
    per_orbit_checks: usize,
    deleted: usize,
}

struct CensusRow {
    gname: String,
    q: usize,
    p: usize,
    k: usize,
    field: String,
    pgl2_order: usize,
    n_involutions: usize,
    normalizer_order: usize,
    subgroup_count: usize,
    orbit_size_stab: Vec<(usize, usize)>,
    eps: Vec<(String, usize)>,
    m1: usize,
    classes: Vec<ClassCensus>,
    triples: usize,
    per_orbit_checks: usize,
    per_orbit_mismatches: usize,
    board_direct_checks: usize,
    board_direct_mismatches: usize,
}

#[allow(clippy::too_many_arguments)]
fn census_group(
    f: &Fq,
    gname: &str,
    trow: &HashMap<(String, Vec<usize>, usize), TemplateRow>,
    tk: &HashMap<(String, Vec<usize>, usize), u8>,
    cited_a5_t1: &BTreeMap<Vec<usize>, u8>,
    class_counts: &BTreeMap<Vec<usize>, usize>,
) -> CensusRow {
    let target = if gname == "S4" { 24 } else { 60 };
    let g = find_realization(f, gname);
    let n = g.n;
    let npts = f.q + 1;

    // ---- orbits and stabilizers (orbit-stabilizer identity asserted) ----
    let mut orbit_of = vec![usize::MAX; npts];
    let mut orbits: Vec<Vec<usize>> = Vec::new();
    for s in 0..npts {
        if orbit_of[s] != usize::MAX {
            continue;
        }
        let oid = orbits.len();
        let mut stack = vec![s];
        orbit_of[s] = oid;
        let mut orb = Vec::new();
        while let Some(x) = stack.pop() {
            orb.push(x);
            for e in 0..n {
                let y = g.perm[e][x] as usize;
                if orbit_of[y] == usize::MAX {
                    orbit_of[y] = oid;
                    stack.push(y);
                }
            }
        }
        orb.sort();
        orbits.push(orb);
    }
    let mut orbit_stab: Vec<usize> = Vec::new();
    for orb in &orbits {
        let base = orb[0];
        let fixers: Vec<usize> = (0..n).filter(|&e| g.perm[e][base] as usize == base).collect();
        let stab = fixers.len();
        // orbit-stabilizer identity, computed independently on both sides
        assert_eq!(orb.len() * stab, target, "orbit-stabilizer identity failed");
        // stabilizer must be cyclic of allowed order
        let allowed: &[usize] = if gname == "S4" { &[1, 2, 3, 4] } else { &[1, 2, 3, 5] };
        assert!(allowed.contains(&stab));
        if stab > 1 {
            assert!(
                fixers.iter().any(|&e| g.ord[e] == stab),
                "point stabilizer not cyclic"
            );
        }
        if gname == "S4" && stab == 2 {
            // stabilizer generator must be a transposition (6 conjugates), not C2b
            let t = fixers.iter().find(|&&e| g.ord[e] == 2).unwrap();
            assert_eq!(g.conj[*t], 6, "order-2 point stabilizer is not C2a");
        }
        orbit_stab.push(stab);
    }
    let mut orbit_size_stab: Vec<(usize, usize)> = orbits
        .iter()
        .zip(orbit_stab.iter())
        .map(|(o, &s)| (o.len(), s))
        .collect();
    orbit_size_stab.sort();

    // ---- split indicators from explicit class representatives ----
    let fixcount = |e: usize| -> usize {
        (0..npts).filter(|&pt| g.perm[e][pt] as usize == pt).count()
    };
    let pick = |o: usize, cj: Option<usize>| -> usize {
        (0..n)
            .find(|&e| g.ord[e] == o && cj.map_or(true, |c| g.conj[e] == c))
            .unwrap()
    };
    let eps_of = |e: usize| -> usize {
        let fc = fixcount(e);
        assert!(fc == 0 || fc == 2, "semisimple element with odd fixed count");
        if fc == 2 {
            1
        } else {
            0
        }
    };
    let eps: Vec<(String, usize)>;
    let mut expected: Vec<(usize, usize)> = Vec::new();
    if gname == "S4" {
        let e2a = eps_of(pick(2, Some(6)));
        let e2b = eps_of(pick(2, Some(3)));
        let e3 = eps_of(pick(3, None));
        let e4 = eps_of(pick(4, None));
        // C2b never yields its own orbit type: split C2b forces split C4 and its
        // fixed points carry full C4 stabilizers (C284 completeness remark).
        if e2b == 1 {
            assert_eq!(e4, 1);
            let c2b = pick(2, Some(3));
            for pt in 0..npts {
                if g.perm[c2b][pt] as usize == pt {
                    let stab = (0..n).filter(|&e| g.perm[e][pt] as usize == pt).count();
                    assert_eq!(stab, 4);
                }
            }
        }
        if e2a == 1 {
            expected.push((12, 2));
        }
        if e3 == 1 {
            expected.push((8, 3));
        }
        if e4 == 1 {
            expected.push((6, 4));
        }
        eps = vec![
            ("e2a".to_string(), e2a),
            ("e2b".to_string(), e2b),
            ("e3".to_string(), e3),
            ("e4".to_string(), e4),
        ];
    } else {
        let e2 = eps_of(pick(2, None));
        let e3 = eps_of(pick(3, None));
        let e5 = eps_of(pick(5, None));
        if e2 == 1 {
            expected.push((30, 2));
        }
        if e3 == 1 {
            expected.push((20, 3));
        }
        if e5 == 1 {
            expected.push((12, 5));
        }
        eps = vec![
            ("e2".to_string(), e2),
            ("e3".to_string(), e3),
            ("e5".to_string(), e5),
        ];
    }
    // fixed-point double count: exceptional orbits are exactly the split types
    let exceptional: usize = expected.iter().map(|(s, _)| s).sum();
    assert_eq!((npts - exceptional) % target, 0, "free-orbit count not integral");
    let m1 = (npts - exceptional) / target;
    for _ in 0..m1 {
        expected.push((target, 1));
    }
    expected.sort();
    assert_eq!(expected, orbit_size_stab, "orbit multiset != split-indicator prediction");

    // ---- normalizer over all of PGL_2(q) ----
    let gset: HashSet<M> = g.elems.iter().cloned().collect();
    let mut norm_count = 0usize;
    let pgl2_order = for_each_pgl2(f, |x| {
        let xi = minv(f, x);
        let c0 = mmul(f, mmul(f, x, g.gens[0]), xi);
        if gset.contains(&c0) {
            let c1 = mmul(f, mmul(f, x, g.gens[1]), xi);
            if gset.contains(&c1) {
                norm_count += 1;
            }
        }
    });
    assert_eq!(norm_count, target, "N(G) != G");
    assert_eq!(pgl2_order % norm_count, 0);
    let subgroup_count = pgl2_order / norm_count;

    // ---- per-triple census ----
    let mut classes: BTreeMap<Vec<usize>, ClassCensus> = BTreeMap::new();
    let mut triples = 0usize;
    let mut per_orbit_checks_total = 0usize;
    let mut per_orbit_mismatches = 0usize;
    let mut board_direct_checks = 0usize;
    let mut board_direct_mismatches = 0usize;
    let ni = g.invs.len();
    for a in 0..ni {
        for b in (a + 1)..ni {
            for c in (b + 1)..ni {
                let (ia, ib, ic) = (g.invs[a], g.invs[b], g.invs[c]);
                // subgroup closure via index bitmask BFS (n <= 60)
                let mut mask = 1u64 << g.ide;
                let mut stack = vec![g.ide];
                while let Some(x) = stack.pop() {
                    for &t in &[ia, ib, ic] {
                        let y = g.mul[x * n + t] as usize;
                        if mask & (1u64 << y) == 0 {
                            mask |= 1u64 << y;
                            stack.push(y);
                        }
                    }
                }
                if mask.count_ones() as usize != n {
                    continue;
                }
                triples += 1;
                let pp = [
                    g.mul[ia * n + ib] as usize,
                    g.mul[ia * n + ic] as usize,
                    g.mul[ib * n + ic] as usize,
                ];
                let mut sig = vec![g.ord[pp[0]], g.ord[pp[1]], g.ord[pp[2]]];
                sig.sort();
                let tp = |x: usize, y: usize, z: usize| -> usize {
                    g.ord[g.mul[(g.mul[x * n + y] as usize) * n + z] as usize]
                };
                let mut t6 = vec![
                    tp(ia, ib, ic),
                    tp(ia, ic, ib),
                    tp(ib, ia, ic),
                    tp(ib, ic, ia),
                    tp(ic, ia, ib),
                    tp(ic, ib, ia),
                ];
                t6.sort();
                assert!(t6.iter().all(|&x| x == t6[0]), "rho not constant on triple");
                sig.push(0);
                sig.extend(t6.iter());

                // deletion set = rational fixed points of the three pair products
                let mut alive = vec![true; npts];
                let mut deleted = 0usize;
                for &h in &pp {
                    let fc = (0..npts).filter(|&pt| g.perm[h][pt] as usize == pt).count();
                    assert!(fc == 0 || fc == 2);
                    for pt in 0..npts {
                        if g.perm[h][pt] as usize == pt && alive[pt] {
                            alive[pt] = false;
                            deleted += 1;
                        }
                    }
                }

                // per-orbit residual values
                let mut board = 0u8;
                let mut per_orbit_checks = 0usize;
                for (oid, orb) in orbits.iter().enumerate() {
                    let stab = orbit_stab[oid];
                    if stab == 1 {
                        // free orbit: no deletions, 3-regular Schreier graph = Cay(G,T)
                        for &pt in orb {
                            assert!(alive[pt], "deletion inside free orbit");
                            let nbrs: BTreeSet<usize> = [ia, ib, ic]
                                .iter()
                                .map(|&t| g.perm[t][pt] as usize)
                                .collect();
                            assert_eq!(nbrs.len(), 3, "free orbit not 3-regular");
                            assert!(!nbrs.contains(&pt));
                        }
                        let t1 = if gname == "S4" {
                            *tk.get(&("S4".to_string(), sig.clone(), 1)).unwrap()
                        } else {
                            *cited_a5_t1.get(&sig[..3].to_vec()).unwrap()
                        };
                        board ^= t1;
                        continue;
                    }
                    // exceptional orbit: build local residual graph, direct nimber
                    let local: HashMap<usize, usize> =
                        orb.iter().enumerate().map(|(i, &pt)| (pt, i)).collect();
                    let vc = orb.len();
                    assert!(vc <= 62);
                    let mut adj = vec![0u64; vc];
                    let mut am = 0u64;
                    for &pt in orb {
                        if !alive[pt] {
                            continue;
                        }
                        let lv = local[&pt];
                        am |= 1u64 << lv;
                        for &t in &[ia, ib, ic] {
                            let y = g.perm[t][pt] as usize;
                            if y != pt && alive[y] {
                                let lw = local[&y];
                                adj[lv] |= 1u64 << lw;
                                adj[lw] |= 1u64 << lv;
                            }
                        }
                    }
                    let del_in_orbit = vc - am.count_ones() as usize;
                    let closed: Vec<u64> = (0..vc).map(|v| adj[v] | (1u64 << v)).collect();
                    let mut memo: HashMap<u64, u8> = HashMap::new();
                    let nim = grundy_plain(am, &adj, &closed, &mut memo);
                    let row = trow
                        .get(&(gname.to_string(), sig.clone(), stab))
                        .unwrap_or_else(|| panic!("missing template {} {:?} {}", gname, sig, stab));
                    let mut comps = Vec::new();
                    let mut rem = am;
                    while rem != 0 {
                        let start = rem & rem.wrapping_neg();
                        let comp = component(rem, start, &adj);
                        comps.push(comp.count_ones() as usize);
                        rem &= !comp;
                    }
                    comps.sort();
                    per_orbit_checks += 1;
                    if nim != row.nimber
                        || del_in_orbit != row.deleted
                        || (vc - del_in_orbit) != row.residual_vertices
                        || comps != row.components
                    {
                        per_orbit_mismatches += 1;
                    }
                    board ^= nim;
                }
                per_orbit_checks_total += per_orbit_checks;

                // whole-board direct replay when it fits
                if npts <= 63 {
                    let mut adj = vec![0u64; npts];
                    let mut am = 0u64;
                    for pt in 0..npts {
                        if !alive[pt] {
                            continue;
                        }
                        am |= 1u64 << pt;
                        for &t in &[ia, ib, ic] {
                            let y = g.perm[t][pt] as usize;
                            if y != pt && alive[y] {
                                adj[pt] |= 1u64 << y;
                                adj[y] |= 1u64 << pt;
                            }
                        }
                    }
                    let mut biggest = 0usize;
                    let mut rem = am;
                    while rem != 0 {
                        let start = rem & rem.wrapping_neg();
                        let comp = component(rem, start, &adj);
                        biggest = biggest.max(comp.count_ones() as usize);
                        rem &= !comp;
                    }
                    if biggest <= 40 {
                        let closed: Vec<u64> = (0..npts).map(|v| adj[v] | (1u64 << v)).collect();
                        let mut memo: HashMap<u64, u8> = HashMap::new();
                        let direct = grundy_plain(am, &adj, &closed, &mut memo);
                        board_direct_checks += 1;
                        if direct != board {
                            board_direct_mismatches += 1;
                        }
                        let e = classes.entry(sig.clone()).or_insert(ClassCensus {
                            sig: sig.clone(),
                            count: 0,
                            board_value: board,
                            board_direct: Some(direct),
                            per_orbit_checks: 0,
                            deleted,
                        });
                        e.board_direct = Some(direct);
                    }
                }
                let e = classes.entry(sig.clone()).or_insert(ClassCensus {
                    sig: sig.clone(),
                    count: 0,
                    board_value: board,
                    board_direct: None,
                    per_orbit_checks: 0,
                    deleted,
                });
                e.count += 1;
                e.per_orbit_checks += per_orbit_checks;
                assert_eq!(e.board_value, board, "board value not constant on class");
                assert_eq!(e.deleted, deleted, "deletion count not constant on class");
            }
        }
    }
    // class histogram must equal the abstract Aut(G)-orbit census
    assert_eq!(
        triples,
        class_counts.values().sum::<usize>(),
        "generating-triple total mismatch"
    );
    for (sig, cc) in &classes {
        assert_eq!(cc.count, class_counts[sig], "class size mismatch");
    }
    assert_eq!(classes.len(), class_counts.len());

    CensusRow {
        gname: gname.to_string(),
        q: f.q,
        p: f.p,
        k: f.k,
        field: f.poly.clone(),
        pgl2_order,
        n_involutions: f.q * f.q,
        normalizer_order: norm_count,
        subgroup_count,
        orbit_size_stab,
        eps,
        m1,
        classes: classes.into_values().collect(),
        triples,
        per_orbit_checks: per_orbit_checks_total,
        per_orbit_mismatches,
        board_direct_checks,
        board_direct_mismatches,
    }
}

// ----------------------------------------------------------------------------
// Brute-force spot check: every involution triple, every subgroup, conjugacy
// classes by union-find under PGL_2(q)-conjugation.  Independent of Dickson.
// ----------------------------------------------------------------------------

struct SpotRow {
    gname: String,
    q: usize,
    generating_triples: usize,
    subgroups: usize,
    pgl2_order: usize,
    conjugacy_classes: usize,
}

fn spot_check(f: &Fq, gname: &str) -> SpotRow {
    let (target, allowed, per_group): (usize, &[usize], usize) = match gname {
        "S4" => (24, &[2, 3, 4], 52),
        "A5" => (60, &[2, 3, 5], 380),
        _ => unreachable!(),
    };
    let invs = involutions(f);
    let ni = invs.len();
    let mut pord = vec![0u8; ni * ni];
    for i in 0..ni {
        for j in (i + 1)..ni {
            let o = morder(f, mmul(f, invs[i], invs[j]));
            let v = if allowed.contains(&o) { o as u8 } else { 0 };
            pord[i * ni + j] = v;
            pord[j * ni + i] = v;
        }
    }
    let mut subgroup_ids: HashMap<Vec<M>, usize> = HashMap::new();
    let mut keys: Vec<Vec<M>> = Vec::new();
    let mut gen_triples = 0usize;
    for i in 0..ni {
        for j in (i + 1)..ni {
            if pord[i * ni + j] == 0 {
                continue;
            }
            for k in (j + 1)..ni {
                if pord[i * ni + k] == 0 || pord[j * ni + k] == 0 {
                    continue;
                }
                let cl = closure_mat(f, &[invs[i], invs[j], invs[k]], target + 4);
                if cl.len() == target {
                    assert!(signature_ok(f, &cl, gname), "order-{} closure not {}", target, gname);
                    gen_triples += 1;
                    if !subgroup_ids.contains_key(&cl) {
                        subgroup_ids.insert(cl.clone(), keys.len());
                        keys.push(cl);
                    }
                }
            }
        }
    }
    assert_eq!(gen_triples % per_group, 0);
    let n_sub = gen_triples / per_group;
    assert_eq!(n_sub, keys.len(), "triple count / {} != distinct subgroups", per_group);

    // union-find under conjugation by PGL_2(q) generators T, S, D
    let gprim = (1..f.q).find(|&x| f.mul_order(x) == f.q - 1).unwrap();
    let pgens: [M; 3] = [[1, 1, 0, 1], [0, 1, 1, 0], [gprim, 0, 0, 1]];
    let mut parent: Vec<usize> = (0..keys.len()).collect();
    fn root(parent: &mut Vec<usize>, mut x: usize) -> usize {
        while parent[x] != x {
            parent[x] = parent[parent[x]];
            x = parent[x];
        }
        x
    }
    for si in 0..keys.len() {
        for &pg in &pgens {
            let pgi = minv(f, pg);
            let mut img: Vec<M> = keys[si]
                .iter()
                .map(|&e| mmul(f, mmul(f, pg, e), pgi))
                .collect();
            img.sort();
            let sj = *subgroup_ids
                .get(&img)
                .expect("conjugate subgroup missing from exhaustive census");
            let (ri, rj) = (root(&mut parent, si), root(&mut parent, sj));
            if ri != rj {
                parent[ri] = rj;
            }
        }
    }
    let classes: BTreeSet<usize> = (0..keys.len()).map(|x| root(&mut parent, x)).collect();
    SpotRow {
        gname: gname.to_string(),
        q: f.q,
        generating_triples: gen_triples,
        subgroups: n_sub,
        pgl2_order: f.q * f.q * f.q - f.q,
        conjugacy_classes: classes.len(),
    }
}

