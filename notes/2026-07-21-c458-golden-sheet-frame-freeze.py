def qcoord_str(x):
    a, b = x
    if b == 0:
        return str(a)
    if a == 0:
        return f"{b}*phi"
    sign = "+" if b > 0 else "-"
    mag = abs(b)
    return f"{a}{sign}{mag}*phi"


def vec_strs(v):
    return [qcoord_str(x) for x in v]


def six_arc_canonical(q_six, tau):
    return sorted((vec_strs(v) for v in q_six(tau)), key=lambda s: tuple(s))


def legendre(a, p):
    r = pow(a % p, (p - 1) // 2, p)
    return -1 if r == p - 1 else r


def qcross(m2, u, v):
    """Cross product of two Q(phi) 3-vectors, using the frozen M2 Q(phi) arithmetic."""
    return (m2.qsub(m2.qmul(u[1], v[2]), m2.qmul(u[2], v[1])),
            m2.qsub(m2.qmul(u[2], v[0]), m2.qmul(u[0], v[2])),
            m2.qsub(m2.qmul(u[0], v[1]), m2.qmul(u[1], v[0])))


def all_axes_pairwise_anisotropic(m2):
    """The 12 axes of the golden + conjugate six-arcs are pairwise in general position over Q(phi):
    every cross-product v x w of distinct axes is anisotropic ((v x w).(v x w) != 0), so the two
    char-0 six-point arcs are genuinely disjoint (F2, C458/M0-addendum Fable review)."""
    from itertools import combinations
    axes = sorted(m2.q_six(m2.QPHI)) + sorted(m2.q_six(m2.QPHIBAR))
    pairs = list(combinations(axes, 2))
    ok = all(m2.qdot(qcross(m2, u, v), qcross(m2, u, v)) != m2.QZERO for (u, v) in pairs)
    return ok, len(pairs)


