detector = load_detector()
pullback = detector.pullback
base = detector.base
FIELD = detector.FIELD
A = detector.A
R = detector.R
X, Y, Z = detector.X, detector.Y, detector.Z
HALF = FIELD(_sage_const_2 ) ** -_sage_const_1 


def ordinary_contraction(left, right, order):
    """Apply the ordinary invariant contraction differential operator."""
    if not _sage_const_0  <= order < base.P:
        raise ValueError("only nonzero ordinary orders below p are tested")
    answer = R.zero()
    order_factorial = FIELD(factorial(order))
    for left_exponent, left_coefficient in left.dict().items():
        li, lj, lk = map(int, tuple(left_exponent))
        for right_exponent, right_coefficient in right.dict().items():
            ri, rj, rk = map(int, tuple(right_exponent))
            for pair_xz in range(min(li, rk, order) + _sage_const_1 ):
                for pair_yy in range(min(lj, rj, order - pair_xz) + _sage_const_1 ):
                    pair_zx = order - pair_xz - pair_yy
                    if pair_zx > min(lk, ri):
                        continue
                    coefficient = (
                        left_coefficient
                        * right_coefficient
                        * order_factorial
                        * factorial(pair_xz)
                        * factorial(pair_yy)
                        * factorial(pair_zx)
                        * comb(li, pair_xz)
                        * comb(rk, pair_xz)
                        * comb(lj, pair_yy)
                        * comb(rj, pair_yy)
                        * comb(lk, pair_zx)
                        * comb(ri, pair_zx)
                        * (-HALF) ** pair_yy
                    )
                    answer += coefficient * (
                        X ** (li + ri - pair_xz - pair_zx)
                        * Y ** (lj + rj - _sage_const_2  * pair_yy)
                        * Z ** (lk + rk - pair_xz - pair_zx)
                    )
    return answer


def retired_scalar_counterexample():
    """Return an exact translation defect for the old scalar pairing."""
    left = X**_sage_const_2  * Z**_sage_const_57 
    right = X**_sage_const_57  * Y * Z
    translated_left = left(X - _sage_const_2  * Y + Z, Y - Z, Z)
    translated_right = right(X - _sage_const_2  * Y + Z, Y - Z, Z)
    before = detector.top_pairing(left, right)
    after = detector.top_pairing(translated_left, translated_right)
    assert before == _sage_const_0 
    assert after != before
    return {
        "left_exponent": [_sage_const_2 , _sage_const_0 , _sage_const_57 ],
        "right_exponent": [_sage_const_57 , _sage_const_1 , _sage_const_1 ],
        "translation_parameter": _sage_const_1 ,
        "pairing_before": int(before),
        "pairing_after": int(after),
        "translation_defect": int(after - before),
    }


def pullback_inputs():
    group_elements = (
        (_sage_const_1 , _sage_const_1 , _sage_const_0 , _sage_const_1 ),
        (_sage_const_1 , A, _sage_const_0 , _sage_const_1 ),
        (_sage_const_0 , -_sage_const_1 , _sage_const_1 , _sage_const_0 ),
    )
    generator_data = [pullback.action_data(g) for g in group_elements]
    primitive = FIELD.multiplicative_generator()
    torus_element = (primitive, _sage_const_0 , _sage_const_0 , primitive**-_sage_const_1 )
    torus_data = pullback.action_data(torus_element)
    _, _, adjusted_cocycles = pullback.split_torus_fixed_lift(
        generator_data, torus_data
    )
    _, embedding_columns, simple_actions = pullback.embedding_polynomials()
    embedded_images = []
    for simple_action in simple_actions:
        columns = []
        for simple_column in range(base.SIMPLE_DEGREE + _sage_const_1 ):
            columns.append(
                sum(
                    (
                        simple_action[source_simple, simple_column]
                        * embedding_columns[source_simple]
                        for source_simple in range(
                            base.SIMPLE_DEGREE + _sage_const_1 
                        )
                        if simple_action[source_simple, simple_column]
                    ),
                    R.zero(),
                )
            )
        embedded_images.append(columns)
    return adjusted_cocycles, embedded_images, simple_actions


def test_order(order, adjusted_cocycles, embedded_images, simple_actions):
    defects = []
    for cocycle, image_columns in zip(adjusted_cocycles, embedded_images):
        defects.append(
            [
                ordinary_contraction(cocycle, image, order)
                for image in image_columns
            ]
        )
    nonzero_defect_columns = sum(
        bool(defect)
        for generator_defects in defects
        for defect in generator_defects
    )
    target_degree = _sage_const_2  * (base.DEGREE - order)
    if nonzero_defect_columns:
        system = detector.contraction_system(
            defects, simple_actions, target_degree
        )
    else:
        system = {
            "target_degree": target_degree,
            "target_dimension": (
                (target_degree + _sage_const_1 ) * (target_degree + _sage_const_2 ) // _sage_const_2 
            ),
            "torus_block_variables": _sage_const_0 ,
            "equations": _sage_const_0 ,
            "coefficient_rank": _sage_const_0 ,
            "augmented_rank": _sage_const_0 ,
            "solvable": True,
        }
    system["contraction_order"] = order
    system["nonzero_defect_columns"] = nonzero_defect_columns
    return system


def calculate(orders):
    adjusted_cocycles, embedded_images, simple_actions = pullback_inputs()
    channels = [
        test_order(
            order, adjusted_cocycles, embedded_images, simple_actions
        )
        for order in orders
    ]
    detecting = next(
        (record for record in channels if not record["solvable"]), None
    )
    return {
        "schema": _sage_const_1 ,
        "q": base.Q,
        "p": base.P,
        "field_modulus": str(FIELD.modulus()),
        "retired_scalar_counterexample": retired_scalar_counterexample(),
        "ordinary_contraction_orders": list(orders),
        "channels": channels,
        "detecting_contraction_order": (
            None if detecting is None else detecting["contraction_order"]
        ),
        "conclusion": (
            "a valid ordinary contraction detects the q=121 pullback"
            if detecting is not None
            else "the checked valid ordinary contractions are blind"
        ),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--orders",
        default="1-10",
        help="comma-separated orders or one inclusive range such as 1-10",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if "-" in args.orders and "," not in args.orders:
        start, stop = map(int, args.orders.split("-", _sage_const_1 ))
        orders = tuple(range(start, stop + _sage_const_1 ))
    else:
        orders = tuple(int(value) for value in args.orders.split(","))
    if not orders or any(order < _sage_const_1  or order >= base.P for order in orders):
        raise ValueError("orders must lie between 1 and p-1")
    result = calculate(orders)
    encoded = json.dumps(result, default=int, indent=_sage_const_2 , sort_keys=True) + "\n"
    if args.write:
        CERTIFICATE.write_text(encoded)
        print(f"wrote {CERTIFICATE.name}")
    elif args.check:
        assert CERTIFICATE.read_text() == encoded
        print(f"checked {CERTIFICATE.name}")
    else:
        print(encoded, end="")


if __name__ == "__main__":
    main()

