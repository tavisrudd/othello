"""Audit the retired q=121 Hasse detector and test valid contractions.

The former C665 detector used divided/Hasse contractions all the way to
order 59.  Those maps do not descend equivariantly from ordinary symmetric
powers in characteristic 11.  This checker first records a one-pair
translation counterexample to its scalar channel.

It then tests only the genuine ordinary contraction maps

    C_r : Sym^2(Sym^59(L(2))) -> Sym^(118-2r)(L(2)),

for 1 <= r < 11.  These are obtained by applying the r-th power of the
invariant contraction differential operator.  The factorial coefficients
are essential; at r >= 11 the ordinary operator is zero.
"""


