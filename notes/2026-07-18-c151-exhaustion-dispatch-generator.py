#!/usr/bin/env python3
"""Generate bounded dispatchers for the C151 per-row exhaustion disjunctions.

Mirrors `2026-07-17-c151-residual-conclusion-dispatch-generator.py` at threshold 33.  The terminal
`concludeNormalizedRowExhaustion` states, for every normalized row containing orbit number 5, that
the row either carries at least 33 legal orbits or is one of the five certified minimizer classes.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import sys
from pathlib import Path
from typing import Sequence


HERE = Path(__file__).resolve().parent
CONCLUSION_GENERATOR = HERE / "2026-07-18-c151-exhaustion-conclusion-generator.py"
EXPECTED_ROWS = 46_056
EXPECTED_B_VALUES = 303


def load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


conclusion = load(CONCLUSION_GENERATOR, "c151_exhaustion_conclusion_generator")
transport = conclusion.transport
strict = conclusion.strict


def source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def generated_header(csv_hash: str, description: str) -> str:
    return f"""/-!
# Generated C151 exhaustion dispatcher

DO NOT EDIT: generated by `notes/2026-07-18-c151-exhaustion-dispatch-generator.py`.

* payload: {description}
* canonical CSV SHA256: `{csv_hash}`
* exhaustion-conclusion generator SHA256: `{conclusion.source_sha256()}`
* exhaustion-dispatch generator SHA256: `{source_sha256()}`
-/
"""


def render_b_dispatcher(b: int, payloads: Sequence[object], csv_hash: str) -> str:
    imports = "".join(
        "import RelativeConicArcs.Q25ExhaustionConclusionData."
        f"{conclusion.conclusion_module_name(payload)}\n"
        for payload in payloads
    )
    row_locations = {
        row.c: (payload.module_name, index)
        for payload in payloads
        for index, row in enumerate(payload.records)
    }
    assert set(row_locations) == set(range(b + 1, 310))
    branches = []
    for c in range(310):
        if c <= b:
            branches.append("  · simp at hbc\n")
        else:
            module_name, index = row_locations[c]
            branches.append(
                f"  · exact concludeExh{module_name} ⟨{index}, by decide⟩ hraw\n"
            )
    return imports + f"""
{generated_header(csv_hash, f"all per-row exhaustion disjunctions with b = {b}")}

namespace RelativeConicArcs
namespace Q25ExhaustionDispatchData

open Q25Coordinates Q25MinimumMask Q25ResidualCoverData Q25ResidualEquality
  Q25ExhaustionConclusionData

set_option maxHeartbeats 300000000
set_option maxRecDepth 100000

theorem concludeExhB_{b:03d} (c : Fin 310) (hbc : {b} < c.val)
    (hraw : RawCap (rowConfig ⟨{b}, by decide⟩ c)) :
    33 ≤ (legalOrbitSet (rowConfig ⟨{b}, by decide⟩ c)).card ∨
      IsMinimumResidualClass (rowConfig ⟨{b}, by decide⟩ c) := by
  fin_cases c
{"".join(branches)}
end Q25ExhaustionDispatchData
end RelativeConicArcs
"""


def render_all(csv_hash: str) -> str:
    imports = "".join(
        f"import RelativeConicArcs.Q25ExhaustionDispatchData.B_{b:03d}\n"
        for b in range(6, 309)
    )
    branches = []
    for b in range(310):
        if b < 6:
            branches.append("  · simp at hb hbc\n")
        elif b == 309:
            branches.append(
                "  · have hbc' : 309 < c.val := by simpa using hbc\n"
                "    omega\n"
            )
        else:
            branches.append(f"  · exact concludeExhB_{b:03d} c hbc hraw\n")
    return imports + f"""
{generated_header(csv_hash, "universal exhaustion disjunction for all 46,056 normalized rows")}

namespace RelativeConicArcs
namespace Q25ExhaustionDispatchData

open Q25Coordinates Q25MinimumMask Q25ResidualCoverData Q25ResidualEquality

set_option maxHeartbeats 300000000
set_option maxRecDepth 100000

/-- Every raw normalized row containing orbit number `5` either carries at least `33` legal orbits
or is one of the five certified minimizer classes. -/
theorem concludeNormalizedRowExhaustion (b c : Fin 310) (hb : 5 < b.val) (hbc : b.val < c.val)
    (hraw : RawCap (rowConfig b c)) :
    33 ≤ (legalOrbitSet (rowConfig b c)).card ∨ IsMinimumResidualClass (rowConfig b c) := by
  fin_cases b
{"".join(branches)}
end Q25ExhaustionDispatchData
end RelativeConicArcs
"""


def write_modules(output_directory: Path, csv: Path) -> None:
    if output_directory.name != "Q25ExhaustionDispatchData":
        raise ValueError("output directory must be named Q25ExhaustionDispatchData")
    rows, _ = transport.cover.read_records(csv)
    assert len(rows) == EXPECTED_ROWS
    payloads = transport.payload_leaves(rows)
    csv_hash = transport.cover.sha256(csv)
    expected = {f"B_{b:03d}.lean" for b in range(6, 309)} | {"All.lean"}
    output_directory.mkdir(parents=True, exist_ok=True)
    unexpected = sorted(
        path.name for path in output_directory.iterdir() if path.name not in expected
    )
    if unexpected:
        raise RuntimeError(f"refusing output directory with unexpected entries: {unexpected}")

    written = []
    for b in range(6, 309):
        b_payloads = tuple(payload for payload in payloads if payload.b == b)
        path = output_directory / f"B_{b:03d}.lean"
        path.write_text(render_b_dispatcher(b, b_payloads, csv_hash), encoding="utf-8")
        written.append(path)
    all_path = output_directory / "All.lean"
    all_path.write_text(render_all(csv_hash), encoding="utf-8")
    written.append(all_path)

    assert len(written) == EXPECTED_B_VALUES + 1 == len(expected)
    print(f"generated_files={len(written)} b_dispatchers={EXPECTED_B_VALUES}")
    print(f"rows={len(rows)} generated_source_bytes={sum(p.stat().st_size for p in written)}")
    print(f"output_directory={output_directory.resolve()}")
    print(f"csv_sha256={csv_hash}")
    print(f"exhaustion_dispatch_generator_sha256={source_sha256()}")
    print(f"generated_tree_sha256={strict.tree_sha256(written, output_directory)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path)
    parser.add_argument("--write-lean-modules", required=True, type=Path)
    args = parser.parse_args()
    write_modules(args.write_lean_modules, args.csv)


if __name__ == "__main__":
    main()
