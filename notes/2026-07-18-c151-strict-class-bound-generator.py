#!/usr/bin/env python3
"""Generate C151 strict canonical-class bounds for the exhaustion layer.

Every committed class certificate in `Q25RowCompositionData` pins its `card_le` field at `32`, but
its `fresh`, `secants`, and `carrier` fields are threshold-free.  `card_legalOrbitSet_ge_of_sound`
(in `Q25ExhaustionBridge`) therefore reuses the committed `ReflectedMaskCertificate.sound` field at
any threshold, against a fresh cardinality `decide` on the same literal mask.

This generator emits `33 <= (legalOrbitSet (normalizedConfig ...)).card` for every canonical class
whose committed mask already carries at least 33 orbit codes -- that is, every class except the five
certified minimizers.  It reads only tracked Lean sources and edits nothing under
`Q25MinimumMask` or `Q25RowCompositionData`, so the generated `>= 32` closure stays valid.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import sys
from pathlib import Path
from typing import Sequence


HERE = Path(__file__).resolve().parent
SPECTRUM_SCRIPT = HERE / "2026-07-18-c151-minimum-mask-spectrum.py"
EXPECTED_CLASSES = 1189
MINIMUM_CARD = 32
STRICT_CARD = 33
MINIMIZER_CLASSES = (65, 267, 445, 772, 1002)
CLASSES_PER_MODULE = 5


def load_spectrum():
    spec = importlib.util.spec_from_file_location(
        "c151_minimum_mask_spectrum", SPECTRUM_SCRIPT
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


spectrum = load_spectrum()


def source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def tree_sha256(files: Sequence[Path], root: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(files):
        relative = path.relative_to(root).as_posix().encode()
        contents = path.read_bytes()
        digest.update(len(relative).to_bytes(4, "big"))
        digest.update(relative)
        digest.update(len(contents).to_bytes(8, "big"))
        digest.update(contents)
    return digest.hexdigest()


def class_module_name(index: int) -> str:
    first = index // CLASSES_PER_MODULE * CLASSES_PER_MODULE
    last = min(first + CLASSES_PER_MODULE - 1, EXPECTED_CLASSES - 1)
    return f"C_{first:04d}_{last:04d}"


def read_mask_cardinalities(composition_root: Path) -> dict[int, int]:
    """Mask popcount per canonical class, parsed from the tracked composition sources."""
    masks = spectrum.parse_masks(composition_root)
    if set(masks) != set(range(EXPECTED_CLASSES)):
        raise RuntimeError("composition sources do not cover exactly classes 0..1188")
    cards = {index: spectrum.popcount(words) for index, words in masks.items()}
    below = sorted(index for index, card in cards.items() if card < MINIMUM_CARD)
    if below:
        raise RuntimeError(f"classes below the certified minimum {MINIMUM_CARD}: {below}")
    minimizers = tuple(sorted(i for i, card in cards.items() if card == MINIMUM_CARD))
    if minimizers != MINIMIZER_CLASSES:
        raise RuntimeError(
            f"minimizer set drifted: expected {MINIMIZER_CLASSES}, parsed {minimizers}"
        )
    return cards


def generated_header(mask_digest: str, description: str) -> str:
    return f"""/-!
# Generated C151 strict canonical-class bounds

DO NOT EDIT: generated by `notes/2026-07-18-c151-strict-class-bound-generator.py`.

* payload: {description}
* mask-stream digest: `{mask_digest}`
* spectrum-script SHA256: `{spectrum.sha256_file(SPECTRUM_SCRIPT)}`
* strict-bound generator SHA256: `{source_sha256()}`
-/
"""


def render_class(index: int) -> str:
    name = f"class{index:04d}"
    return f"""theorem {name}LegalOrbitSet_card_ge_{STRICT_CARD} :
    {STRICT_CARD} ≤ (legalOrbitSet
      (normalizedConfig {name}A {name}B {name}C)).card :=
  Q25ExhaustionBridge.card_legalOrbitSet_ge_of_sound
    (normalizedConfig_isConjInvariant {name}A {name}B {name}C)
    {name}ReflectedMaskCertificate.sound
    (by decide)

"""


def render_leaf(module: str, indices: Sequence[int], mask_digest: str) -> str:
    first, last = indices[0], indices[-1]
    pieces = [
        f"import RelativeConicArcs.Q25RowCompositionData.{module}\n",
        "import RelativeConicArcs.Q25ExhaustionBridge\n",
        "\n",
        generated_header(
            mask_digest,
            f"strict bounds for canonical classes {first} through {last}",
        ),
        "\nnamespace RelativeConicArcs\n",
        "namespace Q25RowCompositionStrictData\n\n",
        "open Q25Coordinates Q25PairCertificate Q25MinimumMask Q25RowCompositionData\n\n",
        "set_option maxHeartbeats 300000000\n",
        "set_option maxRecDepth 100000\n\n",
    ]
    pieces.extend(render_class(index) for index in indices)
    pieces.extend(
        [
            "end Q25RowCompositionStrictData\n",
            "end RelativeConicArcs\n",
        ]
    )
    return "".join(pieces)


def render_aggregate(modules: Sequence[str], mask_digest: str, description: str) -> str:
    imports = "".join(
        f"import RelativeConicArcs.Q25RowCompositionStrictData.{name}\n" for name in modules
    )
    return imports + "\n" + generated_header(mask_digest, description)


def write_modules(output_directory: Path, composition_root: Path) -> None:
    if output_directory.name != "Q25RowCompositionStrictData":
        raise ValueError("output directory must be named Q25RowCompositionStrictData")
    cards = read_mask_cardinalities(composition_root)
    mask_digest = spectrum.mask_stream_digest(spectrum.parse_masks(composition_root))

    strict = [index for index in range(EXPECTED_CLASSES) if cards[index] >= STRICT_CARD]
    assert len(strict) == EXPECTED_CLASSES - len(MINIMIZER_CLASSES)
    by_module: dict[str, list[int]] = {}
    for index in strict:
        by_module.setdefault(class_module_name(index), []).append(index)
    module_names = sorted(by_module)

    expected = {f"{name}.lean" for name in module_names} | {"All.lean"}
    output_directory.mkdir(parents=True, exist_ok=True)
    unexpected = sorted(
        path.name for path in output_directory.iterdir() if path.name not in expected
    )
    if unexpected:
        raise RuntimeError(f"refusing output directory with unexpected entries: {unexpected}")

    written = []
    for name in module_names:
        path = output_directory / f"{name}.lean"
        path.write_text(render_leaf(name, by_module[name], mask_digest), encoding="utf-8")
        written.append(path)

    all_path = output_directory / "All.lean"
    all_path.write_text(
        render_aggregate(
            module_names,
            mask_digest,
            f"import-only aggregate for all {len(strict)} strict canonical-class bounds",
        ),
        encoding="utf-8",
    )
    written.append(all_path)

    assert len(written) == len(expected)
    print(f"generated_files={len(written)} strict_modules={len(module_names)}")
    print(f"strict_classes={len(strict)} minimizer_classes={list(MINIMIZER_CLASSES)}")
    print(f"mask_card_min_strict={min(cards[i] for i in strict)}")
    print(f"mask_card_max={max(cards.values())}")
    print(f"generated_source_bytes={sum(path.stat().st_size for path in written)}")
    print(f"output_directory={output_directory.resolve()}")
    print(f"mask_stream_digest={mask_digest}")
    print(f"strict_generator_sha256={source_sha256()}")
    print(f"generated_tree_sha256={tree_sha256(written, output_directory)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--composition-root",
        type=Path,
        default=Path("lean/RelativeConicArcs/Q25RowCompositionData"),
    )
    parser.add_argument("--write-lean-modules", required=True, type=Path)
    args = parser.parse_args()
    write_modules(args.write_lean_modules, args.composition_root)


if __name__ == "__main__":
    main()
