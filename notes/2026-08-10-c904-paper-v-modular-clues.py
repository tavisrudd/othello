#!/usr/bin/env python3
"""Exact bounded clues for the Paper-V modular upgrade search.

The script has two independent parts:

1. rational projector identities for the six axes of the augmentation
   representation of a six-point A5-action;
2. direct F_11 point counts for every member of the certified Paper-V cubic
   pencil, using the committed coefficient certificate.

It does not prove smoothness over an algebraic closure, identify a modular
curve, or prove an intermediate-Jacobian decomposition.
"""

from fractions import Fraction
import itertools
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CERTIFICATE = (
    ROOT
    / "papers/clebsch-round-trip/verification/evidence/paper_ii_chordal_axis.json"
)
Q = 11


def matmul(left, right):
    return [
        [sum(left[i][k] * right[k][j] for k in range(len(right)))
         for j in range(len(right[0]))]
        for i in range(len(left))
    ]


def matscale(scalar, matrix):
    return [[scalar * value for value in row] for row in matrix]


def matadd(matrices):
    return [
        [sum(matrix[i][j] for matrix in matrices)
         for j in range(len(matrices[0][0]))]
        for i in range(len(matrices[0]))
    ]


def projector_on_root_basis(axis):
    """Matrix of P_axis on e_0-e_5,...,e_4-e_5."""
    matrix = [[Fraction(0) for _ in range(5)] for _ in range(5)]
    for column in range(5):
        coordinate = Fraction(1 if axis == column else (-1 if axis == 5 else 0))
        for row in range(5):
            vector_coordinate = Fraction(5 if row == axis else -1, 5) if axis < 5 else Fraction(-1, 5)
            matrix[row][column] = coordinate * vector_coordinate
    return matrix


def projector_checks():
    projectors = [projector_on_root_basis(axis) for axis in range(6)]
    identity = [[Fraction(i == j) for j in range(5)] for i in range(5)]
    zero = [[Fraction(0) for _ in range(5)] for _ in range(5)]
    assert all(matmul(projector, projector) == projector for projector in projectors)
    assert matadd(projectors) == matscale(Fraction(6, 5), identity)
    for i, left in enumerate(projectors):
        for j, right in enumerate(projectors):
            if i != j:
                assert matmul(matmul(left, right), left) == matscale(Fraction(1, 25), left)

    integral_norms = [matscale(5, projector) for projector in projectors]
    assert all(all(value.denominator == 1 for row in norm for value in row)
               for norm in integral_norms)
    assert any(value.denominator == 5 for projector in projectors
               for row in projector for value in row)
    assert matadd(integral_norms) == matscale(6, identity)
    for i, left in enumerate(integral_norms):
        for j, right in enumerate(integral_norms):
            if i != j:
                assert matmul(matmul(left, right), left) == left

    gram = [[5 if i == j else -1 for j in range(6)] for i in range(6)]
    assert all(sum(row) == 0 for row in gram)
    print("axis projectors: sum(P_i)=6/5 I; P_i P_j P_i=1/25 P_i")
    print("integral norms: minimal common multiplier 5; sum(5P_i)=6I")
    print("axis Gram: diagonal 5, off-diagonal -1, radical generated by all-ones")


def projective_points(field_order, dimension):
    for first in range(dimension):
        for tail in itertools.product(range(field_order), repeat=dimension - first - 1):
            yield [0] * first + [1] + list(tail)


def evaluate_cubic(coefficients, basis, point):
    return sum(
        coefficient * point[i] * point[j] * point[k]
        for coefficient, (i, j, k) in zip(coefficients, basis)
    ) % Q


def point_count_checks():
    data = json.loads(CERTIFICATE.read_text())
    conference = data["conference_triangle_cubic"]
    chordal = data["projected_sheet_cubic"]
    basis = list(itertools.combinations_with_replacement(range(5), 3))
    points = list(projective_points(Q, 5))
    assert len(points) == sum(Q**i for i in range(5))
    certified_singular_counts = {
        tuple(record["projective_parameter"]): record["f11_singular_point_count"]
        for record in data["invariant_pencil_singular_census"]
    }

    records = []
    for parameter in [(1, value) for value in range(Q)] + [(0, 1)]:
        a, b = parameter
        coefficients = [
            (a * c + b * h) % Q for c, h in zip(conference, chordal)
        ]
        point_count = sum(
            evaluate_cubic(coefficients, basis, point) == 0 for point in points
        )
        middle_trace = 1 + Q + Q**2 + Q**3 - point_count
        singular_count = certified_singular_counts[parameter]
        elliptic_trace_candidate = (
            middle_trace // (5 * Q) if middle_trace % (5 * Q) == 0 else None
        )
        records.append(
            (parameter, singular_count, point_count, middle_trace, elliptic_trace_candidate)
        )

    zero_rational_singular = [record for record in records if record[1] == 0]
    assert len(zero_rational_singular) == 8
    assert {record[2] for record in zero_rational_singular} == {1629}
    assert {record[3] for record in zero_rational_singular} == {-165}
    assert {record[4] for record in zero_rational_singular} == {-3}
    print("F11 pencil: parameter, rational-singular-count, #X(F11), H3 trace, a11 candidate")
    for record in records:
        print(record)
    print("zero-F11-singular parameters: 8, all #X(F11)=1629 and candidate a11=-3")

    # The Paper-V affine parameter r=b/a is related to the canonical integral
    # pencil P+tQ by t=2(r-3)/r.  Its two chordal values r=7,infinity
    # become t=-2,+2; conference r=0 becomes infinity; and the ten-point
    # member r=3 becomes t=0.
    def canonical_parameter(parameter):
        a, b = parameter
        if a == 0:
            return 2
        r = b * pow(a, -1, Q) % Q
        if r == 0:
            return None
        return 2 * (r - 3) * pow(r, -1, Q) % Q

    singular_dictionary = {
        (1, 0): None,
        (1, 3): 0,
        (1, 7): -2 % Q,
        (0, 1): 2,
    }
    assert all(canonical_parameter(parameter) == target
               for parameter, target in singular_dictionary.items())

    def elliptic_j(parameter):
        assert parameter not in (None, 0)
        square = parameter * parameter % Q
        return (
            9 * (3 * square + 1) * pow(27 * square + 1, 3, Q)
            * pow(square, -1, Q)
        ) % Q

    smooth_t = [canonical_parameter(record[0]) for record in zero_rational_singular]
    j_values = {elliptic_j(parameter) for parameter in smooth_t}
    assert j_values == {4, 10}

    def standard_elliptic_trace(j_invariant):
        denominator = (1728 - j_invariant) % Q
        coefficient_a = 3 * j_invariant * pow(denominator, -1, Q) % Q
        coefficient_b = 2 * j_invariant * pow(denominator, -1, Q) % Q
        point_count = 1
        for x_value in range(Q):
            right = (x_value**3 + coefficient_a * x_value + coefficient_b) % Q
            point_count += 1 if right == 0 else 2 if pow(right, (Q - 1) // 2, Q) == 1 else 0
        return Q + 1 - point_count

    traces = {j_invariant: standard_elliptic_trace(j_invariant) for j_invariant in j_values}
    assert traces == {4: -3, 10: -3}
    print("canonical parameter t=2(r-3)/r; smooth j-values {4,10}, both elliptic trace -3")


def main():
    projector_checks()
    point_count_checks()
    print("PASS")


if __name__ == "__main__":
    main()
